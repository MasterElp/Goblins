#pragma once

#include <cstdint>
#include <vector>

#include <nlohmann/json.hpp>

#include "core/World.hpp"

namespace goblins {

// Летопись мира: сколько клеток занимал каждый вид травы, сколько было
// особей каждого вида травоядных и хищников и каким был их средний геном
// на такой-то тик.
//
// Живёт в server, а не в core, по той же причине, что и WorldSave: это не
// закон мира и не его возможность, а наблюдение за миром — мир от неё не
// меняется и без неё живёт ровно так же (02_CorePrinciples.md, п.1: мир
// существует независимо от наблюдателя). Ядру она не нужна ни одной
// системой; нужна она тому, кто на мир смотрит.
//
// При этом ведёт её именно сервер, а не клиент: у клиента история
// обрывалась бы на каждом переподключении и начиналась бы с момента, когда
// на мир посмотрели, — то есть показывала бы время наблюдения, а не жизнь
// мира. Сервер пишет её с первого тика, независимо от того, подключён ли
// хоть кто-нибудь, и кладёт в файл сохранения вместе с самим миром.
//
// Читает ECS registry, поэтому record() вызывать только с потока GameLoop
// (как publish и saveWorld — см. NetworkServer::publish).
class PopulationHistory {
public:
    struct Point {
        std::uint64_t tick = 0;
        // Индекс в векторе — индекс вида (PlantGenomeComponent::species и
        // AnimalGenomeComponent::species). Число видов за жизнь мира не
        // меняется: новые виды появляются только генерацией, а она заводит
        // и новую летопись.
        //
        // Два вектора на животных, а не один: индекс вида у травоядных и у
        // хищников свой, и сложить их вместе значило бы смешать два разных
        // нумерования — вид 0 на графике оказался бы то травой в поле, то
        // тем, кто её ест.
        std::vector<int> plants;
        std::vector<int> trees;
        // Кусты — своим вектором по той же причине, что и деревья: у них
        // своя нумерация видов, и вид 0 на общем графике оказался бы то
        // травой, то ягодником.
        std::vector<int> bushes;
        std::vector<int> herbivores;
        std::vector<int> predators;
        // И третий вектор — гоблины по племенам. Отдельный по той же
        // причине, по которой раздельны два звериных: нумерование у племён
        // своё (GoblinTribesComponent), и сложить их с видами зверя значило
        // бы смешать два разных счёта.
        std::vector<int> goblins;

        // Средний геном всего живого этой диеты: по одному числу на черту
        // из её таблицы (kGrassTraits / herbivoreTraits / predatorTraits),
        // в тех же единицах, в каких ген живёт в самом существе.
        //
        // Среднее по ВСЕМ особям диеты, а не по видам отдельно: вопрос,
        // ради которого это записывается, — куда сносит мир целиком, а не
        // чем вид отличается от вида (это и так видно в карточке существа
        // и в архетипах). Вымирание вида здесь читается как сдвиг
        // среднего в сторону выжившего.
        //
        // Порядок — порядок таблицы черт, имена в летопись не пишутся:
        // таблица одна на весь мир и меняется только с новой сборкой
        // сервера. Клиенту имена уходят отдельно, вместе с world_init
        // (см. протокол в NetworkServer.hpp).
        std::vector<int> plantGenome;
        std::vector<int> treeGenome;
        std::vector<int> bushGenome;
        std::vector<int> herbivoreGenome;
        std::vector<int> predatorGenome;
        std::vector<int> goblinGenome;
    };

    // Шаг между точками в тиках у только что заведённой летописи. Не
    // каждый тик: численность меняется медленнее, чем идёт время, и точка
    // на тик означала бы гигабайты ради кривой, неотличимой на глаз от
    // этой.
    static constexpr std::uint64_t kBaseIntervalTicks = 10;

    // Потолок числа точек. При переполнении летопись прореживается вдвое
    // (шаг удваивается), а не теряет начало: интересна вся кривая — как
    // мир пришёл к тому, что видно сейчас, — поэтому лучше грубее, но
    // целиком.
    static constexpr std::size_t kMaxPoints = 1024;

    // Записать точку, если с прошлой прошло не меньше interval() тиков.
    // Вызывать после каждого тика — сама решит, нужна ли запись.
    void record(const World& world);

    // Забыть всё: у нового (сгенерированного) мира своя летопись, и
    // сшивать её с прежней значило бы врать о том, что было.
    void clear();

    const std::vector<Point>& points() const { return points_; }
    std::uint64_t interval() const { return interval_; }

    // Для файла сохранения (server/WorldSave.cpp) и для протокола
    // (server/NetworkServer.cpp): {"interval": N, "points": [...]}.
    // Точки — массивами, а не объектами с ключами: их тысяча, и в файле,
    // и в сообщении имена полей весили бы больше самих чисел.
    nlohmann::json toJson() const;
    // То же, но только точки новее данного тика — этим дельта протокола
    // дописывает клиенту то, чего у него ещё нет, вместо того чтобы гнать
    // всю летопись на каждое сообщение.
    nlohmann::json toJson(std::uint64_t afterTick) const;
    // Битые или отсутствующие данные — не ошибка: мир из старого файла
    // просто начинает летопись заново, как и мир, сгенерированный только
    // что.
    void fromJson(const nlohmann::json& json);

private:
    // Оставить каждую вторую точку и удвоить шаг.
    void thin();

    std::vector<Point> points_;
    std::uint64_t interval_ = kBaseIntervalTicks;
};

} // namespace goblins
