#pragma once

#include <array>
#include <cstdint>
#include <string>

namespace goblins {

// Имя существа — закон, а не поле.
//
// Имя целиком выводится из постоянного идентификатора (IdentityComponent,
// core/): "Бобл (Клык) проворный" — это три числа, вынутые из одного и того
// же id, и больше ничего. Отсюда всё остальное:
//
//   * имени нет в компоненте — значит, его не надо сохранять и переводить
//     при смене формата сохранения;
//   * имени нет в протоколе — ни в карточке, ни в дельте (CLAUDE.md, круг
//     нового поля существа). Круг этот про поля, которые МЕНЯЮТСЯ или
//     ХРАНЯТСЯ; имя не делает ни того, ни другого: id у клиента уже есть, и
//     он называет гоблина сам, тем же законом и тем же именем, что назвал бы
//     сервер;
//   * имя не может разъехаться с существом. Разъезжается то, что везут двумя
//     путями, а тут пути нет вовсе.
//
// Живёт в shared/, а не в core/ и не у клиента: называть одного и того же
// гоблина обе стороны провода обязаны одинаково, а заголовков core/ клиент не
// видит (07_TechStack.md, п.6).
//
// Закон общий для всякого, у кого есть id: зверю имя даётся той же строкой,
// если однажды понадобится. Гоблинами дело ограничено не законом, а тем, что
// имя показывают только им.
namespace naming {

// Латиница, а не кириллица, и это не выбор вкуса: клиент рисует raylib'ом со
// встроенным шрифтом, в котором есть только ASCII, — кириллическое имя вышло
// бы рядом пустых прямоугольников. Остальные надписи клиента по той же
// причине английские.
inline constexpr std::array kGiven = {
    "Bobl",  "Grish", "Nuk",   "Zarg",  "Mub",   "Krek",  "Tosh",  "Vagd",
    "Snel",  "Hurm",  "Pyx",   "Drok",  "Umbo",  "Rikt",  "Skab",  "Molg",
    "Veed",  "Churk", "Blint", "Zog",   "Nib",   "Gurt",  "Ekk",   "Thrup",
    "Mazl",  "Flig",  "Dreg",  "Skrag", "Vott",  "Grod",  "Ipp",   "Wusk",
    "Tarn",  "Belk",  "Zhod",  "Muzz",  "Prit",  "Gnol",  "Sarv",  "Ozzt",
    "Hib",   "Rung",  "Slok",  "Domb",  "Kizz",  "Yurb",  "Nazz",  "Grumbo",
};

// Кличка — не второе имя, а прозвище: вещь, а не звук. Оттого список другой
// породы, чем первый, — иначе "Бобл Гриш" читалось бы как двое.
inline constexpr std::array kNick = {
    "Fang",   "Tusk",   "Ember",  "Knot",   "Rust",   "Cinder", "Nail",   "Thorn",
    "Bone",   "Soot",   "Pebble", "Wart",   "Stump",  "Hook",   "Crumb",  "Ladle",
    "Twig",   "Kettle", "Flint",  "Grit",   "Bucket", "Nub",    "Shard",  "Slug",
    "Kink",   "Marrow", "Tallow", "Ferret", "Claw",   "Husk",   "Pincer", "Ash",
};

// Определение — с маленькой буквы: оно идёт последним и заглавной спорило бы
// с именем за начало строки.
inline constexpr std::array kEpithet = {
    "nimble",  "sullen", "one-eared", "greedy",   "patient",  "quick",  "crooked", "loud",
    "lucky",   "wary",   "stubborn",  "sneaky",   "hungry",   "sharp",  "slow",    "shaggy",
    "bold",    "sly",    "clumsy",    "restless", "quiet",    "scarred", "squint", "lanky",
    "stout",   "grim",   "cheerful",  "idle",     "watchful", "ragged", "keen",    "weathered",
};

// Трое из четырёх с кличкой.
//
// Кличка есть не у всех, и это главное, что делает список именами, а не
// разрядами счётчика: там, где имя собрано из трёх обязательных частей, все
// имена одной длины и одного склада, и глаз перестаёт их различать. Пропуск
// же сразу делит поселение на "Бобла (Клыка) проворного" и просто "Грода
// хмурого" — второго запоминаешь именно тем, что у него клички нет.
inline constexpr std::uint64_t kNickShare = 4;

struct Name {
    const char* given = "";
    // nullptr — клички нет. Пустая строка не годится: "имя () проворный"
    // отличается от "имени без клички" ровно тем, что его надо было бы
    // отдельно вычищать в каждом месте показа.
    const char* nick = nullptr;
    const char* epithet = "";
};

// Разряды берутся из id как есть, без размешивания: id — это уже готовый
// выход splitmix64 (см. IdentityComponent и core/Random.hpp), биты в нём
// разложены ровно. Куски не пересекаются — иначе имя и кличка ходили бы
// парой, и "Бобл" всегда оказывался бы "Клыком".
//
// Остаток от деления на длину списка слегка перекашивает выбор (последний
// неполный блок чуть вероятнее) — на шестнадцати разрядах и полусотне слов
// перекос меньше сотой доли процента, то есть меньше всего, что тут вообще
// различимо.
inline Name nameOf(std::uint64_t id) {
    Name out;
    out.given = kGiven[(id & 0xFFFFull) % kGiven.size()];
    if (((id >> 16) & 0xFull) % kNickShare != 0) {
        out.nick = kNick[((id >> 20) & 0xFFFFull) % kNick.size()];
    }
    out.epithet = kEpithet[((id >> 40) & 0xFFFFull) % kEpithet.size()];
    return out;
}

// Чем гоблина зовут: "Bobl (Fang)" или просто "Grod". Без определения — им
// не окликают, оно не обращение, а описание.
//
// Сочетаний имени с кличкой — полторы тысячи, и на поселение в две сотни
// тёзки выпадут наверняка. Это не поломка: имя — чтобы узнать того, за кем
// следишь, а не чтобы отличить одного из всех. Где нужна точность, там и
// сейчас берут id (связи, дельта, наблюдение).
inline std::string shortName(std::uint64_t id) {
    const Name name = nameOf(id);
    std::string out = name.given;
    if (name.nick != nullptr) {
        out += " (";
        out += name.nick;
        out += ")";
    }
    return out;
}

// Имя целиком: "Bobl (Fang) nimble", "Grod grim".
//
// Отдельной строкой — для тех мест, где имя не делится на части (строка
// вывода, сообщение, список). Клиент показывает его иначе — имя заголовком,
// определение припиской помельче, — и не потому, что целого ему мало: справа
// от заголовка и в панели, и в карточке стои́т своя надпись, и целое имя
// доставало бы до неё у самых длинных сочетаний.
inline std::string fullName(std::uint64_t id) {
    std::string out = shortName(id);
    out += ' ';
    out += nameOf(id).epithet;
    return out;
}

} // namespace naming

} // namespace goblins
