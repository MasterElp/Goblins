#pragma once

namespace goblins {

// Точность, с которой состояние мира уходит по сети. Это НЕ шкала мира
// (та одна и лежит в core/Scale.hpp) — это отдельное решение о том,
// сколько знаков имеет смысл везти клиенту.
//
// Мир считает доли тысячными. Клиент из плотных слоёв — влажности,
// каменистости, воды, развитости, высоты, падали — не делает ничего,
// кроме смешения цветов (clients/desktop/src/TileColors.hpp). А цвет
// различает куда меньше тысячи ступеней: самая широкая шкала там —
// каменистость, и она разводит цвет тайла на 91 уровень из 255 на весь
// свой диапазон; влажность даёт 37 ступеней, развитость растения — 40,
// вода — 114 на всю видимую глубину. Сотая доля (100 ступеней) покрывает
// любую из них с запасом, а тысячная везла девять десятых чисел, которых
// не видит никто.
//
// Цена тысячной была не в размере числа, а в частоте: дельта слоя — это
// список изменившихся клеток, и клетка попадает в него от изменения на
// единицу. Влажность подтягивается к своему пределу шагом не меньше
// единицы за тик (HydrologySystem, шаг 5а) — то есть на тысячной шкале
// весь мир менялся каждый тик и целиком ехал по проводу. На сотой та же
// клетка попадает в дельту раз в десять тиков.
//
// Счётные величины сюда не относятся и не округляются: минералы, перегной,
// номера видов и семена — штуки, а не доли, и у них своя цена деления,
// равная единице.
inline constexpr int kWireStep = 10;

// Округление от нуля, а не к ближайшему: ноль в слоях воды и падали
// значит "здесь ничего нет" (клиент так и проверяет, MapTexture.cpp), и
// лужа глубиной меньше кванта обязана остаться лужей, а не исчезнуть с
// карты.
constexpr int toWire(int value) {
    return value >= 0 ? (value + kWireStep - 1) / kWireStep : -((-value + kWireStep - 1) / kWireStep);
}

} // namespace goblins
