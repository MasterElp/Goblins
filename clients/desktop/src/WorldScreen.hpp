namespace WorldScreen {

// Единственный экран мира: карта, наблюдение за симуляцией и подбор
// параметров генерации в одном месте. Раньше это были два экрана
// (Simulation и World Generation), показывавших один и тот же мир одной и
// той же картой — разница была только в панели настроек справа и в том,
// что генерация всегда вписывала карту в окно, а симуляция позволяла
// прокрутку с масштабом. Обе возможности остались: панель сворачивается
// (клавиша G), карта вписывается в окно по требованию (клавиша F).
//
// Прокрутка (WASD/стрелки), масштаб (колесо), слои почвы (1-6), пауза (P),
// константы ядра (C), панель генерации (G), вписать карту (F).
//
// config не const: масштаб, включённые слои и открытость панели
// сохраняются в него и на диск (configPath) сразу при изменении — как
// графические настройки на экране "Настройки" (SettingsScreen), без
// отдельной кнопки "Сохранить".
//
// panel живёт снаружи (в main.cpp), а не внутри: это редактируемая копия
// параметров генерации, и она не должна теряться при выходе в меню и
// возврате обратно.
// closeRequested — игрок закрыл окно крестиком (main.cpp). Экран мира
// перехватывает это и спрашивает про сохранение, как при выходе в меню:
// несохранённый мир иначе теряется молча. Флаг сбрасывается, как только
// вопрос задан; выход подтверждают уже в диалоге (AppScreen::Exit).
AppScreen draw(NetworkClient& network, goblins::ClientConfig& config, const std::string& configPath,
               SettingsPanel& panel, bool& closeRequested);

// Открыть панель на вкладке параметров при следующем показе экрана. Этим
// пользуется экран выбора мира: "New world" больше не запускает симуляцию
// сам, а приводит игрока к параметрам генерации — размер карты, seed и всё
// остальное выбирают ДО того, как мир создан, а не перегенерацией уже
// созданного.
void requestParamsTab();

} // namespace WorldScreen
