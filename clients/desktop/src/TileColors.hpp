#pragma once

#include <algorithm>
#include <cmath>

#include <raylib.h>

// Цвет тайла — смешение почвенных параметров разными оттенками (общее
// для экранов "Генерация мира" и "Симуляция", чтобы карта выглядела
// одинаково в обоих режимах).
namespace TileColors {

inline Color lerp(Color a, Color b, float t) {
    t = std::clamp(t, 0.0f, 1.0f);
    return Color{static_cast<unsigned char>(a.r + (b.r - a.r) * t), static_cast<unsigned char>(a.g + (b.g - a.g) * t),
                 static_cast<unsigned char>(a.b + (b.b - a.b) * t), 255};
}

// Каменистость задаёт материал (земля или серый камень), влажность
// затемняет поверх, минералы добавляют золотистый отблеск. Оттенка
// утоптанной земли здесь больше нет: утрамбованности не стало в самой
// почве (core/components/SoilComponent.hpp), и красить нечего.
// mineralsFraction — уже нормализованная доля (0..1), см.
// mineralsFraction(int) ниже: сам SoilComponent.minerals — счётное целое,
// не доля, поэтому нормализация вынесена отдельно, а не в этот блендер.
inline Color soil(float moisture, float rockiness, float mineralsFraction, float trampled) {
    static const Color dirt{101, 67, 33, 255};
    static const Color rock{132, 130, 124, 255};
    static const Color wet{40, 46, 38, 255};
    static const Color mineral{196, 168, 62, 255};
    // Утоптанная земля — светлее и суше на вид: голая утоптанная тропа
    // выбита до песка. Светлее, а не темнее, намеренно: тропа обязана
    // читаться поверх тёмной сырой поймы и тёмной травы, а тёмное на
    // тёмном не видно вовсе — та же причина, по которой луг держат светлым,
    // а рощи тёмными.
    static const Color path{168, 142, 104, 255};

    Color c = lerp(dirt, rock, rockiness);
    c = lerp(c, wet, moisture * 0.6f);
    c = lerp(c, mineral, mineralsFraction * 0.5f);
    // Последней: тропа — то, что поверх всего остального, и она тем ярче,
    // чем сильнее умята.
    c = lerp(c, path, std::clamp(trampled, 0.0f, 1.0f) * 0.75f);
    return c;
}

// Насыщение цвета — с этого количества минералов на тайле дальнейший рост
// уже не меняет оттенок. Не привязано к TerrainParams::mineralsAverage
// (тот — про генерацию, это — чисто про то, где видимая шкала выходит на
// плато), поэтому отдельная константа, а не общий параметр.
constexpr float kMineralsVisualCap = 30.0f;

inline float mineralsFraction(int minerals) {
    return std::clamp(static_cast<float>(minerals) / kMineralsVisualCap, 0.0f, 1.0f);
}

// Цвета видов травы — по индексу вида (PlantGenomeComponent::species,
// приходит в снапшоте). Оттенки светлые, зелёно-жёлто-оливковые: трава на
// карте — это цвет самой земли, чуть тронутый зеленью, а не предмет на ней.
// Тёмная гуща оставлена деревьям (treeSpecies ниже), и держать луг светлым
// теперь обязательно: рощи узнаются на карте именно тем, что они — тёмные
// пятна, а тёмное на тёмном не читается.
//
// Двенадцать — ровно верхний предел числа видов в мире
// (core::kMaxGrassSpecies); если сервер когда-нибудь пришлёт индекс больше,
// цвет просто повторится (остаток от деления), а не приведёт к выходу за
// границы.
inline Color plantSpecies(int species) {
    static const Color palette[12] = {
        {150, 202, 124, 255}, {192, 216, 118, 255}, {130, 190, 158, 255}, {214, 224, 136, 255},
        {166, 208, 166, 255}, {138, 196, 186, 255}, {202, 210, 114, 255}, {160, 186, 120, 255},
        {182, 226, 160, 255}, {134, 176, 138, 255}, {224, 232, 170, 255}, {146, 206, 190, 255},
    };
    if (species < 0) {
        return palette[0];
    }
    return palette[species % 12];
}

// Трава поверх почвы — не квадрат, а лёгкая подмешка цвета вида: сквозь
// неё видно землю, её влажность и её камень, и тем сильнее, чем растение
// мельче. Подмешка намеренно слабая: трава покрывает почти всю карту, и
// будь она плотной, карта превратилась бы в ровный зелёный лист, на
// котором не разглядеть ни рельефа, ни воды, ни — главное — рощ.
inline Color plant(Color soilColor, int species, float growth) {
    return lerp(soilColor, plantSpecies(species), 0.12f + 0.28f * std::clamp(growth, 0.0f, 1.0f));
}

// Цвета видов кустов — своей палитрой, между травяной и древесной: куст
// плотнее травы и ниже дерева, и на карте он должен читаться как гуща на
// лугу, а не как ещё один оттенок луга. Четыре — верхний предел числа видов
// (core::kMaxBushSpecies).
inline Color bushSpecies(int species) {
    static const Color palette[4] = {
        {74, 118, 72, 255}, {96, 124, 64, 255}, {66, 110, 92, 255}, {104, 112, 60, 255},
    };
    if (species < 0) {
        return palette[0];
    }
    return palette[species % 4];
}

// Куст поверх почвы — подмешка сильнее травяной: куст землю закрывает, а
// трава её лишь красит. Слабее единицы всё же намеренно: под кустом видно,
// сухо ему или мокро, а это и решает, вырастет ли там ягодник.
inline Color bush(Color soilColor, int species, float growth) {
    return lerp(soilColor, bushSpecies(species), 0.45f + 0.45f * std::clamp(growth, 0.0f, 1.0f));
}

// Ягоды на кусте — красная искра тем ярче, чем их больше. Считаются штуками
// (core::kBerryMax — полный куст), поэтому доля берётся здесь, а не
// приходит готовой: сам слой счётный.
//
// Видеть их обязательно: обобранный ягодник и полный — разные места, и по
// карте должно быть понятно, к какому из них гоблин идёт.
constexpr float kBerriesVisualCap = 12.0f;

inline Color berries(Color bushColor, int count) {
    static const Color berry{188, 62, 74, 255};
    const float share = std::clamp(static_cast<float>(count) / kBerriesVisualCap, 0.0f, 1.0f);
    return lerp(bushColor, berry, 0.25f + 0.45f * share);
}

// Куча принесённой еды. Своим цветом, не похожим ни на траву, ни на падаль:
// куча — единственная вещь на карте, оказавшаяся там не сама, и увидеть её
// надо с одного взгляда, иначе весь шаг с ношей не проверить глазами.
//
// Насыщение — примерно горсть взрослого (kCarryPerSize = 2000,
// core/Carry.hpp): дальше растёт только уверенность, а не цвет.
constexpr float kStoreVisualCap = 2000.0f;

inline Color store(Color base, int food) {
    static const Color heap{226, 178, 86, 255};
    const float share = std::clamp(static_cast<float>(food) / kStoreVisualCap, 0.0f, 1.0f);
    return lerp(base, heap, 0.35f + 0.55f * share);
}

// Семя в клетке — тёмная крапина цвета своего вида: оно лежит В земле, а
// не стоит на ней, поэтому цвет вида сперва притемняется и только потом
// подмешивается к почве. Так семя не путается с проростком (тот уже
// зелёный и тем ярче, чем больше вырос), но видно, что клетка не пустая:
// на заросшем лугу семена лежат под своими родителями и на карте не
// видны вовсе — а вот семя, пережившее растение и ждущее в опустевшей
// клетке, увидеть важно.
inline Color seed(Color soilColor, int species) {
    static const Color earth{28, 24, 18, 255};
    return lerp(soilColor, lerp(plantSpecies(species), earth, 0.55f), 0.45f);
}

// Цвета видов деревьев — по индексу вида. Палитра своя, а не травяная, и
// вся тёмно-зелёная: роща на карте должна читаться пятном с первого
// взгляда, иначе весь смысл островков теряется. Пять — верхний предел
// числа видов деревьев (core::kMaxTreeSpecies).
// Сколько всего цветов у деревьев — оно же верхний предел числа их видов
// (core::kMaxTreeSpecies). Наружу нужно тому, кто печёт спрайты сразу на
// все виды (TreeSprites).
constexpr int kTreeSpeciesCount = 5;

inline Color treeSpecies(int species) {
    static const Color palette[kTreeSpeciesCount] = {
        {24, 66, 32, 255}, {40, 78, 30, 255}, {18, 58, 48, 255}, {52, 74, 24, 255}, {30, 52, 34, 255},
    };
    if (species < 0) {
        return palette[0];
    }
    return palette[species % kTreeSpeciesCount];
}

// Цвет ствола. Сплошной и тёмно-зелёный: дерево рисуется не текселем
// карты, а фигурой поверх неё (см. WorldScreen) — тонким прямоугольником,
// воткнутым в клетку и выходящим на клетку выше, — и просвечивать сквозь
// него нечему.
//
// Развитость читается по цвету: подрост глуше и светлее взрослого, но и он
// остаётся тёмно-зелёным — ствол виден всегда, с первого своего тика. Цвет
// почвы в подмешке не участвует намеренно: земля видна вокруг ствола, а
// сам он не должен меняться от места к месту.
inline Color tree(int species, float growth) {
    static const Color sapling{92, 112, 80, 255};
    return lerp(sapling, treeSpecies(species), 0.35f + 0.65f * std::clamp(growth, 0.0f, 1.0f));
}

// Цвета видов хищников — по индексу вида. Палитра третья и намеренно
// холодно-красная: хищника надо отличать от добычи мгновенно и не путать
// ни с травой, ни с ней. Шесть — верхний предел числа видов хищников
// (core::kMaxPredatorSpecies).
inline Color predatorSpecies(int species) {
    static const Color palette[6] = {
        {198, 74, 60, 255}, {150, 56, 74, 255},  {226, 106, 78, 255},
        {124, 60, 92, 255}, {176, 92, 108, 255}, {214, 132, 120, 255},
    };
    if (species < 0) {
        return palette[0];
    }
    return palette[species % 6];
}

// Цвета видов травоядных — по индексу вида, как и у травы, но палитра
// намеренно другая: тёплые охристо-рыжие тона против зелени луга. Животное
// на карте — не часть растительности, и путать их взглядом нельзя. Восемь
// — верхний предел числа видов травоядных в мире
// (core::kMaxHerbivoreSpecies); индекс больше просто повторит цвет
// (остаток от деления), а не выйдет за границы.
inline Color herbivoreSpecies(int species) {
    static const Color palette[8] = {
        {214, 158, 84, 255},  {186, 116, 66, 255}, {231, 199, 122, 255}, {158, 96, 62, 255},
        {236, 172, 140, 255}, {198, 140, 92, 255}, {172, 128, 104, 255}, {242, 214, 178, 255},
    };
    if (species < 0) {
        return palette[0];
    }
    return palette[species % 8];
}

// Цвета племён гоблинов — по номеру племени. Палитра третья и намеренно
// холодная, сине-зелёная: на карте уже есть тёплая охра травоядных и красная
// краснота хищников, и гоблин не должен читаться ни тем, ни другим. Шесть —
// верхний предел числа племён (core::kMaxGoblinTribes); номер больше просто
// повторит цвет, а не выйдет за границы.
inline Color goblinTribe(int tribe) {
    static const Color palette[6] = {
        {94, 176, 158, 255}, {66, 132, 150, 255},  {132, 200, 172, 255},
        {78, 108, 142, 255}, {148, 186, 200, 255}, {104, 148, 132, 255},
    };
    if (tribe < 0) {
        return palette[0];
    }
    return palette[tribe % 6];
}

// Падаль — красновато-бурое пятно поверх почвы, заметно теплее перегноя:
// туша на земле должна читаться как событие, а не как оттенок грунта.
// Насыщенность растёт с количеством мяса и выходит на плато — разница
// между одной тушей и тремя на одном тайле уже не важна.
inline Color carcass(Color soilColor, float meat) {
    static const Color rot{122, 52, 44, 255};
    return lerp(soilColor, rot, std::clamp(meat / 6.0f, 0.0f, 1.0f) * 0.75f);
}

// Перегной — тёмное органическое пятно на почве. Насыщенность растёт с
// количеством минералов, которые ещё не вернулись в почву, и выходит на
// плато: разница между "тут умерло одно растение" и "тут умерло десять"
// после какого-то предела уже не читается.
inline Color humus(Color soilColor, int minerals) {
    static const Color rot{58, 44, 30, 255};
    return lerp(soilColor, rot, std::clamp(static_cast<float>(minerals) / 12.0f, 0.0f, 1.0f) * 0.6f);
}

// От мелкой (светлее, бирюзовее) до глубокой (тёмно-синяя) воды.
inline Color water(float depth) {
    static const Color shallow{90, 150, 175, 235};
    static const Color deep{18, 36, 66, 255};
    const float t = std::clamp(depth / 3.0f, 0.0f, 1.0f);
    return lerp(shallow, deep, t);
}

// Чёрно-белый градиент рельефа: t — уже готовая доля 0..1, не сама высота.
// Абсолютного диапазона высот здесь нет и быть не может — mountain_height
// у разных миров разный (по умолчанию 16, а не 41995, как в примере
// конфига), и зашитые в саму функцию границы либо забивали бы карту в
// сплошной белый на высоких горах, либо не давали никакого контраста на
// низких. Долю считает вызывающая сторона — по настоящему диапазону ЭТОГО
// мира (MapTexture.cpp: state.heightMin/heightMax, зафиксированные на
// world_init).
inline Color applyHeightShading(float t) {
    static const Color low{ 0, 0, 0, 255 };
    static const Color high{ 255, 255, 255, 255 };
    return lerp(low, high, std::clamp(t, 0.0f, 1.0f));
}

} // namespace TileColors
