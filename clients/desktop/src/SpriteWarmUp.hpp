// Испечь все рисунки разом, до первого кадра.
//
// Печь их можно только при созданном GL-контексте, поэтому каждый модуль
// печётся лениво — из статической переменной внутри себя. Ленивость эта верна,
// но у неё есть цена, и после того как все рисунки легли на один общий лист
// (SpriteAtlas::Page), цена выросла: лист растёт по мере того, как до каждого
// рисунка доходит дело, и каждый рост заливается на видеокарту целиком.
//
// Замерено в живом клиенте: семнадцать выпечек на 21.6 мс и ЧЕТЫРЕ заливки на
// 19.1 мс, размазанные по первым четырём кадрам мира. При тридцати кадрах в
// секунду это четыре кадра подряд мимо бюджета — ровно в тот миг, когда мир
// впервые показывают.
//
// Второе, и оно важнее миллисекунд: пока рисунки печёт первый кадр, РАСКЛАДКА
// общего листа зависит от того, что в мире оказалось. Мир без воды кладёт воду
// позже, мир без деревьев — дерево позже, и лист выходит разный. Сегодня это
// никому не мешает, но делает разложение по листу зависимым от содержимого
// мира, а такую зависимость лучше не заводить вовсе.
