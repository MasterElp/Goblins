// Карточка выбранного — маленьким окном поверх карты, в левом нижнем углу.
//
// Зачем она, когда справа уже есть подробная панель (InfoPanel). Панель
// отвечает на вопрос "расскажи всё": там тело, желания, геном, клетка под
// ним — под сорок строк, и читают их, остановившись. Карточка отвечает на
// другой вопрос — "кого я сейчас веду глазами": имя, цвет, цел ли, чем занят.
// Её читают, не отрываясь от карты, и оттого она стои́т НА карте, рядом с тем,
// за кем следят, а не в стороне за краем экрана.
//
// Панель при этом никуда не девается и не дублируется: карточка показывает
// то, что помещается в полдюжины строк, и ни одной цифры сверх этого.
//
// Появляется только по ВЫБОРУ (щелчку), а не по наведению. Наведение — это
// скольжение мыши по карте, и окно, всплывающее и гаснущее под курсором,
// читалось бы миганием, а не сведениями; на наведение отвечает панель справа,
// которая стои́т на месте.
namespace SelectionCard {

// Где стои́т карточка при таком окне карты. Ширина ноль — показывать нечего
// (ничего не выбрано), и рисовать её не надо.
//
// Место считается ОТДЕЛЬНО от рисования, потому что читателей у него двое:
// сам рисунок и ввод. Карточка лежит на карте, и щелчок по ней не должен
// ни выбирать клетку под нею, ни таскать карту — а чтобы этого не делать,
// вводу надо знать, где она, раньше, чем она нарисована.
Rectangle bounds(const InfoPanel::Target& target, Rectangle viewport);

void draw(const WorldState& state, const InfoPanel::Target& target, Rectangle bounds);

} // namespace SelectionCard
