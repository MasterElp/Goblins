#pragma once

#include <cstdint>
#include <string>

#include <raylib.h>

// Рисунки травоядных: олень сбоку, четыре занятия по два кадра, три облика,
// свои цвета на каждый вид.
//
// Оленем рисуется ВСЯКОЕ травоядное, каким бы ни был его вид, — тот же приём,
// каким хищник рисуется волком, а гоблин одним и тем же рисунком на все
// племена: вид опознаётся цветом, силуэт говорит то, что у всех травоядных
// общее.
//
// От волка олень отличается не цветом, а СЛОЖЕНИЕМ: ноги длиннее, шея выше,
// туловище тоньше. Хищник низкий и длинный, добыча высокая и лёгкая — с
// одного взгляда должно быть видно, кто кого ест, и цвет для этого слишком
// слабый довод: на пёстрой земле охра травоядного и краснота хищника
// сходятся, а силуэт не сходится никогда.
//
// Сам рисунок здесь не живёт: он лежит в ресурсах (assets/sprites/deer.spr,
// см. Assets.hpp), а здесь — только то, что знает о травоядных именно клиент.
namespace DeerSprites {

// Кадр — ровно клетка, как у волка и гоблина.
constexpr int kSize = 16;

// Обликов три, и они складывают возраст с полом: телёнок, взрослая самка и
// взрослый самец с рогами.
//
// Порознь эти две вещи не ложатся, оттого они и в одной оси: рогов у телёнка
// не бывает ни при каком поле, и четвёртая клетка таблицы — рогатый телёнок —
// была бы кадром, которому в мире нечего изображать.
//
// Пол теперь виден рогами, а не формой значка, и это честнее прежнего: у
// квадрата и кружка не было никакой связи с полом, их приходилось помнить.
constexpr int kKinds = 3;

// Кадров на занятие. Пара: показать нужно не походку, а что зверь живой и
// чем он занят.
constexpr int kFrames = 2;

// Занятия. Их четыре, и одно есть только у травоядного.
enum class Pose {
    Stand = 0, // стоит: ничего не гонит, либо ищет пару
    Walk,      // идёт
    Flee,      // БЕЖИТ: уходит от того, кто может съесть
    Feed,      // морда у земли: щиплет траву или пьёт
};
constexpr int kPoses = 4;

// Есть ли чем рисовать. false — ресурс не нашёлся или в нём не хватает
// кадров; травоядное тогда остаётся тем же значком, каким оно рисуется на
// мелком масштабе (см. WorldScreen).
bool ready();

// Атлас: строка — вид травоядного, столбец — кадр.
const Texture2D& atlas();

// Где в атласе лежит нужный кадр. facing — сторона: >= 0 мордой вправо,
// < 0 влево (кусок возвращается отрицательной ширины, и DrawTexturePro
// отражает его сам). Видов со спины и навстречу у зверя нет — по той же
// причине, что и у волка.
Rectangle source(int species, Pose pose, int kind, int frame, int facing);

// Облик по развитости тела (0..1, как она приходит в снапшоте) и полу.
// Порог взрослости тот же, которым мир отделяет взрослого (kBreedingGrowth в
// AnimalSystem): рога вырастают тогда же, когда зверь становится взрослым и в
// мире, а не когда так решил рисунок.
int kindOf(float growth, const std::string& sex);

// Чем рисовать зверя, у которого такое желание. walking — сделал ли он шаг
// только что (см. walkingNow).
//
// Бегство — единственное желание, которому нужен и шаг: "убегаю" стоя на
// месте не выглядит ничем, потому что бегство это и есть шаг. Оно же и
// единственное, ради чего травоядному дан свой кадр: на карте видно, что
// стадо побежало, раньше, чем видно, от кого.
Pose poseOf(const std::string& desire, bool walking);

// Идёт ли зверь сейчас: давно ли был его последний шаг. stepTick — тик, на
// котором клиент видел шаг (WorldState::Animal), 0 — не видел ни разу.
//
// Памяти пять тиков против волчьих трёх: травоядное медленнее (скорость
// 200..1150 тысячных клетки за тик против хищничьих 900..1800,
// AnimalGenetics), и у самого медленного шаг занимает пять тиков — помни
// меньше, и он мигал бы между ходьбой и стоянием на каждом шагу.
bool walkingNow(std::uint64_t stepTick, std::uint64_t tick);

// Какой кадр показывать этому зверю сейчас. Часы — тик мира: зверь двигается
// сам, и остановленный мир обязан замереть весь. Фаза от постоянного номера
// зверя — иначе всё стадо переступало бы разом.
int frameOf(std::uint64_t id, std::uint64_t tick);

} // namespace DeerSprites
