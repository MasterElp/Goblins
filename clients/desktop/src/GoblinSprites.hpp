#pragma once

#include <cstdint>
#include <string>

#include <raylib.h>

// Рисунки гоблинов: два возраста и семь занятий по два кадра, свои цвета на
// каждое племя.
//
// Зачем гоблину рисунок, когда ромба хватало. Ромб отвечал на один вопрос —
// "здесь гоблин", — и на этом заканчивался. А смотрят на гоблина ради
// другого: почему их двадцать столпилось у ручья, отчего этот идёт мимо
// куста с полными руками, кто лежит, а кто работает. Всё это в мире уже
// есть, но на карте до сих пор выглядело одинаковым ромбом, и единственным
// способом узнать ответ было щёлкнуть по каждому и прочесть карточку.
// Рисунок отвечает на это разом и на всю округу.
//
// Отсюда и три вещи, которыми кадры различаются, — и ровно три:
//   занятие  — что он делает (по желанию из протокола и по тому, идёт ли);
//   сторона  — куда идёт (вбок отражением, отвесно — своими кадрами);
//   возраст  — детёныш или взрослый.
// Пол сюда намеренно не входит: он не виден со стороны и не меняет ни
// одного поступка гоблина в законах мира — в отличие от зверя, где по полу
// различаются сами значки, потому что больше о звере сказать нечего.
//
// Сам рисунок здесь не живёт: он лежит в ресурсах (assets/sprites/goblin.spr,
// см. Assets.hpp), а здесь — только то, что знает о гоблинах именно клиент:
// какие бывают занятия, каким кадром рисуется какое желание и с какой
// скоростью сменяются кадры.
namespace GoblinSprites {

// Кадр — ровно клетка, в отличие от дерева и постройки. Те из своей клетки
// торчат вверх, гоблин в ней стоит: он ходит по земле, и на одной клетке их
// может оказаться несколько.
//
// Листов рисунка ДВА, и это не запас на будущее. Клетка на экране бывает и в
// два пикселя (карта целиком), и в шестьдесят четыре (вплотную); один
// рисунок не годится на оба конца — мелкий, растянутый вчетверо, распадается
// на квадраты, а крупный, ужатый вдвое, теряет ровно ту подробность, ради
// которой нарисован.
constexpr int kCoarseSize = 16;
constexpr int kFineSize = 32;

// Возрасты: детёныш и взрослый. Два, а не три, как у дерева, и причина
// обратная той: у дерева три облика потому, что оно стоит на месте
// десятки тысяч тиков и больше сказать о нём нечем, а гоблин и так меняет
// облик каждым своим занятием. Третья ступень отличалась бы от соседних на
// пиксель роста — меньше, чем гоблин качается, стоя.
constexpr int kStages = 2;

// Кадров на занятие. Пара: показать нужно не походку, а что гоблин живой и
// чем он занят.
constexpr int kFrames = 2;

// Занятия. Их семь, и это НЕ список желаний из протокола: желаний столько
// же (GoblinDesire), но соответствие между ними не однозначное — идущий за
// водой и идущий к ягоднику выглядят одинаково, а вот стоящий над кустом и
// идущий к нему с полными руками не выглядят одинаково ничуть.
//
// Клиент по-прежнему не знает, какие занятия бывают В МИРЕ (07_TechStack.md,
// п.6): он знает, какие бывают на КАРТИНКЕ, а это его собственное дело.
// Незнакомое имя желания рисуется стоянием (см. poseOf) — новое желание в
// мире не обязано ждать нового кадра здесь.
enum class Pose {
    Stand = 0, // стоит: ничего не гонит, либо ищет пару
    Walk,      // идёт налегке
    Carry,     // идёт с ношей в руках
    Eat,       // ест
    Drink,     // пьёт
    Rest,      // лежит
    Work,      // работает руками: строит, собирает, складывает в кучу
};
constexpr int kPoses = 7;

// Какой из двух листов кадров. Оба нарисованы одними и теми же именами
// кадров и красятся одной и той же раскраской: разойтись им нельзя, иначе
// гоблин менял бы облик от поворота колеса мыши.
enum class Detail { Coarse, Fine };

// Какой лист брать при такой клетке на экране.
//
// Крупный — только когда клетка не мельче самого кадра: ужатый крупный лист
// теряет ту самую подробность, ради которой нарисован, и выглядит грязнее
// мелкого. Нет крупного листа или он неполон — всегда мелкий: это не беда, а
// обычный путь, и второй лист вовсе не обязателен для того, чтобы клиент
// рисовал гоблинов.
Detail detailFor(float tileSize);

// Есть ли чем рисовать этим листом. false — ресурс не нашёлся или в нём не
// хватает кадров; если негоден мелкий, гоблин остаётся тем же ромбом, каким
// он рисуется на мелком масштабе (см. WorldScreen).
bool ready(Detail detail);

// Атлас: строка — племя, столбец — кадр. Печётся при первом обращении
// (нужен уже созданный GL-контекст) и живёт до конца работы окна — как и
// текстура карты, намеренно не выгружается: raylib освобождает свои ресурсы
// сам при CloseWindow.
const Texture2D& atlas(Detail detail);

// Куда гоблин повёрнут. Две независимые вещи, и обе нужны сразу.
//
// Вбок он повёрнут ВСЕГДА: сторона липкая, она держится с последнего шага,
// у которого была боковая составляющая, — и стоящему, и жующему есть куда
// смотреть. А отвесно — только пока он идёт ровно вверх или вниз; кончился
// шаг, кончилось и это.
//
// Отвесный шаг — единственный, у которого боковой составляющей нет вовсе, и
// потому единственный, которому нужен свой кадр. Косой рисуется боковым
// видом: со стороны он боковым и выглядит.
struct Facing {
    // +1 вправо, -1 влево.
    int side = 1;
    // -1 вверх (спиной к смотрящему), +1 вниз (лицом), 0 — шаг был боковым
    // или косым.
    int vertical = 0;
};

// Где в атласе лежит нужный кадр.
//
// Влево кадр не нарисован вовсе: возвращается кусок ОТРИЦАТЕЛЬНОЙ ширины, и
// DrawTexturePro отражает его сам. Второй набор кадров был бы тем же
// рисунком наоборот, и правку в него пришлось бы вносить дважды.
//
// Вид со спины и навстречу есть только у ходьбы и у ноши. У остальных
// занятий берётся боковой, и это не нехватка кадров: направление есть у
// того, кто ИДЁТ, — у жующего и лежащего его в мире нет вовсе.
Rectangle source(Detail detail, int tribe, Pose pose, int stage, int frame, Facing facing);

// Возраст по развитости тела (0..1, как она приходит в снапшоте). Порог тот
// же, которым мир отделяет взрослого от подростка (kBreedingGrowth в
// GoblinSystem): взрослый на карте — это тот, кто взрослый и в мире, а не
// тот, кто дорос до придуманной здесь черты.
int stageOf(float growth);

// Чем рисовать гоблина, у которого такое желание. walking — сделал ли он
// шаг только что (см. walkingNow), loaded — есть ли что-нибудь в руках.
//
// Одного желания мало, и в этом весь смысл двух других доводов: "хочу есть"
// одинаково верно и для идущего за полкарты к ягоднику, и для стоящего над
// ним. Рисовать обоих жующими значило бы врать про половину племени —
// именно та беда, ради которой лист кадров считается негодным целиком, если
// в нём не хватает хоть одного кадра.
Pose poseOf(const std::string& desire, bool walking, bool loaded);

// Идёт ли гоблин сейчас: давно ли был его последний шаг. stepTick — тик, на
// котором клиент видел шаг (WorldState::Goblin), 0 — не видел ни разу.
//
// Не мгновение, а память на несколько тиков: шаг у гоблина занимает от
// одного тика до четырёх (скорость 300..900 тысячных клетки за тик,
// GoblinGenetics), и по одному лишь "сдвинулся ли он в этой дельте" идущий
// мигал бы между ходьбой и стоянием несколько раз в секунду.
bool walkingNow(std::uint64_t stepTick, std::uint64_t tick);

// Какой кадр показывать этому гоблину сейчас.
//
// Часы здесь — тик мира, а не время на стене, и это единственное отличие от
// качания дерева. Дерево качает ветер, он дует и в остановленном мире; а
// гоблин двигается сам, и остановленный мир обязан замереть весь. Заодно
// ускоренный мир и выглядит ускоренным.
//
// Фаза — от постоянного номера гоблина (IdentityComponent): иначе всё племя
// переступало бы разом, как один предмет.
int frameOf(std::uint64_t id, std::uint64_t tick);

} // namespace GoblinSprites
