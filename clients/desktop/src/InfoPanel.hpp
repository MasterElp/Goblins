// Карточка того, на что смотрит игрок: существо, растение или сама клетка.
//
// Что показывать, решает не эта панель, а экран мира (WorldScreen): он
// знает и про курсор, и про выбор кликом. Сюда приходит уже готовая цель.
//
// Данные — из двух источников, и это не небрежность. Всё, что есть в
// снимке мира (почва, вода, перегной, падаль, семя, само наличие
// животного), панель читает прямо из него: оно уже пришло, и спрашивать
// сервер отдельно значило бы показывать то же самое с задержкой. А тело,
// желания и геном выбранного существа приходят карточкой
// (WorldState::watched, запрос "watch") — их в общем снимке нет и быть не
// должно: геном каждого животного в каждой дельте весил бы больше, чем всё
// остальное состояние мира вместе взятое.
namespace InfoPanel {

// На что смотрим. Animal — по постоянному идентификатору (животное
// ходит, и клетка его не определяет), Plant и Soil — по клетке.
struct Target {
    enum class Kind { None, Animal, Goblin, Plant, Soil };

    Kind kind = Kind::None;
    std::uint64_t animalId = 0;
    int x = 0;
    int y = 0;
    // Выбрано кликом (и держится, пока не выберут другое) или просто
    // оказалось под курсором. Разница видна в заголовке карточки: иначе
    // непонятно, почему цифры перестали меняться вслед за мышью.
    bool pinned = false;
};

// Цель равна другой, если это тот же объект: у животного — тот же
// идентификатор, у клетки — та же клетка. "Закреплённость" в это не
// входит: закрепление того же самого существа новой целью не делает.
inline bool sameTarget(const Target& a, const Target& b) {
    if (a.kind != b.kind) {
        return false;
    }
    if (a.kind == Target::Kind::Animal || a.kind == Target::Kind::Goblin) {
        // Поле одно на обоих: это постоянный идентификатор существа, а не
        // "номер животного". Держать рядом второе, гоблинское, значило бы
        // завести два имени одному и тому же.
        return a.animalId == b.animalId;
    }
    return a.x == b.x && a.y == b.y;
}

// Чем является выбранное и каким цветом оно помечено на карте.
//
// Наружу это вынесено потому, что читателей у заголовка теперь двое: сама
// панель и карточка выбранного над картой (SelectionCard). Считай его каждый
// по-своему — и одно и то же существо звалось бы в них по-разному, а заметить
// такое можно только поставив их рядом.
struct Heading {
    std::string title;
    // Тот же цвет, каким существо нарисовано на карте: карточку и точку на
    // карте надо связывать взглядом, а не догадкой. Прозрачный — метки нет
    // (почва, исчезнувшее существо).
    Color swatch{0, 0, 0, 0};
    // Где выбранное СЕЙЧАС: существо ходит, и клетка, с которой его выбрали,
    // уже не его клетка.
    int x = 0;
    int y = 0;
    // Выбранного больше нет в мире (съеден, умер, вытоптан).
    bool gone = false;
};
Heading headingOf(const WorldState& state, const Target& target);

// Существо по постоянному номеру; nullptr — такого в списке уже нет.
const WorldState::Animal* findAnimal(const WorldState& state, std::uint64_t id);
const WorldState::Goblin* findGoblin(const WorldState& state, std::uint64_t id);

// Карточка сервера (WorldState::watched) относится именно к этой цели?
// Между кликом и ответом проходит одна рассылка, и всё это время там лежит
// карточка предыдущего выбранного — показать её как текущую значило бы
// соврать.
bool watchedMatches(const WorldState& state, const Target& target);

void draw(const WorldState& state, const Target& target, Rectangle bounds);

} // namespace InfoPanel
