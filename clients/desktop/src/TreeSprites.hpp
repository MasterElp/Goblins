#pragma once

#include <raylib.h>

// Рисунки деревьев: три возраста по два кадра, свои цвета на каждый вид.
//
// Дерево — единственное на карте, что не выражается ни цветом клетки, ни
// значком в ней: оно из клетки торчит вверх, стоит на месте десятки тысяч
// тиков и за это время трижды меняет облик. Рощу узнают по кронам, а не по
// оттенку земли, поэтому у неё и рисунок, а не заливка.
//
// Рисунок лежит в исходнике текстом, а не в файлах рядом с exe. Причина не
// в бережливости: у клиента нет и никогда не было каталога ресурсов, и
// заводить его ради тридцати крошечных картинок значило бы завести вместе с
// ним и путь к нему, и его поиск при запуске, и обращение с пропавшим
// файлом. Текстовый рисунок к тому же виден в diff'е — изменение кроны
// читается как изменение кода, а не как "картинка стала другой".
namespace TreeSprites {

// Размер одного кадра. Ровно клетка в ширину и две в высоту: дерево
// воткнуто в свою клетку, а крона выходит на клетку выше. Шестнадцать —
// это ClientConfig::tile_size по умолчанию, то есть при обычном масштабе
// рисунок ложится пиксель в пиксель.
constexpr int kWidth = 16;
constexpr int kHeight = 32;

// Возрасты: росток, подрост, взрослое. Три, а не больше: возраст должен
// читаться с одного взгляда на карту, а не разглядыванием — четвёртая
// ступень отличалась бы от соседних меньше, чем дрожит крона.
constexpr int kStages = 3;

// Кадров качания. Пара: дерево не ходит, оно качается, и всё, что нужно
// показать, — что оно живое.
constexpr int kFrames = 2;

// Атлас: строка — вид дерева, столбец — возраст и кадр. Собирается при
// первом обращении (нужен уже созданный GL-контекст) и живёт до конца
// работы окна — как и текстура карты, намеренно не выгружается: raylib
// освобождает свои ресурсы сам при CloseWindow.
const Texture2D& atlas();

// Где в атласе лежит нужный кадр.
Rectangle source(int species, int stage, int frame);

// Возраст по развитости растения (0..1, как она приходит в снапшоте).
int stageOf(float growth);

// Какой кадр качания показывать этому дереву сейчас. Фаза зависит от
// клетки: иначе вся роща качалась бы разом, как один предмет.
int frameOf(int x, int y, double seconds);

} // namespace TreeSprites
