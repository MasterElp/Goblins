#pragma once

// Экраны приложения. Меню — точка входа после запуска; пункты меню ведут
// в соответствующий экран. Назад — по Esc, из любого экрана в меню.
//
// Экран мира один (World): и подбор параметров генерации, и наблюдение за
// симуляцией — это один и тот же мир на одной и той же карте, отличавшийся
// раньше только тем, крутится ли рядом панель настроек. Держать под это два
// экрана значило дублировать отрисовку карты, подсказку по тайлу под
// курсором и работу с паузой, а переключаться между ними — терять
// прокрутку, масштаб и включённые слои.
//
// "World" в меню ведёт не сразу в мир, а на экран выбора мира
// (WorldSelect): мир — это всегда какой-то конкретный сохранённый мир,
// поэтому его сначала нужно выбрать (или создать новый).
enum class AppScreen {
    MainMenu,
    Settings,
    WorldSelect,
    World,
};
