#pragma once

#include <cstdint>
#include <vector>

#include <raylib.h>

#include "SpriteAtlas.hpp"

// Рябь на воде: рисунок поверх цвета клетки, свой на каждое направление
// течения и своя густота на каждую глубину.
//
// Цвет клетки (TileColors::water) отвечает на вопрос "какая тут глубина" и
// виден на любом масштабе, вплоть до карты, вписанной в окно. Рябь отвечает на
// другой — "стоит эта вода или течёт и куда" — и появляется, только когда
// клетка достаточно крупная, чтобы её разглядеть. Тот же приём, что у травы с
// кустом: подмешка в текстуру не отменяется рисунком, а дополняется им.
//
// Куда течёт, клиент считает САМ, и ничего нового по проводу для этого не
// едет. Поверхность воды — это высота дна плюс глубина (`height` + `water` в
// протоколе), и ровно по разнице таких поверхностей гоняет воду сам мир
// (HydrologySystem: `surface = terrainHeight + waterDepth`). Вычисленное на
// клиенте направление — не догадка о мире, а тот же его закон, посчитанный
// заново; поле в протоколе сказало бы ровно то же самое, только весом в целый
// слой на каждый тик.
namespace WaterSprites {

// Кадр — ровно клетка: вода лежит В клетке, а не торчит из неё.
constexpr int kSize = 16;

// Кадров на вид ряби. Четыре, а не два, как у зверя: у зверя кадр говорит
// "он жив", а тут кадры — само движение, и по двум не видно, в какую сторону
// оно идёт.
constexpr int kFrames = 4;

// Разводий на каждый вид. Три, и по той же причине, что у травы и у крон:
// узор, повторённый клетка в клетку, читается не водой, а решёткой.
constexpr int kVariants = 3;

// Строк в листе — не виды, а ГЛУБИНЫ: мелко, средне, глубоко. У воды нет
// видов, зато есть глубина, и она единственное, что меняет её цвет.
constexpr int kDepths = 3;

// Подробность — общая на все рисунки (SpriteAtlas::Detail).
using Detail = SpriteAtlas::Detail;

// Куда и как быстро течёт вода в клетке. dx/dy — -1, 0 или 1; speed — ноль у
// стоячей и до единицы у самой быстрой.
struct Flow {
    int dx = 0;
    int dy = 0;
    float speed = 0.0f;
};

// Куда потечёт вода из этой клетки: самый крутой спуск поверхности среди
// восьми соседей.
//
// Сухие соседи считаются наравне с мокрыми, и это не небрежность: сухая
// клетка НИЖЕ уровня воды — это край, за который вода вот-вот перевалится, и
// течение там самое быстрое, какое на карте бывает. Мир исключает из счёта
// ровно обратное — сухое и ВЫШЕ уровня, куда воде не подняться.
//
// Диагональный сосед дальше прямого в корень из двух раз, и перепад до него
// делится на это же: иначе наискось всегда выходило бы круче, и всякая река
// текла бы наискосок.
//
// Мелкий перепад считается за стоячую воду, и порог тут не про физику, а про
// округление: слои едут сотыми долями, разность двух поверхностей носит в
// себе до двух сотых ошибки, и направление по перепаду мельче этого —
// стрелка на подброшенной монете (kStillDrop в WaterSprites.cpp).
Flow flowAt(const std::vector<float>& terrainHeight, const std::vector<float>& depth, int width,
            int areaHeight, int x, int y);

// Какой лист брать при такой клетке. Нет крупного или он неполон — мелкий.
Detail detailFor(float tileSize);

// Есть ли чем рисовать этим листом. Негоден мелкий — ряби нет вовсе, и вода
// остаётся тем, чем она нарисована в текстуре карты (см. WorldScreen).
bool ready(Detail detail);

// Текстура — общая на весь клиент (SpriteAtlas::page): вода лежит на том же
// листе, что и всё остальное, потому что рисуется вперемешку с ним.
const Texture2D& atlas(Detail detail);

// Ступень глубины для строки листа.
int depthStep(float depth);

// Какое разводье лежит на этой клетке. От клетки, а не от случая: случай
// пересчитывался бы каждый кадр, и река бы кипела.
int variantOf(int x, int y);

// Какой кадр показывать сейчас. Часы — тик мира, а не время на стене (в
// отличие от качания дерева и травы): дерево качает ветер, он дует и в
// остановленном мире, а воду двигает сам мир — остановленный обязан замереть
// весь. Чем быстрее течение, тем чаще меняются кадры.
int frameOf(const Flow& flow, std::uint64_t tick);

// Где в атласе лежит нужный кадр. Направление разбирается здесь же:
// нарисованы три течения из восьми (вбок, вниз, наискось), остальные пять
// получаются отражением куска — по горизонтали, по вертикали или обоими
// разом. Кадры внутри вида сдвинуты ВДОЛЬ течения, поэтому отражённые бегут в
// отражённую сторону сами, без второго набора рисунков.
Rectangle source(Detail detail, int depth, const Flow& flow, int variant, int frame);

} // namespace WaterSprites
