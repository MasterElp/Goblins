#pragma once

#include <raylib.h>

// Рисунки травы и кустов: три возраста по два кадра качания, свои цвета на
// каждый вид.
//
// Оба здесь, а не порознь, потому что на карте они одно и то же: растение,
// сидящее в клетке ЦЕЛИКОМ. Данные у них общие (вид на клетке да развитость),
// рисуются они одним проходом и одной парой строк в WorldScreen, и порознь
// два таких файла отличались бы только именем ресурса.
//
// Дерево при этом живёт отдельно (TreeSprites), и не по недосмотру: оно из
// клетки ТОРЧИТ вверх, занимает две и потому рисуется в обходе по строкам,
// где важен порядок наложения. Трава и куст в этом порядке не участвуют
// вовсе — им нечем заслонять соседа.
//
// Зачем рисунок, когда есть подмешка цвета в текстуру карты. Подмешка
// (TileColors::plant, ::bush) отвечает на вопрос "тут луг" и видна на любом
// масштабе, вплоть до карты, вписанной в окно. Рисунок отвечает на другой —
// "какая тут трава и что с этим кустом", — и появляется, только когда клетка
// достаточно крупная, чтобы его разглядеть. Подмешку он не отменяет: сквозь
// былинки видно землю, её влажность и её камень, и это ровно то, ради чего
// подмешка слабая.
//
// Сами рисунки здесь не живут: они лежат в ресурсах (assets/sprites/grass.spr
// и bush.spr, см. Assets.hpp), а здесь — только то, что знает о растениях
// именно клиент: сколько у них возрастов, какого цвета листва у какого вида и
// с какой скоростью их качает ветер.
namespace PlantSprites {

// Размер кадра — ровно клетка. Шестнадцать, как и у всех прочих рисунков:
// это ClientConfig::tile_size по умолчанию, то есть при обычном масштабе
// рисунок ложится пиксель в пиксель.
constexpr int kSize = 16;

// Возрасты: росток, подрост, взрослое. Три, и границы те же, что у дерева
// (TreeSprites::stageOf), — не совпадение, а одно правило на все растения:
// треть шкалы это самая мелкая разница, которую глаз ловит без
// разглядывания.
constexpr int kStages = 3;

// Кадров качания. Пара: растение не ходит, оно качается, и всё, что нужно
// показать, — что оно живое.
constexpr int kFrames = 2;

// Кустиков травы на каждый возраст. Три, и это не украшение: с одним весь луг
// выходил расчёской — былинки во всех клетках стояли в одних и тех же
// столбцах, и через десяток клеток это читалось не травой, а штриховкой.
//
// У куста такого нет и не нужно: кустов на карте единицы, они стоят порознь,
// и одинаковость двух соседних в глаза не бросается — в отличие от луга,
// который тянется на пол-экрана.
constexpr int kGrassVariants = 3;

// Есть ли чем рисовать. false — ресурс не нашёлся или в нём не хватает
// кадров; клетка тогда остаётся тем, чем она нарисована в самой текстуре
// карты, — подмешкой цвета (см. MapTexture). Тот же предмет, изображённый
// настолько подробно, насколько его видно.
bool grassReady();
bool bushReady();

// Атласы: строка — вид растения, столбец — кадр. Пекутся при первом
// обращении (нужен уже созданный GL-контекст) и живут до конца работы окна —
// как и текстура карты, намеренно не выгружаются: raylib освобождает свои
// ресурсы сам при CloseWindow.
//
// Атласа два, а не один, потому что раскрасок у них разное число: у травы
// двенадцать видов, у куста четыре, и общий лист заставил бы печь травяные
// кадры в кустовых цветах и наоборот.
const Texture2D& grassAtlas();
const Texture2D& bushAtlas();

// Где в атласе лежит нужный кадр.
Rectangle grass(int species, int stage, int variant, int frame);
Rectangle bush(int species, int stage, int frame);

// Какой кустик травы стоит на этой клетке. От клетки, а не от случая: случай
// пересчитывался бы каждый кадр, и луг бы кипел.
int variantOf(int x, int y);

// Ягоды — отдельным кадром ПОВЕРХ куста, как куча материала поверх площадки
// (BuildSprites::material): куст один и тот же, обобран он или полон.
// Кадров два, горсть и полный куст, и берутся они по числу ягод на клетке —
// счётному, как оно и приходит в слое.
Rectangle berries(int count);

// Возраст по развитости растения (0..1, как она приходит в снапшоте).
int stageOf(float growth);

// Какой кадр качания показывать этой клетке сейчас. Фаза зависит от клетки —
// иначе весь луг качался бы разом, как один предмет, — и берётся она от
// клетки, а не от номера растения: номер меняется при загрузке мира, а
// клетка нет (та же причина, что и у дерева, TreeSprites::frameOf).
//
// Часы здесь — время на стене, а не тик мира, и это тоже как у дерева:
// траву качает ветер, а он дует и в остановленном мире. У гоблина наоборот —
// он двигается сам, и остановленный мир обязан его заморозить.
int frameOf(int x, int y, double seconds);

} // namespace PlantSprites
