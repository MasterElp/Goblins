// Средний геном мира по времени: три графика друг под другом — трава,
// травоядные, хищники, — и на каждом по линии на черту.
//
// Отвечает на вопрос, которого не задаёт ни один другой экран: КУДА мир
// едет. Численность (PopulationGraph) показывает, кого сколько; карточка
// существа — каким выпал вот этот зверь; а здесь видно, как отбор
// перекладывает бюджет вида из одной черты в другую за тысячи тиков —
// стадо, поголовно уходящее в скорость, потому что его едят, или трава,
// сдающая долголетие ради семян.
//
// Все черты кладутся на одну шкалу "вложения" 0..1 — ту самую, которой
// геном и порождается (core/generation/Genetics.hpp): 0 — худшее для
// существа значение черты, 1 — лучшее. Иначе их не положить рядом вовсе:
// предельный возраст живёт в тысячах тиков, а скорость — в тысячных
// клетки, и одна общая ось по значению превратила бы все кривые, кроме
// возраста, в прямую по нулю. Границы вложения приходят с сервера вместе
// с именами черт — сам клиент состава генома не знает (07_TechStack.md,
// п.6).
