#pragma once

#include <raylib.h>

// Рисунки построек: навес, подстилка, колышки замысла и куча принесённого
// материала.
//
// Постройка — второе после дерева, что не выражается цветом клетки. Причина
// у неё та же, что у рощи: навес из клетки ТОРЧИТ ВВЕРХ, и его крыша
// выходит на клетку выше. А вот причина рисовать её подробно — своя, и она
// важнее: постройка это единственное на карте, что сделано РУКАМИ, и лагерь
// должен читаться лагерем, а не пятном другого оттенка. Кроме того, у
// постройки есть прочность, и по силуэту сразу видно, стоит ли перед тобой
// остов, половина или целое, — чего никаким оттенком не сказать.
//
// Сам рисунок здесь не живёт: он лежит в ресурсах (assets/sprites/build.spr,
// см. Assets.hpp), а здесь — только то, что знает о постройках именно
// клиент: сколько у них ступеней прочности и какого цвета солома и жердь.
namespace BuildSprites {

// Размер одного кадра — тот же, что у дерева, и по той же причине: клетка в
// ширину, две в высоту, шестнадцать пикселей на клетку при обычном
// масштабе.
constexpr int kWidth = 16;
constexpr int kHeight = 32;

// Ступеней прочности. Три: остов, половина, целое. Больше не нужно —
// четвёртая отличалась бы от соседних меньше, чем толщина жерди, а закон
// мира и так говорит о постройке не "готово/не готово", а числом
// (BuildingComponent).
constexpr int kStages = 3;

// Есть ли чем рисовать. false — ресурс не нашёлся или в нём не хватает
// кадров; постройка тогда остаётся тем, чем она нарисована в самой текстуре
// карты, — оттенком клетки (см. TileColors::canopy).
bool ready();

// Атлас: раскраска одна, столбец — кадр. Печётся при первом обращении
// (нужен уже созданный GL-контекст) и живёт до конца работы окна.
const Texture2D& atlas();

// Где в атласе лежит нужный кадр. stage — ступень прочности, 0..kStages-1.
Rectangle canopy(int stage);
Rectangle bedding(int stage);
// Колышки замысла: kind — то же число, что едет в слое "site" (1 навес,
// 2 подстилка).
Rectangle site(int kind);
// Куча принесённого на площадку материала, ещё не пущенного в дело.
Rectangle material();

// Ступень по прочности (0..1, как она приходит в снапшоте). Нулевая
// прочность сюда не приходит вовсе: постройки с нулём в мире нет.
int stageOf(float condition);

} // namespace BuildSprites
