#pragma once

#include <filesystem>
#include <string>
#include <string_view>
#include <vector>

// Ресурсы клиента: рисунки, лежащие файлами рядом с исполняемым, а не
// зашитые в код.
//
// Рисунок в исходнике хорош ровно до второго рисунка. Дерево, гоблин,
// зверь, постройка, значок в панели — у каждого свои кадры и свои
// возрасты, и первый же из них, набранный строками в .cpp, потянет за
// собой второй, а вместе они превратят экран в склад пиксель-арта. Файл
// же правится без пересборки, лежит там, где его ищут, и виден в diff'е
// не хуже кода — он и есть текст.
//
// Формат нарочно текстовый, а не PNG. Причин две, и обе про работу с ним,
// а не про размер: рисунок в знаках правится любым редактором и читается
// в diff'е построчно ("крона стала шире на пиксель" — это одна строка
// изменений, а не "картинка стала другой"), и, главное, знак — это не
// цвет, а РОЛЬ пикселя: крона, тень, ствол. Цвет к роли подбирает уже
// клиент — тем же деревом он рисует пять видов, а гоблинов раскрасит по
// племени, ничего не перерисовывая.
namespace Assets {

// Разобранный рисунок: несколько кадров одного размера, каждый — сетка
// знаков высотой height и шириной width.
//
// Что означает знак, слой ресурсов не знает и знать не должен: он читает
// сетку, а смысл знакам придаёт тот, кто рисунок заказал (см. палитру в
// SpriteAtlas). Поэтому здесь нет ни цветов, ни прозрачности — только
// буквы.
struct SpriteSheet {
    int width = 0;
    int height = 0;
    // Имена кадров в том порядке, в каком они лежат в файле.
    std::vector<std::string> names;
    // Сам рисунок: frames[кадр][строка] — строка ровно width знаков.
    std::vector<std::vector<std::string>> frames;

    bool empty() const { return frames.empty(); }
    // Номер кадра по имени; -1 — такого кадра в файле нет. Искать по
    // имени, а не полагаться на порядок: порядок в файле — дело того, кто
    // рисует, и менять его он вправе.
    int frameIndex(std::string_view name) const;
};

// Каталог ресурсов — рядом с исполняемым файлом, как и config.json
// (shared/platform/ExecutablePath.hpp): рабочая директория не то же самое,
// что расположение exe, и клиент, запущенный ярлыком, иначе не нашёл бы
// ничего.
std::filesystem::path directory();

// Рисунок по имени: "tree" читается из assets/sprites/tree.spr. Один раз —
// дальше отдаётся из памяти.
//
// Файла нет или он испорчен — возвращается пустой лист и одна строка в
// stderr. Не ошибка и не падение: рисовать без картинки умеет каждый, кто
// её просит (см. WorldScreen — там дерево без рисунка становится тем же
// прямоугольником, каким оно рисуется на мелком масштабе). Ресурс — это
// то, чем показывают мир, а не то, из чего он состоит.
const SpriteSheet& sprites(const std::string& name);

} // namespace Assets
