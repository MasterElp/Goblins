#pragma once

#include <cstdint>
#include <string>

#include <raylib.h>

// Рисунки хищников: волк сбоку, четыре занятия по два кадра, два возраста,
// свои цвета на каждый вид.
//
// Волком рисуется ВСЯКИЙ хищник, каким бы ни был его вид в мире, и это не
// упрощение, а тот же приём, каким одним рисунком рисуются пять видов
// деревьев и шесть племён гоблинов: вид опознаётся цветом, а не силуэтом.
// Силуэт же говорит то, что у всех хищников общее, — четыре ноги, морда
// вперёд, хвост, — и говорит это с одного взгляда, чего кружок не мог.
//
// Травоядное при этом осталось значком, и не по недосмотру. О звере, который
// ест траву, карта отвечает на один вопрос: сколько его и какой он величины,
// — и на него значок отвечает лучше рисунка, потому что честно вырождается в
// точку на отдалённой карте. О хищнике спрашивают другое: где он и не крадётся
// ли он сейчас, — и вот на это кружок не отвечал ничем.
//
// Сам рисунок здесь не живёт: он лежит в ресурсах (assets/sprites/wolf.spr,
// см. Assets.hpp), а здесь — только то, что знает о хищниках именно клиент:
// какие бывают занятия, каким кадром рисуется какое желание и с какой
// скоростью сменяются кадры.
namespace WolfSprites {

// Кадр — ровно клетка, как у гоблина и по той же причине: зверь по земле
// ходит, а не торчит из клетки вверх, и на одной клетке их может быть
// несколько.
constexpr int kSize = 16;

// Возрасты: щенок и взрослый. Два, как у гоблина, и порог тот же — тот,
// которым мир отделяет взрослого (kBreedingGrowth в AnimalSystem).
constexpr int kStages = 2;

// Кадров на занятие. Пара: показать нужно не походку, а что зверь живой и
// чем он занят.
constexpr int kFrames = 2;

// Занятия. Их четыре, и одно из них есть только у хищника.
enum class Pose {
    Stand = 0, // стоит: ничего не гонит, либо ищет пару
    Walk,      // идёт
    Stalk,     // КРАДЁТСЯ: идёт за добычей, прижавшись к земле
    Feed,      // морда у земли: ест или пьёт
};
constexpr int kPoses = 4;

// Есть ли чем рисовать. false — ресурс не нашёлся или в нём не хватает
// кадров; хищник тогда остаётся тем же значком, каким он рисуется на мелком
// масштабе (см. WorldScreen).
bool ready();

// Атлас: строка — вид хищника, столбец — кадр. Печётся при первом обращении
// (нужен уже созданный GL-контекст) и живёт до конца работы окна.
const Texture2D& atlas();

// Где в атласе лежит нужный кадр. facing — сторона: >= 0 мордой вправо,
// < 0 влево (кусок возвращается отрицательной ширины, и DrawTexturePro
// отражает его сам).
//
// Видов со спины и навстречу у зверя нет вовсе, в отличие от гоблина:
// четвероногое спереди — это морда и четыре точки, и такой кадр не прибавил
// бы к клетке ничего. Отвесный шаг рисуется боковым видом.
Rectangle source(int species, Pose pose, int stage, int frame, int facing);

// Возраст по развитости тела (0..1, как она приходит в снапшоте).
int stageOf(float growth);

// Чем рисовать зверя, у которого такое желание. walking — сделал ли он шаг
// только что (см. walkingNow).
//
// Желания мало и здесь: "хочу есть" одинаково верно и для крадущегося за
// полкарты, и для стоящего над тушей. Зато вместе с шагом оно и даёт то
// единственное, ради чего хищнику дан свой кадр: идущий ЗА ЕДОЙ хищник
// охотится, и это видно раньше, чем он догонит.
Pose poseOf(const std::string& desire, bool walking);

// Идёт ли зверь сейчас: давно ли был его последний шаг. stepTick — тик, на
// котором клиент видел шаг (WorldState::Animal), 0 — не видел ни разу.
//
// Памяти три тика, а не четыре, как у гоблина: хищник быстр (скорость
// 900..1800 тысячных клетки за тик, AnimalGenetics — то есть шаг почти
// каждый тик), и дольше помнить значило бы показывать бегущим того, кто уже
// встал над добычей.
bool walkingNow(std::uint64_t stepTick, std::uint64_t tick);

// Какой кадр показывать этому зверю сейчас. Часы — тик мира, как у гоблина:
// зверь двигается сам, и остановленный мир обязан замереть весь. Фаза от
// постоянного номера зверя — иначе вся стая переступала бы разом.
int frameOf(std::uint64_t id, std::uint64_t tick);

} // namespace WolfSprites
