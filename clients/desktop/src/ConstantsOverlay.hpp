#pragma once

#include "NetworkClient.hpp"

// Оверлей "константы законов мира" — то, что НЕ настраивается: числа,
// зашитые в ядро (core/Diagnostics.hpp) и присланные сервером в world_init.
// Отдельный оверлей, а не строки в панели генерации, по двум причинам:
// панель — это то, что можно крутить, и мешать с ней нередактируемое
// значило бы врать; и нужны эти числа одинаково на обоих экранах — и когда
// подбираешь генерацию, и когда смотришь на идущую симуляцию.
//
// Пока система настраивается, это единственный способ сопоставить
// поведение мира с числом, не открывая исходники.
namespace ConstantsOverlay {

// Обрабатывает клавишу C и рисует оверлей поверх всего, если он включён.
// Состояние "открыт/закрыт" живёт внутри и общее на все экраны: перейдя с
// генерации на симуляцию с открытым оверлеем, его видишь и там — это одни
// и те же числа про один и тот же мир.
//
// allowToggle = false, когда на экране есть поле ввода текста (имя мира
// при сохранении): иначе набранная в имени буква "C" открывала бы оверлей.
// Рисование при этом продолжается — закрыть уже открытый оверлей
// пользователь должен мочь всегда... но и это через allowToggle, поэтому
// поле ввода на экране симуляции появляется только поверх закрытого
// оверлея (оверлей перекрывает весь экран и своё поле ввода прячет).
void update(const WorldState& state, bool allowToggle = true);

// Открыт ли оверлей — экрану это нужно, чтобы не реагировать на мышь и
// горячие клавиши под ним.
bool visible();

} // namespace ConstantsOverlay
