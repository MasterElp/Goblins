#pragma once

#include <span>
#include <string>
#include <vector>

#include <raylib.h>

#include "Assets.hpp"

// Рисунок из ресурсов — в текстуру, которой можно рисовать.
//
// Между ресурсом и экраном стоит один вопрос: каким цветом. Знак в файле —
// это роль пикселя (крона, тень, ствол), а не цвет, и одному и тому же
// рисунку клиент даёт столько раскрасок, сколько ему нужно: пять видов
// деревьев, столько же племён гоблинов, две стороны в драке. Здесь эти
// раскраски и запекаются — все разом, в одну текстуру.
//
// Одна текстура на всё, а не по текстуре на раскраску: привязка текстуры
// стоит дороже самой отрисовки, а роща — это сотни прямоугольников за
// кадр. Строка атласа — раскраска, столбец — кадр.
namespace SpriteAtlas {

// Чем красить знак. Таблица, а не функция: раскраска — это данные, её
// видно целиком и её можно положить рядом с тем, к чему она относится.
// Знак, которого в таблице нет, остаётся прозрачным — так в рисунке и
// выражается пустота.
struct Ink {
    char symbol = '.';
    Color color{0, 0, 0, 0};
};
using Palette = std::vector<Ink>;

// Запечённый рисунок. Живёт столько же, сколько окно: текстура намеренно
// не выгружается в деструкторе — при закрытии окна raylib освобождает свои
// ресурсы сам, а UnloadTexture после CloseWindow обращался бы к
// уничтоженному GL-контексту (та же причина, что и у MapTexture::Cache).
class Sheet {
public:
    // Запечь. Пустой лист ресурсов или пустой список раскрасок — не
    // ошибка: Sheet просто остаётся непригодным (ready() == false), и
    // вызывающая сторона рисует тем, чем рисовала бы без картинки вовсе.
    void build(const Assets::SpriteSheet& art, std::span<const Palette> palettes);

    bool ready() const { return ready_; }
    const Texture2D& texture() const { return texture_; }
    int frameCount() const { return frames_; }
    int paletteCount() const { return palettes_; }

    // Где в атласе лежит кадр frame в раскраске palette. Номера вне
    // пределов заворачиваются остатком, а не падают: вид с номером больше,
    // чем раскрасок, — это вопрос к настройкам мира, а не повод уронить
    // клиент.
    Rectangle source(int palette, int frame) const;

    // Ширина одного кадра. Наружу нужна тому, кто выбирает между мелким и
    // крупным листом: порог — это и есть кадр крупного (см. Detailed).
    int width() const { return width_; }

private:
    Texture2D texture_{};
    bool ready_ = false;
    int width_ = 0;
    int height_ = 0;
    int frames_ = 0;
    int palettes_ = 0;
};

// Запечённый лист, у которого кадры зовутся по именам, а не по номерам.
//
// Здесь лежит всё, что у рисунков ОБЩЕЕ, и ровно оно: прочитать ресурс,
// запечь раскраски, разыскать кадры по именам и решить, годен ли лист
// вообще. Своим у дерева и у постройки остаётся только то, чем они
// отличаются, — какие раскраски, какие кадры и что означает возраст.
//
// Не хватает хоть одного названного кадра — лист негоден целиком
// (ready() == false), и это правило важнее, чем кажется. Показать вместо
// взрослого дерева росток, а вместо целого навеса остов — хуже, чем не
// показать ничего: оно выглядит как рисунок и врёт про мир. Рисовать
// тогда нечем, и вызывающая сторона обходится тем же, чем обходится на
// мелком масштабе.
struct Baked {
    Sheet sheet;
    // Номера кадров в листе в том порядке, в каком их спросили.
    std::vector<int> frames;
    bool complete = false;

    // Где лежит кадр с этим номером в списке имён, в этой раскраске.
    // Номера вне пределов заворачиваются, а не падают (см. Sheet::source).
    Rectangle source(int palette, int frame) const;
};

// Подробность рисунка. Листов у каждого рисунка ДВА, и это не запас на
// будущее: клетка на экране бывает и в два пикселя (карта целиком), и в
// шестьдесят четыре (вплотную), и один рисунок не годится на оба конца —
// мелкий, растянутый вчетверо, распадается на квадраты, а крупный, ужатый
// вдвое, теряет ровно ту подробность, ради которой нарисован.
enum class Detail { Coarse, Fine };

// Пара листов одного и того же рисунка: мелкий и крупный.
//
// Механизм общий на всех — дерево, траву, куст, зверя, гоблина, — и обязан
// быть общим: разъедься правило выбора листа между ними, и на одном и том же
// масштабе половина карты рисовалась бы мелко, а половина крупно.
struct Detailed {
    Baked coarse;
    Baked fine;

    // Годен ли этот лист. Мелкий негоден — рисовать нечем вовсе; крупный
    // негоден — просто всегда берётся мелкий, и это обычный путь, а не беда:
    // второй лист не обязателен.
    bool ready(Detail detail) const;
    const Baked& sheet(Detail detail) const;
    const Texture2D& texture(Detail detail) const;

    // Какой лист брать при такой клетке на экране. Крупный — только когда
    // клетка не мельче его кадра: ужатый крупный лист теряет ту самую
    // подробность, ради которой нарисован, и выглядит грязнее мелкого.
    Detail detailFor(float tileSize) const;
};

// Запечь оба листа разом: art и art + "_fine". Имена кадров и раскраска у них
// одни и те же — разойтись им нельзя, иначе предмет менял бы облик от
// поворота колеса мыши.
Detailed bakeDetailed(const std::string& art, std::span<const Palette> palettes,
                      std::span<const char* const> frameNames);

// Запечь рисунок по имени ресурса. Печь можно только при созданном
// GL-контексте, поэтому вызывается это лениво — из статической переменной
// внутри того, кто рисунком пользуется.
Baked bake(const std::string& art, std::span<const Palette> palettes, std::span<const char* const> frameNames);

} // namespace SpriteAtlas
