#pragma once

#include <span>
#include <string>
#include <vector>

#include <raylib.h>

#include "Assets.hpp"

// Рисунок из ресурсов — в текстуру, которой можно рисовать.
//
// Между ресурсом и экраном стоит один вопрос: каким цветом. Знак в файле —
// это роль пикселя (крона, тень, ствол), а не цвет, и одному и тому же
// рисунку клиент даёт столько раскрасок, сколько ему нужно: пять видов
// деревьев, столько же племён гоблинов, две стороны в драке. Здесь эти
// раскраски и запекаются — все разом.
//
// Текстура на весь клиент ОДНА, и это главное, что тут есть. Дерево, трава,
// куст, вода, зверь, гоблин, постройка лежат на одном общем листе, потому что
// смена привязки текстуры стоит дорого, а рисуются они ВПЕРЕМЕШКУ: обход идёт
// по клеткам, и на одной клетке подряд встречаются трава, навес и дерево.
//
// Замерено на видимой сетке 80x45: восемью листами выходило 3313
// прямоугольников и 1242 смены привязки — по смене на каждые два-три
// прямоугольника, и весь кадр стоил 31.7 мс против 7.1 мс тем же порядком с
// одной текстурой. Дело было не в порядке обхода (его ломать нельзя: навес из
// нижней строки обязан лечь поверх дерева из верхней), а именно в числе
// текстур.
namespace SpriteAtlas {

// Чем красить знак. Таблица, а не функция: раскраска — это данные, её
// видно целиком и её можно положить рядом с тем, к чему она относится.
// Знак, которого в таблице нет, остаётся прозрачным — так в рисунке и
// выражается пустота.
struct Ink {
    char symbol = '.';
    Color color{0, 0, 0, 0};
};
using Palette = std::vector<Ink>;

// Куда на общем листе лёг рисунок со всеми своими раскрасками.
//
// Кадры уложены подряд и заворачиваются на следующую строку блока, а не тянутся
// одной длинной полосой, как было, пока лист был у каждого рисунка свой: полоса
// в сорок восемь кадров по тридцать два пикселя — это полторы тысячи пикселей в
// ширину, и на общем листе такая полоса диктовала бы его ширину всем остальным.
struct Placement {
    int x = 0;
    int y = 0;
    int frameWidth = 0;
    int frameHeight = 0;
    int columns = 0;  // кадров в строке блока
    int frames = 0;
    int palettes = 0;
    bool ready = false;

    // Где лежит кадр frame в раскраске palette. Номера вне пределов
    // заворачиваются остатком, а не падают: вид с номером больше, чем
    // раскрасок, — это вопрос к настройкам мира, а не повод уронить клиент.
    Rectangle source(int palette, int frame) const;
};

// Общий лист. Живёт столько же, сколько окно: текстура намеренно не
// выгружается в деструкторе — при закрытии окна raylib освобождает свои
// ресурсы сам, а UnloadTexture после CloseWindow обращался бы к уничтоженному
// GL-контексту (та же причина, что и у MapTexture::Cache).
class Page {
public:
    // Положить рисунок на лист и сказать, куда он лёг. Пустой лист ресурсов
    // или пустая раскраска — не ошибка: возвращается негодное место
    // (ready == false), и вызывающая сторона рисует тем, чем рисовала бы без
    // картинки вовсе.
    //
    // Лист растёт вниз и НИКОГДА не переставляет уже положенное: места,
    // выданные раньше, остаются верными, поэтому докладывать можно лениво, по
    // мере того как до каждого рисунка доходит дело.
    Placement place(const Assets::SpriteSheet& art, std::span<const Palette> palettes);

    // Готовая текстура. Не const: тут же и заливается, если с прошлого раза на
    // лист что-то положили. Заливать в place() нельзя — за один кадр рисунков
    // кладётся несколько, и лист уезжал бы на видеокарту столько раз, сколько
    // их легло.
    const Texture2D& texture();

private:
    void upload();

    Texture2D texture_{};
    bool loaded_ = false;
    bool dirty_ = false;
    int height_ = 0;
    std::vector<Color> pixels_;
};

// Тот самый единственный лист.
Page& page();

// Запечённый рисунок: место на общем листе плюс перевод имён кадров в их
// номера.
//
// Кадры ищутся ПО ИМЕНИ, а не по порядку в файле: порядок — дело того, кто
// рисует, и менять его он вправе. Не нашлось хоть одного имени — complete
// становится false, и рисунком не пользуются вовсе: зверь, стоящий вместо
// того, чтобы бежать, хуже значка, потому что выглядит как ответ, а отвечает
// неверно.
struct Baked {
    Placement placement;
    std::vector<int> frames;
    bool complete = false;

    Rectangle source(int palette, int frame) const;
    const Texture2D& texture() const { return page().texture(); }
};

// Подробность рисунка. Листов у каждого рисунка ДВА, и это не запас на
// будущее: клетка на экране бывает и в два пикселя (карта целиком), и в
// шестьдесят четыре (вплотную), и один рисунок не годится на оба конца —
// мелкий, растянутый вчетверо, распадается на квадраты, а крупный, ужатый
// вдвое, теряет ровно ту подробность, ради которой нарисован.
//
// Листа два, а текстура по-прежнему одна: оба лежат на общем листе, просто
// разными блоками.
enum class Detail { Coarse, Fine };

// Пара рисунков одного и того же предмета: мелкий и крупный.
//
// Механизм общий на всех — дерево, траву, куст, зверя, гоблина, — и обязан
// быть общим: разъедься правило выбора между ними, и на одном и том же
// масштабе половина карты рисовалась бы мелко, а половина крупно.
struct Detailed {
    Baked coarse;
    Baked fine;

    // Годен ли этот рисунок. Мелкий негоден — рисовать нечем вовсе; крупный
    // негоден — просто всегда берётся мелкий, и это обычный путь, а не беда:
    // второй рисунок не обязателен.
    bool ready(Detail detail) const;
    const Baked& sheet(Detail detail) const;
    const Texture2D& texture(Detail detail) const;

    // Какой рисунок брать при такой клетке на экране. Крупный — только когда
    // клетка не мельче его кадра: ужатый крупный теряет ту самую подробность,
    // ради которой нарисован, и выглядит грязнее мелкого.
    Detail detailFor(float tileSize) const;
};

// Запечь рисунок по имени ресурса. Печь можно только при созданном
// GL-контексте, поэтому вызывается это лениво — из статической переменной
// внутри того, кто рисунком пользуется.
Baked bake(const std::string& art, std::span<const Palette> palettes,
           std::span<const char* const> frameNames);

// Запечь оба рисунка разом: art и art + "_fine". Имена кадров и раскраска у
// них одни и те же — разойтись им нельзя, иначе предмет менял бы облик от
// поворота колеса мыши.
Detailed bakeDetailed(const std::string& art, std::span<const Palette> palettes,
                      std::span<const char* const> frameNames);

} // namespace SpriteAtlas
