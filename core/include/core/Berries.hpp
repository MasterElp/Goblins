#pragma once

#include <algorithm>
#include <cstddef>
#include <cstdint>

#include "core/Scale.hpp"
#include "core/components/BerryComponent.hpp"

namespace goblins {

// Как на кусте зреют и как с него берут ягоды — ОДИН закон на всех, кто его
// спрашивает: PlantSystem (растить), GoblinSystem (рвать), наблюдатель
// (рисовать). Живёт здесь, а не внутри системы, по той же причине, что и
// core/Rest.hpp с core/Knowledge.hpp: у закона больше одного вызывающего, а
// две копии одного закона расходятся молча (CLAUDE.md).
//
// Про существ он не знает ничего и принимает простые числа — развитость
// куста, крупицы в клетке, сколько ягод хотят взять. Кто именно рвёт (гоблин
// сегодня, кто-то ещё завтра), закону безразлично.

// Биомасса одной ягоды — в той же шкале, в какой меряется развитость
// растения и мясо туши (core/Scale.hpp), иначе съеденное пришлось бы
// переводить на границе, а перевод — это место, где теряется тысяча.
//
// Величина выбрана из укуса: bite_size живёт в 50..450 тысячных от размера
// тела (AnimalGenetics.hpp), то есть ягода — примерно один укус взрослого.
// Меньше — и сбор превратился бы в сотню тиков стояния у куста; больше — и
// одна ягода кормила бы гоблина досыта, а ягодник перестал бы быть местом,
// куда ходят.
constexpr int kBerryMass = 200;

// Сколько ягод держит полностью выросший куст. Дюжина — это два-три сытых
// гоблина: ягодник кормит малую группу, а не племя. Отсюда и расхождение
// племён по карте: за одним кустом всем не прокормиться.
constexpr int kBerryMax = 12;

// Ниже этой развитости куст не плодоносит вовсе: подрост сперва растёт.
// Иначе первый же проросток кормил бы собой, и ягодник не отличался бы от
// луга ничем, кроме имени.
constexpr int kBerryMaturity = 400;

// Раз во сколько тиков на кусте прибывает ягода. Срок, а не скорость: одна
// штука за много тиков — величина, которую целыми числами иначе не выразить
// (core/Scale.hpp), а накопитель ради неё заводить незачем.
//
// Число подобрано против того, как быстро ягоды съедают: полный куст
// объедается за десяток тиков, а отрастает дюжина ягод за две с лишним
// тысячи. Ягодник обязан наполняться МЕДЛЕННО — иначе к нему не нужно
// возвращаться, достаточно стоять рядом.
constexpr int kBerryPeriod = 180;

// Крупица минералов на каждые столько ягод. Не за каждую: при
// kPlantMinerals = 4 (столько крупиц в целом травяном теле) ягода за
// крупицу означала бы, что полный куст стоит земле трёх трав, и ягодники
// выедали бы свою клетку досуха.
//
// Из этого же следует, где ягодники растут: на бедной клетке куст упирается
// в ближайшую "платную" ягоду и дальше не зреет, на богатой набирает
// полный. Ягодник сам собой оказывается на богатой земле, и это не правило
// расстановки, а следствие обмена веществом.
constexpr int kBerriesPerGrain = 4;

// Сколько ягод вообще может висеть на кусте такой развитости.
inline int berryCapacity(int growth) {
    return kBerryMax * std::clamp(growth, 0, kFull) / kFull;
}

// Пора ли этому кусту уронить ягоду. Сдвиг по номеру клетки — чтобы кусты
// не наливались все разом в один тик: срок один на всех, а очередь у
// каждого своя. Ничего для этого помнить не надо, и потому система не
// хранит состояния между тиками (05_Entity.md, п.3).
inline bool berryDue(std::uint64_t tick, std::size_t cell) {
    return (tick + static_cast<std::uint64_t>(cell)) % static_cast<std::uint64_t>(kBerryPeriod) == 0;
}

// Созревание одной ягоды. cellMinerals — крупицы клетки под кустом, из них
// же ягода и делается; закон правит их сам, потому что иначе плата за ягоду
// оказалась бы в другом файле, чем сама ягода.
//
// false — не созрела: куст мал, ягод и так полно, или в земле нет крупицы
// ровно тогда, когда она понадобилась.
inline bool ripenBerry(BerryComponent& bush, int growth, int& cellMinerals) {
    if (growth < kBerryMaturity || bush.berries >= berryCapacity(growth)) {
        return false;
    }
    // Платная ли эта ягода, видно из самого счёта — накопитель для такого не
    // нужен: остаток от деления и есть очередь.
    const bool paid = (bush.berries + 1) % kBerriesPerGrain == 0;
    if (paid) {
        if (cellMinerals <= 0) {
            return false;
        }
        --cellMinerals;
        ++bush.minerals;
    }
    ++bush.berries;
    return true;
}

// Сколько ягод и сколько крупиц вместе с ними досталось тому, кто рвал.
struct BerryPick {
    int berries = 0;
    int minerals = 0;
};

// Сорвать до want ягод. Развитость куста при этом НЕ меняется — в этом всё
// отличие ягодника от луга, и ради него закон и написан отдельно от
// объедания травы.
//
// Крупицы уходят долей от сорванного: сколько ягод взяли, столько вещества
// с ними и ушло.
inline BerryPick pickBerries(BerryComponent& bush, int want) {
    BerryPick picked;
    if (want <= 0 || bush.berries <= 0) {
        return picked;
    }
    picked.berries = std::min(want, bush.berries);
    picked.minerals = bush.minerals * picked.berries / bush.berries;
    bush.berries -= picked.berries;
    bush.minerals -= picked.minerals;
    return picked;
}

} // namespace goblins
