#pragma once

namespace goblins {

// С какой прочности забор перестаёт быть намерением и становится преградой —
// ОДИН закон на всех, кто спрашивает: проходимость (core/Path.hpp), рисование,
// меры. Про существ не знает ничего и принимает числа.
//
// --- Чего здесь больше нет ---
//
// Здесь жил закон КРАЯ ОБЖИТОГО: какая клетка снаружи (по утоптанности) и
// какая доля подходов к лагерю не закрыта. Он существовал ради одного
// единственного вызывающего — решения гоблина, где воткнуть кол и насколько
// его гонит городиться, — и ушёл вместе с этим решением
// (docs/10_Goblins.md, "Забор строится, но никто его не хочет").
//
// Возвращать его, если гоблину снова понадобится хотеть забор, надо целиком и
// сюда же: край обжитого — свойство МИРА, а не разума, и два его определения
// в разных местах разъедутся молча. В истории он записан подробно, вместе с
// доводами за порог утоптанности против разности и за то, почему тропу нужно
// закрывать наравне с целиной.

// Половина полной прочности — прямое следствие закона построек: "навес
// прочностью в половину — это половина навеса" (BuildingComponent). Ниже
// половины через плетень перешагивают, выше — обходят.
constexpr int kFenceShut = 500;

// Держит ли забор такой прочности.
inline bool fenceShuts(int condition) {
    return condition >= kFenceShut;
}

} // namespace goblins
