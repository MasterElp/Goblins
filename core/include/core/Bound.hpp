#pragma once

#include <algorithm>

#include "core/Scale.hpp"

namespace goblins {

// Край обжитого: какая клетка снаружи и насколько сторона открыта — ОДИН
// закон на всех, кто спрашивает. Про существ не знает ничего и принимает
// числа.
//
// Чем именно край закрывают — дело core/Build.hpp; здесь только про то, ГДЕ
// он проходит.
//
// --- Почему утоптанность ---
//
// Кольцо забора вокруг лагеря — явление высокого порядка, и проектировать его
// напрямую нельзя (02_CorePrinciples.md, п.14). Значит нужно локальное
// правило, из которого кольцо получается само, и оно в мире уже лежит: КРАЙ
// ЛЮБОЙ КЛЯКСЫ ЗАМКНУТ. Лагерь — это утоптанное пятно (core/Trample.hpp), его
// край и есть кольцо, и никто его не назначает.
//
// --- Почему порог, а не разность ---
//
// "Снаружи" — это НЕЖИЛАЯ земля: та, по которой ходят мало. Не "менее
// утоптанная, чем здесь".
//
// Разность стояла здесь первой и была отвергнута замером. Довод за неё был
// такой: с порогом край уползал бы наружу вслед за самим лагерем — чем больше
// ходят, тем шире круг клеток, перешагнувших порог. Довод верен, но он
// оказался меньшей бедой из двух.
//
// Первая беда разности — ДЫРЫ, и ради них порог и заведён. Тропа, уходящая
// из лагеря, утоптана почти как лагерь, разности не даёт и внешней не
// считается; в стене на её месте оставался проход, а через проход заходит и
// зверь. Прежде это называлось "ворота получаются сами" и считалось удачей;
// но ворота, которых не закрыть, — это не ворота, а отсутствие ограды. С
// порогом тропа утоптана слабее лагеря, значит внешняя, значит её закрывают:
// гоблин перелезает руками, зверь нет.
//
// Вторая — край ПОСРЕДИ ЛАГЕРЯ. Утоптанность внутри пятна неровная: ядро под
// тысячу, бахрома шестьсот, разность четыреста — и вот "край" там, где
// никакого края нет. С порогом обе клетки свои, и края между ними не
// возникает.
//
// Чего порог НЕ вылечил — сказать честно, иначе завтра его будут винить не в
// том. Сыпь (966 клеток с плетнём при лучшей прочности 25 из ста и ни одной
// запертой) держалась и после него: 950 клеток, лучшая 19, и та не росла с
// восьмитысячного тика. Причина у сыпи была своя и совсем в другом месте —
// система собирала BuildingComponent из двух полей вместо трёх и не видела
// начатого плетня (см. GoblinSystem, fenceAt).
//
// А на довод про уползание отвечает сам закон троп — не замером, а
// арифметикой его же констант: он даёт не равновесие, а ГОНКУ. Проход
// прибавляет 60 (kTrampleStep), время снимает единицу за четыре тика
// (kTrampleRecoverPeriod) — значит земля, по которой ходят чаще раза в 240
// тиков, насыщается до полной, а по которой реже, садится в ноль.
// Промежуточных значений мир держит мало, и порог кладётся в этот провал.

// С какой утоптанности земля считается обжитой — своей.
//
// Половина полной, и это середина того провала, о котором сказано выше:
// закон троп сажает клетку либо к тысяче, либо к нулю, а середина — место,
// дальше всего отстоящее от обоих. Выше порог — меньше участок (обносится
// только хорошо обжитое ядро), ниже — больше.
constexpr int kLivedIn = 500;

// С какой прочности забор перестаёт быть намерением и становится преградой.
//
// Половина — прямое следствие закона построек: "навес прочностью в половину
// — это половина навеса" (BuildingComponent). Ниже половины через плетень
// перешагивают, выше — обходят.
constexpr int kFenceShut = 500;

// Считается ли соседняя клетка внешней. Спрашивают об этом, стоя на своей
// земле, — поэтому проверок две: своя ли она и нежилой ли сосед.
inline bool outsideOf(int troddenHere, int troddenThere) {
    return troddenHere >= kLivedIn && troddenThere < kLivedIn;
}

// Держит ли забор такой прочности.
inline bool fenceShuts(int condition) {
    return condition >= kFenceShut;
}

// Закрыт ли подход: туда либо нельзя ступить и так (вода, валун, край мира),
// либо там уже стоит забор нужной прочности.
//
// ВОТКНУТЫЙ КОЛ ЗАКРЫТЫМ НЕ СЧИТАЕТСЯ, и это стоило отдельного замера.
// Сперва он считался — рассуждение было такое: иначе гоблин, воткнув кол,
// счёл бы сторону по-прежнему открытой и воткнул бы второй рядом. Вышло
// хуже: колья вставали по всему краю за десяток тиков, открытость падала в
// ноль, нехватка исчезала — и достраивать их становилось незачем. Замер:
// двадцать шесть площадок разом, тринадцать клеток с забором и прочность
// один из ста.
//
// Кол — это замысел, а не преграда: через него проходят. Пока сторона не
// заплетена, она открыта, и нехватка держится ровно до тех пор, пока дело не
// сделано. Второй кол рядом при этом не встаёт — не потому, что сторона
// закрыта, а потому, что на клетке уже есть площадка (placeSite,
// core/Build.hpp).
inline bool approachShut(bool standableOutside, int fenceCondition) {
    return !standableOutside || fenceShuts(fenceCondition);
}

// Насколько сторона ещё открыта, 0..kFull: какая доля ВНЕШНИХ подходов не
// закрыта.
//
// Знаменатель — число внешних подходов, а не все восемь, и это несущее:
// открытость обязана дойти до нуля ровно тогда, когда сторона закрыта. Дели
// на восемь — и гоблин на краю кляксы с тремя внешними соседями никогда не
// довёл бы её ниже пяти восьмых, то есть строил бы вечно.
//
// Нет внешних подходов вовсе — ноль, а не деление: гоблин посреди лагеря
// ничего не городит, и это тот самый механизм, которым кольцо получается
// контуром, а не сплошной застройкой.
inline int opennessOf(int outsideCount, int shutCount) {
    if (outsideCount <= 0) {
        return 0;
    }
    const int open = std::max(0, outsideCount - shutCount);
    return open * kFull / outsideCount;
}

} // namespace goblins
