#pragma once

#include <algorithm>

#include "core/Carcass.hpp"
#include "core/Scale.hpp"

namespace goblins {

// Отчего живому страшно — ОДИН закон на всех, у кого есть тело. Живёт здесь,
// а не внутри AnimalSystem, по той же причине, что и core/Rest.hpp с
// core/Build.hpp: спрашивающих у него стало больше одного, а две копии
// одного закона расходятся молча (CLAUDE.md).
//
// Спрашивающих двое: зверь, который боялся всегда, и гоблин, который до сих
// пор не боялся никого — хищник его не видел. Теперь видит, и страх у них
// обязан быть один и тот же: разойдись он, и вышло бы, что зубы кусают
// по-разному в зависимости от того, кого кусают.
//
// Про существ закон не знает ничего и принимает числа. Даже порог тревоги
// приходит снаружи: у зверя и у гоблина пороги желаний свои
// (GoblinSystem.cpp: "общим здесь остаётся закон, а не значения"), и
// вписать сюда одно число значило бы решить за обоих.
//
// Источники перечислены ОТДЕЛЬНЫМИ функциями, а не свёрнуты в одну. Это не
// оформление: который из них применим, решает вызывающий, и решает
// по-разному. Падаль под ногами пугает зверя — но не гоблина: место, где
// кого-то съели, уже отнимает у гоблина годность (kRestCarcassPenalty,
// core/Rest.hpp), и второй закон о том же был бы одним законом, записанным
// дважды.
//
// Берётся из них БОЛЬШИЙ, а не сумма — они об разном, — и это тоже дело
// вызывающего: складывать чужие ответы закон за него не станет.

// --- Падаль пугает ---
// Во что превращается лежащая на клетке туша для того, кто на неё набрёл.
// Отсчёт от kMeatPerSize — мяса взрослой туши: целая туша пугает в полную
// силу этого веса, обглоданная и подгнившая — слабее, и вместе с мясом страх
// сходит на нет сам, без отдельного закона забывания.
//
// Меньше единицы намеренно: место, где вчера убили, тревожит, но не гонит
// так, как гонят зубы, которые видно прямо сейчас.
//
// Отдельного невидимого слоя "встревоженности" (DangerComponent) для этого
// нет и не нужно: удар зубами и так оставляет на той же клетке падаль, и
// она — тот самый след охоты, только видимый. Два следа одного события,
// ложащиеся на одну клетку и тающие каждый по-своему, — это один закон,
// записанный дважды.
constexpr int kCarcassFearWeight = 700;

// --- Страх от ран ---
// Насколько пугает чужая сила того, у кого не осталось целости. Полная
// величина — это раненный НАСМЕРТЬ рядом с равным по величине врагом; на
// деле страх выходит меньше во столько раз, во сколько тело ещё цело.
//
// Источник, общий для всех. Прежде страх был свойством одной диеты: "хищник
// ни от кого не бегает — на него в этом мире не охотятся". Это было верно
// ровно до тех пор, пока рога отвечали одной хромотой. Теперь добыча его
// убивает, а отступать он не умел вовсе — и охотился при здоровье 270 из
// 1000, пока не погибал. Замер: у всех охотящихся хищников здоровье
// 270..787, при этом энергии в баках половина и больше. Умирали они
// ранеными, а не голодными.
//
// Величина подобрана против порога желаний (350): при половине утраченной
// целости и равном по величине враге страх выходит 500 — потрёпанный уходит;
// при четверти утраченной — 250, ниже порога: поцарапанный продолжает своё
// дело.
//
// Расстояние в эту величину НЕ входит, в отличие от страха добычи, и это не
// упущение. Добыча боится приближения зубов, а раненый боится места, где его
// бьют: пока опасный в поле зрения, он уходит, а не приплясывает у края
// досягаемости. Оттого он и покидает стадо целиком, а потом берёт одиночку —
// ровно то, ради чего заведён и выбор отбившегося (kHuntCompany).
constexpr int kWoundFear = kFull;

// С какой твёрдостью испуг ложится в память места (PlaceKind::Danger,
// core/Knowledge.hpp).
//
// Своё число, а не kRememberGain, и без него памяти об опасности не было бы
// вовсе. remember занимает чужой слот только тем, что твёрже занятого
// (core/Knowledge.hpp), а у обжившегося все восемь слотов держат сотни:
// испуг ценой в сорок падал бы на пол каждый раз, и заметить это было бы
// нечем — гоблин просто никогда не помнил бы, где страшно.
//
// Триста выбрано против двух чисел сразу. Против забывания (kForgetRate = 1)
// один испуг тает за триста тиков — примерно столько, сколько нужно, чтобы
// зверь ушёл и вернулся. И против порога желаний (350): ОДНОГО испуга на
// дело не хватает, двух хватает. Место, где напугали однажды, — случайность;
// место, где пугают, — свойство места.
constexpr int kScareMark = 300;

// Насколько сторонятся опасного на ходу (WalkShy, core/Walk.hpp): и того,
// чьи зубы видно сейчас, и места, где пугали прежде.
//
// Вровень с сторонением чужого вида и заведомо меньше половины тяги к цели
// (kAimPull): сторонение подправляет шаг, а не ведёт его. Больше — и
// напуганный однажды у собственной лежанки не смог бы к ней вернуться, то
// есть страх отнимал бы дом вместо того, чтобы заставить его обустроить.
constexpr int kDangerShy = 300;

// Страх от видимых зубов: тот, кто способен тебя съесть, и он в поле зрения.
//
// alarmFloor — порог желаний того, кто боится: на самом краю видимости страх
// равен ровно порогу и растёт к полному по мере приближения зубов.
// Замеченный хищник — всегда повод уходить, а не только тот, что стоит
// рядом.
//
// Разница огромна: пока травоядное срывалось с места лишь тогда, когда
// хищник подходил вплотную, оно отдавало ему половину форы, погоня выходила
// короткой и кончалась одинаково — стадо выбивалось под ноль за несколько
// тысяч тиков, а следом вымирали и сами хищники. Фора, которую даёт
// зоркость, и есть главная защита добычи.
//
// Страшен при этом не всякий, у кого зубы, а тот, кто способен ими что-то
// сделать. Мерка та же, что решает исход удара (core/Strike.hpp), —
// отношение размеров: враг вровень пугает в полную силу, вдвое меньший — в
// половину, и до порога желаний такой страх уже не дотягивает. Без этого
// весь молодняк хищников выбивался в первые тики: взрослое травоядное
// вчетверо крупнее недоросля, а бьёт всякий, кого напугали. Заодно это и
// просто верно: стадо не разбегается от котёнка и не топчет его.
//
// Расстояние приходит дробным и тут же становится целым страхом: считать
// корень из суммы квадратов целыми числами незачем, а хранится всё равно
// целое (core/Scale.hpp).
inline int seenScare(float distance, float sight, int alarmFloor, int otherSize, int mySize) {
    const int danger = std::min(kFull, std::max(0, otherSize) * kFull / std::max(1, mySize));
    const int alarm = std::clamp(alarmFloor, 0, kFull);
    const float reach = sight > 0.0f ? sight : 1.0f;
    const int near = alarm + static_cast<int>((kFull - alarm) * (1.0f - distance / reach));
    return near * danger / kFull;
}

// Страх от ран: я ранен, а рядом тот, кто способен добить. hurt — сколько
// целости утрачено (kFull - health).
//
// Отношение размеров здесь НЕ срезается по kFull, в отличие от видимых
// зубов: втрое крупнейший добьёт с одного удара, и бояться его надо втрое
// сильнее — потолок ставится уже готовому страху.
inline int woundScare(int hurt, int otherSize, int mySize) {
    const int danger = std::max(0, otherSize) * kFull / std::max(1, mySize);
    return std::clamp(kWoundFear * std::clamp(hurt, 0, kFull) / kFull * danger / kFull, 0, kFull);
}

// Дрожь над падалью: здесь кого-то убили и съели.
//
// У такого страха нет источника, от которого убегать: боящийся не знает, где
// хищник, он знает только, что тут плохое место. Поэтому вызывающий и не
// запоминает при нём никакой угрозы — бегущий без цели просто уходит куда
// глаза глядят, и уже этим освобождает участок, а хищнику приходится искать
// добычу заново в другом месте.
inline int carcassDread(int meat) {
    return std::min(kFull, std::max(0, meat) * kCarcassFearWeight / kMeatPerSize);
}

} // namespace goblins
