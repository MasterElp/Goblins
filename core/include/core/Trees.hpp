#pragma once

namespace goblins {

// Закон дерева — ОДИН на генерацию и на симуляцию, по той же причине, что
// влажность в core/Moisture.hpp: этими числами пользуются двое (TreeSeeding
// расставляет первые деревья, PlantSystem растит и расселяет остальные), а
// две копии одного закона разъезжаются молча.
//
// --- Почему деревья растут островками, а не по всей карте ---
//
// Потому что дерево живёт с площади, а площадь конечна и разная.
//
// Минералы в почве розданы генерацией шумом со своей частотой
// (kMineralsFrequencyRatio, TerrainGenerator): карта — не ровное поле, а
// пятна побогаче и пятна победнее, от нуля до двух средних. Течение их
// больше не разносит, если выключено "Spread by water", — то есть пятна
// стоят на месте всю жизнь мира.
//
// Дерево большое, и на полный рост ему нужно kTreeMinerals крупиц — в
// полтора десятка раз больше, чем траве. Одной клетки на это заведомо не
// хватает (в среднем там десяток крупиц), поэтому дерево тянет их корнями
// со всех клеток в радиусе kTreeRootRadius. И ровно настолько, насколько
// корни его прокормили, оно и вырастает: недокормленное дерево остаётся
// подростом, не дорастает до размера, с которого роняют семена, и никуда
// не расселяется.
//
// Отсюда всё и получается само:
//   - на бедном пятне дерева не будет никогда — не из запрета, а потому
//     что там нечем вырасти;
//   - на богатом пятне деревья встают, пока не выберут его; следующий
//     подрост уже не прокормится, и роща перестаёт расти;
//   - умершее дерево возвращает свои крупицы перегноем в свою клетку, и
//     роща десятки тысяч тиков стоит на месте, обновляясь изнутри;
//   - трава при этом тянет из тех же клеток, но по четыре крупицы и
//     ненадолго, поэтому лугу роща не мешает, а роще луг — почти нет.
//
// Никакого "не больше N деревьев в радиусе R" здесь нет намеренно: счётчик
// сказал бы то же самое, но был бы пределом, а не причиной, — и одинаково
// ровно лёг бы на всю карту, дав редкий равномерный лес вместо рощ. Пятна
// богатой земли — причина, и они разные, поэтому и рощи разные.

// Сколько крупиц минералов держит в себе полностью выросшее дерево.
// Полтора десятка травяных запасов: дерево и стоит на месте травы полтора
// десятка её поколений.
inline constexpr int kTreeMinerals = 60;

// Докуда дотягиваются корни (в клетках, по Чебышёву): 2 — это пятно 5x5,
// два с половиной сотни крупиц на среднем грунте. Меньше — дерево не
// прокормится нигде, больше — рощи сольются в лес.
inline constexpr int kTreeRootRadius = 2;

// Насколько далеко от другого дерева можно встать (в клетках, по
// Чебышёву). Единица означает "не вплотную": корни соседей и так делят
// почти одну и ту же землю, а стоящие стеной деревья не оставили бы под
// собой ни травы, ни места, где спрятаться.
inline constexpr int kTreeSpacing = 1;

// Докуда улетает семя дерева. Заметно дальше травяного (та роняет в
// соседнюю клетку): дерево высокое, семя относит. Больше радиуса корней —
// иначе семя всегда падало бы в уже выбранную родителем землю, и роща не
// смогла бы ни расшириться на соседнее богатое пятно, ни начаться заново
// там, где старая вымерла.
inline constexpr int kTreeSeedRange = 5;

} // namespace goblins
