#pragma once

#include <algorithm>

namespace goblins {

// Отделить часть от запаса — и вместе с ней ту долю вещества, которая в этой
// части лежит.
//
// Мелкий закон, но общий уже для троих: ягоды на кусте (core/Berries.hpp),
// еда в руках (core/Carry.hpp) и куча на земле (core/Store.hpp). Всюду одно
// и то же: есть счёт чего-то и есть крупицы минералов, вынутые из земли и
// уехавшие внутрь этого чего-то; берут часть — крупицы обязаны уехать той же
// долей.
//
// Скопировать эти три строки трижды было бы дешевле написания заголовка, и
// ровно поэтому здесь заголовок: копии расходятся молча, а разойтись им есть
// на чём — целочисленное деление, пустой запас, запрошено больше, чем есть.
// Потерянные на округлении крупицы не возвращаются в мир никогда: их не
// вернёт ни навоз, ни падаль, потому что их уже нет.

// Что отделилось: сколько взяли и сколько вещества ушло вместе с этим.
struct Portion {
    int amount = 0;
    int minerals = 0;
};

// Взять до want из запаса. amount и minerals правятся на месте: закон
// принимает числа, а не компонент, — потому им и могут пользоваться трое,
// у которых компоненты разные.
inline Portion takePortion(int& amount, int& minerals, int want) {
    Portion taken;
    if (want <= 0 || amount <= 0) {
        return taken;
    }
    taken.amount = std::min(want, amount);
    // Доля вещества считается ДО убавления запаса: делить на уже
    // уменьшенное — значит отдать больше, чем в этой части лежало.
    taken.minerals = minerals * taken.amount / amount;
    amount -= taken.amount;
    minerals -= taken.minerals;
    return taken;
}

} // namespace goblins
