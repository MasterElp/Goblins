#pragma once

#include <algorithm>
#include <cstddef>
#include <cstdint>

#include "core/Scale.hpp"

namespace goblins {

// Как ноги уминают землю и как земля от этого отходит — ОДИН закон на всех,
// кто ходит. Живёт здесь, а не внутри системы, по той же причине, что и
// core/Rest.hpp, core/Knowledge.hpp и core/Berries.hpp: вызывающих у него
// больше одного, а две копии одного закона расходятся молча (CLAUDE.md).
//
// Про существ он не знает ничего и принимает простые числа: утоптанность
// клетки, вес того, кто на неё встал, номер тика. Сегодня топчут только
// гоблины, завтра — все, кто ходит, и разница будет в одной строке вызова.
//
// Зачем это миру. Память места (docs/10_Goblins.md, п.4b) сделала маршрут
// повторяющимся в ГОЛОВЕ гоблина, а ягодник (08_Plants.md, п.6c) дал этому
// маршруту концы. Но мир об этом по-прежнему ничего не знал: второй гоблин
// чужого пути не видит и найти его не может. Тропа — первое, чем один
// гоблин сообщает другому что-то о мире, ничего никому не говоря.

// Сколько утоптанности прибавляет шаг взрослого (у мелкого — доля от
// размера тела). Около семнадцати проходов до полной: тропа должна
// набиваться на глазах, но не с первого шага — иначе всякая случайная
// прогулка оставляла бы за собой дорогу.
constexpr int kTrampleStep = 60;

// Раз во сколько тиков утоптанность клетки убывает на единицу. Срок, а не
// скорость (core/Scale.hpp): убыль в четверть тысячной за тик целыми
// числами не выражается, а накопитель ради неё заводить незачем.
//
// При kFull = 1000 это значит, что нехоженая тропа зарастает начисто за
// четыре тысячи тиков — вчетверо дольше, чем гоблин забывает место
// (kForgetRate, core/Knowledge.hpp). Соотношение выбрано, а не совпало:
// тропа обязана ПЕРЕЖИТЬ память того, кто её набил. Иначе чужую дорогу не
// найдёт никто, тропы не сойдутся, и лагерю неоткуда будет взяться.
constexpr int kTrampleRecoverPeriod = 4;

// Насколько утоптанная земля мешает траве расти: при полной утоптанности
// рост впятеро медленнее. Не запрет — на тропе трава редеет, а исчезает
// только там, где ходят постоянно.
//
// Связь "утоптанность -> рост" однажды из мира убрали вместе с habitatFit
// (PlantSystem), и убрали правильно: она была вторым способом сказать то,
// что уже говорит влажность, и никто по той земле не ходил. Теперь ходят, и
// причина появилась: тропа, на которой растёт трава, — не тропа, а полоса
// на карте.
constexpr int kTrampleGrowthPenalty = 800;

// Шаг по клетке: нога умяла землю. weight — размер тела (bodySize,
// core/Body.hpp): взрослый давит сильнее детёныша, и это не черта генома, а
// прямое следствие того, чем он давит.
//
// Порядок вызовов на итог не влияет — сложение с потолком коммутативно
// (min(min(a+x,F)+y,F) == min(a+x+y,F)), поэтому двое, ступившие на одну
// клетку в один тик, дают одно и то же в любом порядке обхода
// (04_WorldModel.md, п.8).
inline void trampleBy(int& trampled, int weight) {
    if (weight <= 0) {
        return;
    }
    trampled = std::min(kFull, trampled + kTrampleStep * weight / kFull);
}

// Пора ли этой клетке отойти на единицу. Сдвиг по номеру клетки — чтобы вся
// карта не зарастала разом в один тик: срок один на всех, очередь у каждого
// своя. Тот же приём, что у созревания ягод (core/Berries.hpp), и по той же
// причине — заодно он размазывает по тикам и поток изменений на провод.
inline bool trampleFades(std::uint64_t tick, std::size_t cell) {
    return (tick + static_cast<std::uint64_t>(cell)) % static_cast<std::uint64_t>(kTrampleRecoverPeriod) == 0;
}

// Обеспеченность влагой, ослабленная утоптанностью. Считается так, чтобы
// промежуточное произведение не выходило за kFull: величины здесь целые и
// перемножаются трижды, а порядок делений — ровно то место, где мир
// однажды уже разъехался в тысячу раз (CLAUDE.md).
inline int trampledGrowth(int vitality, int trampled) {
    const int loss = std::clamp(trampled, 0, kFull) * kTrampleGrowthPenalty / kFull;
    return vitality - vitality * loss / kFull;
}

} // namespace goblins
