#pragma once

#include "core/World.hpp"
#include "core/generation/GoblinParams.hpp"

namespace goblins {

// Этап генерации мира "Появление разумных существ" (02_CorePrinciples.md,
// п.5), выполняется один раз и последним — после животных. Порядок здесь не
// формальность: разум возникает в уже сложившемся мире, а не вместе с ним.
// Как и остальные этапы, это не System — прямое создание Entity здесь не
// нарушает правило очереди команд (05_Entity.md, п.5): систем на этапе
// генерации ещё никто не выполняет.
//
// Делает три вещи, ровно как seedAnimals:
//   1. Выбирает племена (makeGoblinTribes) и кладёт их архетипы на World
//      Entity (GoblinTribesComponent).
//   2. Записывает туда же свойства мира, которые нужны GoblinSystem каждый
//      тик: скорость мутаций и seed для случайности гоблинов
//      (WorldPropertiesComponent).
//   3. Выпускает поголовье — туда, где в пределах видимости растёт трава. У
//      каждого свой геном, свой пол, свой возраст и свой запас: ровесники
//      вымирали бы одной волной.
//
// Про падаль при расстановке не спрашивается, хотя гоблин всеяден: на только
// что рождённой карте туш ещё нет вовсе — умирать было некому. Трава есть
// всегда, и по ней и выбирается место.
//
// Первое поголовье не берёт вещество из ниоткуда: белок, с которым гоблин
// появляется на свет, вычитается из минералов той клетки, на которой он
// стоит, и вернётся в мир падалью.
void seedGoblins(World& world, const GoblinParams& params, unsigned seed);

} // namespace goblins
