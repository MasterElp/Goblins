#pragma once

namespace goblins {

// Параметры этапа "Появление разумных существ" (02_CorePrinciples.md, п.5) —
// последнего, уже после животных: разум возникает в сложившемся мире, а не
// вместе с ним. Как и AnimalParams, это plain-структура с разумными
// значениями по умолчанию: core не знает о JSON и конфигурации
// (07_TechStack.md, п.6), заполняет её server.
struct GoblinParams {
    // Сколько племён существует в этом мире. Обрезается генерацией к
    // границам из GoblinGenetics.hpp.
    //
    // Два по умолчанию, а не одно: гоблины различаются с рождения, и первое,
    // чем они различаются, — это племя. Одно племя дало бы мир, где все
    // рождаются одинаковыми и расходятся только мутацией через поколения, —
    // чище для наблюдения, но беднее для того, ради чего всё затевается.
    int tribes = 2;

    // Сколько гоблинов выпускается при генерации — штуки, как у животных.
    // Порядок величины взят из 02_CorePrinciples.md, п.16: около трёх
    // поселений примерно по двадцать жителей. Столько их будет не сразу и
    // не обязательно — дальше поголовье живёт само.
    int count = 30;

    // Свойство мира (06_GameLoop.md, п.1a): насколько геном ребёнка может
    // отличаться от родительского — доля вложения черты (см. Genetics.hpp),
    // в тысячных (core/Scale.hpp). Своё, а не общее с животными: скорость
    // наследственных изменений у разумных не обязана совпадать со звериной,
    // и связывать их одним ползунком значило бы решить это за мир.
    int mutationRate = 60;

    // Долголетие: во сколько раз растянуты сроки жизни против записанных в
    // геноме, в тысячных (kFull — как в геноме, 10000 — вдесятеро дольше).
    // Свойство мира (06_GameLoop.md, п.1a), а не черта: множитель нельзя
    // класть в ген, иначе поедет бюджет преимуществ — см.
    // WorldPropertiesComponent.
    int pace = 10000;

    // Свойство мира: насколько особи внутри племени расходятся нравом
    // (core/generation/GoblinCharacters.hpp) — полная ширина полосы вокруг
    // нрава племени, в тысячных шкалы.
    //
    // Ноль — законный мир, а не вырожденный: все в племени выходят
    // одинаковыми, и по нему удобно смотреть, что даёт сам нрав племени, без
    // личных отличий. Своё число, не общее с mutationRate: тело и нрав
    // наследуются разными законами, и связывать их одним ползунком значило бы
    // решить за мир, что молчаливые племена обязаны быть ещё и однородными
    // телом.
    int characterSpread = 400;

    // Свойство мира: с какой скоростью у гоблина СРЕДНЕЙ общительности растёт
    // желание поговорить — за один удар пульса (paceBeat, core/Scale.hpp).
    //
    // Ноль выключает разговоры во всём мире целиком, и это не запасной случай,
    // а рабочий: тем же ползунком снимается вторая половина машинной сверки
    // (мир с разговорами против мира без них). Порог желания — 350
    // (kDesireFloor), значит при двадцати средний гоблин созревает для
    // разговора за 35 ударов пульса.
    int talkUrge = 20;
};

} // namespace goblins
