#pragma once

#include "core/Scale.hpp"

namespace goblins {

// Параметры этапа "Появление животных" (02_CorePrinciples.md, п.5) —
// следующего за заселением растительностью. Как и PlantParams, это
// plain-структура с разумными значениями по умолчанию: core не знает о JSON
// и конфигурации (07_TechStack.md, п.6), заполняет её server (см.
// shared/config::AnimalConfig и маппинг в server/main.cpp).
//
// Травоядные и хищники — один этап, а не два: они появляются вместе и
// живут по одной системе, различаясь только диетой.
struct AnimalParams {
    // Сколько видов травоядных и хищников существует в этом мире.
    // Обрезается генерацией к границам из AnimalGenetics.hpp (1..8 и 1..6).
    int herbivoreSpecies = 2;
    int predatorSpecies = 1;

    // Сколько особей выпускается в мир при генерации. Не доля площади, как
    // у травы, а штуки: животных десятки, а не тысячи, и "процент карты"
    // для них ничего не означал бы. Дальше поголовье живёт само —
    // размножается, голодает, гибнет от зубов и вымирает по законам
    // AnimalSystem, поэтому это стартовое поголовье, а не итоговое.
    //
    // Хищников по умолчанию заметно меньше, чем добычи: иначе они выедят
    // её раньше, чем она успеет расплодиться, и мир опустеет за первую же
    // сотню тиков. Ноль в любой из двух строк — мир без этого звена
    // (только трава; трава и травоядные; в принципе и хищники без добычи —
    // но эти просто вымрут).
    int herbivoreCount = 120;
    int predatorCount = 10;

    // Свойство мира (06_GameLoop.md, п.1a): насколько геном детёныша может
    // отличаться от родительского — доля вложения черты (см. Genetics.hpp),
    // а не доля самого значения гена. Одно на всех животных: это скорость
    // наследственных изменений в этом мире, а не свойство диеты.
    // В тысячных долях вложения черты (core/Scale.hpp).
    int mutationRate = 60;
};

} // namespace goblins
