#pragma once

#include "core/Scale.hpp"

namespace goblins {

// Параметры заселения мира растительностью — этап генерации, следующий за
// почвой/водой и булыжниками (02_CorePrinciples.md, п.5: "Заселение
// растительностью"). Как и TerrainParams, это plain-структура с разумными
// значениями по умолчанию: core не знает о JSON и конфигурации
// (07_TechStack.md, п.6), заполняет её server (см. shared/config
// ::PlantConfig и маппинг в server/main.cpp).
struct PlantParams {
    // Сколько видов травы существует в этом мире. Обрезается генерацией
    // до [kMinGrassSpecies, kMaxGrassSpecies] (PlantGenetics.hpp) — 3..12.
    int grassSpecies = 5;

    // Какую долю пригодных клеток засеять при генерации. Дальше трава
    // расселяется сама (PlantSystem), поэтому это стартовая заселённость,
    // а не итоговая: даже с маленького значения луг за сотни тиков
    // занимает всё, что ему подходит.
    // В тысячных долях карты (core/Scale.hpp): 60 — это прежние 6%.
    int grassCoverage = 60;

    // Свойство мира (06_GameLoop.md, п.1a): насколько сильно геном
    // потомка может отличаться от родительского — доля вложения черты
    // (см. PlantGenetics.hpp), а не доля самого значения. Выбирается при
    // генерации, дальше PlantSystem его только читает.
    // В тысячных долях вложения черты: 60 — это прежние 6%.
    int mutationRate = 60;

    // Сколько видов деревьев существует в этом мире. Обрезается генерацией
    // до [kMinTreeSpecies, kMaxTreeSpecies] (PlantGenetics.hpp) — 1..5.
    int treeSpecies = 2;

    // Какую долю карты занять деревьями при генерации, в тысячных
    // (core/Scale.hpp). На порядок меньше травяной: дерево стоит на месте
    // десятки тысяч тиков и занимает клетку целиком, а вокруг себя ещё и
    // запрещает вставать соседям (core/Trees.hpp).
    //
    // Это не итоговая заселённость и не потолок: сколько деревьев мир
    // прокормит, решает не эта настройка, а минералы в земле — поставь
    // больше, чем земля тянет, и лишние просто не найдут себе места.
    int treeCoverage = 10;

    // Свойство мира: раз во сколько тиков перегной возвращает в почву одну
    // крупицу минералов. Тоже выбирается один раз при генерации.
    int humusDecayPeriod = 50;
};

} // namespace goblins
