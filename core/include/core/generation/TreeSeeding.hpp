#pragma once

#include "core/World.hpp"
#include "core/generation/PlantParams.hpp"

namespace goblins {

// Первые деревья мира — стадия генерации, идущая ПЕРЕД травой и по той же
// причине, по которой булыжники идут перед обеими: кто занимает место
// первым, тот его и получает. Луг зарастает всюду, где ему хватает влаги, и
// дереву, посаженному после него, не осталось бы ни одной свободной клетки.
//
// Рощи не расставляются "кучками" каким-нибудь особым правилом. Они
// получаются сами: дерево встаёт только там, где под корнями лежит
// достаточно крупиц (core/Trees.hpp), а крупицы розданы генерацией пятнами
// — значит, и деревья ложатся пятнами. Посаженное дерево сразу забирает
// свою долю из земли, поэтому следующая попытка рядом чаще не проходит, и
// роща получается редкой, а не сплошной.
void seedTrees(World& world, const PlantParams& params, unsigned seed);

} // namespace goblins
