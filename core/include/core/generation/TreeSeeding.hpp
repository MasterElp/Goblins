namespace goblins {

// Первые деревья мира — стадия генерации, идущая ПЕРЕД травой и по той же
// причине, по которой булыжники идут перед обеими: кто занимает место
// первым, тот его и получает. Луг зарастает всюду, где ему хватает влаги, и
// дереву, посаженному после него, не осталось бы ни одной свободной клетки.
//
// Каждый вид высаживается ОДНОЙ плотной куртиной в случайном месте, а не
// рассыпается по карте поодиночке: так у вида с первого тика есть место,
// где он живёт. Рассыпанное дерево почти всегда оказывалось единственным на
// несколько десятков клеток — семя летит шесть клеток (core/Trees.hpp), и
// соседа в этом круге у него нет, — то есть мир начинался полем одиночек,
// которым тысячи тиков сползаться в рощи.
//
// Форму куртине никто не задаёт. Сажают кольцами от центра наружу, пока не
// набрана доля вида, а край рвут камни, вода и, главное, минералы: дерево
// встаёт только там, где под корнями лежит достаточно крупиц
// (core/Trees.hpp), и каждое посаженное сразу забирает свою долю из земли.
// Поэтому куртина плотна в середине и рвана по краю, а на скупой земле
// обрывается, не набрав и половины.
void seedTrees(World& world, const PlantParams& params, unsigned seed);

} // namespace goblins
