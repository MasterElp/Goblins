#pragma once

#include "core/Scale.hpp"

namespace goblins {

// Параметры генерации террейна. Здесь только те числа, которые меняют
// ВИДИМЫЙ результат и которые осмысленно крутить снаружи; всё остальное —
// внутренняя механика с обоснованным значением, и она живёт константами в
// TerrainGenerator.cpp/HydrologySystem.cpp рядом с местом использования, а
// не тянется через конфигурацию, сеть и файл сохранения только ради того,
// чтобы никогда не быть изменённой.
//
// core не знает о JSON/конфигурации (07_TechStack.md, п.6: core не зависит
// от server) — это plain-структура с разумными значениями по умолчанию;
// server сам решает, каким её заполнить (из своей конфигурации, см.
// shared/config/Config.hpp ::TerrainConfig и маппинг в server/main.cpp).
struct TerrainParams {
    // Масштаб рельефа. Больше — крупнее пятна и формы, меньше — мельче и
    // чаще. Один на все слои: масштабы каменистости и минералов —
    // фиксированные доли от него (см. TerrainGenerator.cpp), потому что
    // независимо они никогда и не крутились, а разница между слоями нужна
    // только чтобы узоры не совпадали друг с другом.
    // Размер узора в тайлах: во сколько тайлов укладывается одна крупная
    // форма рельефа. Раньше это была частота шума (0.02) — величина
    // обратная и дробная; в тайлах то же самое читается глазом и целое.
    int featureSize = 50;

    // Сколько слоёв фрактального шума складывается: больше — мельче
    // детали поверх крупных форм. Lacunarity/gain у fBm канонические
    // (2.0/0.5) и вынесены в константы — их подстройка меняет картинку
    // так же, как частота и октавы, только менее предсказуемо.
    int noiseOctaves = 4;

    // Высота высочайшей вершины мира — в тех же единицах, что глубина воды
    // (HeightComponent, riverDepth). Горы должны быть НАСТОЯЩИМИ горами:
    // при прежнем диапазоне высот 0..1 весь перепад рельефа был
    // сопоставим с глубиной реки, и никакого "спуска с горы к морю" не
    // получалось — вода расползалась по почти плоской карте.
    //
    // Форма склона — не параметр, а закон (kMountainSharpness в
    // TerrainGenerator.cpp): высота растёт не линейно с шумом, а с
    // нажимом, поэтому бо́льшая часть карты остаётся низиной, а вершины
    // редки и высоки.
    // В тысячных единицы глубины (kDepthUnit, core/Scale.hpp): 16000 —
    // это прежние 16, то есть примерно двадцать глубин реки.
    int mountainHeight = 16000;

    // Насколько сильно ВЫСОТА рельефа делает почву твёрдой (каменистой и
    // утрамбованной): 0 — каменистость чисто своя, от шума; 1 — она почти
    // повторяет рельеф, и горы целиком из камня.
    //
    // Направление связи именно такое, а не обратное. Раньше было наоборот
    // (hardnessHeightBump: твёрдая земля ПОДНИМАЛА рельеф), но тогда
    // "горы из камня" и "камень поднимает горы" — один и тот же круг, и
    // держать обе связи сразу нельзя. Из двух выбрана эта: гора — это в
    // первую очередь скальный выход, а не куча земли, которая почему-то
    // стала твёрдой.
    // В тысячных долях: 600 — это прежние 0.6.
    int mountainHardness = 600;

    // Река: явное русло (не эмерджентное накопление стока) — сколько
    // рек, базовая ширина в тайлах (гуляет по руслу за счёт шума),
    // извилистость (0 — прямая линия, 1 — максимальный меандр) и базовая
    // глубина воды (тоже с шумом по длине).
    int riverCount = 3;
    // Ширина — в тайлах и десятых долях тайла (30 = три тайла): целая
    // ширина оказалась бы слишком грубой ручкой на узких реках.
    int riverWidth = 30;
    // Извилистость — в тысячных долях (0 — прямая, kFull — максимум).
    int riverSinuosity = 500;
    // Глубина — в тысячных единицы глубины.
    int riverDepth = 900;

    // Средняя глубина воды пруда в тех же единицах, что и riverDepth
    // (глубина тайла, не множитель): у каждого пруда своя форма впадины
    // (Priority-Flood), поэтому глубина внутри пруда не одна и та же
    // всюду, а масштабируется формой впадины так, чтобы СРЕДНЯЯ по пруду
    // глубина равнялась ровно pondDepth — как у реки depthMul даёт шум
    // вдоль русла вокруг среднего riverDepth.
    int pondDepth = 900;

    // Минералы (SoilComponent.minerals, целое число): шум, в среднем по
    // карте дающий mineralsAverage. Дальнейшее движение минералов между
    // тайлами по правилу песочной кучи — HydrologySystem, не генерация.
    // Крупицы — счётные, шкалы у них нет и не было.
    int mineralsAverage = 10;

    // Источники воды (WaterSourceComponent, см. TerrainGenerator.cpp):
    // РОВНО ОДИН на реку, у самого её истока в горах, плюс
    // waterSourceCount "родников" в случайных точках карты.
    //
    // waterSourceDepth — глубина СТОЛБА воды источника и свойство мира:
    // источник не подливает сколько-то за тик, а просто всегда стоит на
    // этой глубине, сколько бы из него ни вытекло (06_GameLoop.md, п.1a).
    // Отсюда же и единственный способ перелить мир водой: каждый источник
    // отдаёт примерно свою глубину за тик, поэтому важно не столько
    // значение, сколько ЧИСЛО источников. Когда источник стоял на каждой
    // клетке выше ледниковой отметки, их получались сотни, и карту
    // заливало целиком за несколько сотен тиков.
    int waterSourceCount = 3;
    int waterSourceDepth = 1000;

    // Отток воды и дожди — тоже свойства мира (см.
    // WorldPropertiesComponent): вместе с источниками они образуют баланс
    // воды, и настраиваться должны все вместе, иначе настраиваемый приток
    // при неизменяемом оттоке заливает карту целиком.
    // rainIntervalTicks — раз во сколько тиков начинается дождь (0 —
    // дождей нет), rainAmount — глубина одной капли. Дождь идёт несколько
    // тиков и роняет капли в случайные точки, а не заливает карту разом.
    // Сколько тысячных глубины вода теряет от испарения за сто тиков
    // (см. core::WorldPropertiesComponent::waterEvaporationRate).
    int waterEvaporationRate = 20;
    int rainIntervalTicks = 400;
    int rainAmount = 50;

    // Эрозия: скорость вымывания породы потоком (см.
    // WorldPropertiesComponent) — тоже свойство мира: выбирается здесь,
    // при генерации, HydrologySystem только читает.
    int soilErosionRate = 50;
};

} // namespace goblins
