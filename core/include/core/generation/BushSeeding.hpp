namespace goblins {

// Первые кусты мира — стадия генерации между деревьями и травой. Порядок тот
// же и по той же причине: кто занимает место первым, тот его и получает.
// Дерево вперёд куста, потому что ему нужны крупицы под корнями целой
// площадью; куст вперёд травы, потому что луг зарастает всюду и не оставил бы
// ягоднику ни одной клетки.
//
// Кусты сажаются КУПАМИ, а не поодиночке и не одной куртиной на вид: ягодник
// — это несколько кустов рядом, и таких ягодников на карте несколько.
// Одинокий куст кормит одного гоблина полтора раза и не стоит дороги к нему;
// сплошные заросли делают еду фоном, а фон не запоминают. Между этими
// крайностями и живёт весь смысл кустов (docs/plan/10_Goblins_roadmap.md,
// шаг 3a).
//
// Раскладка купы — общий закон гнезда (core/generation/Nest.hpp), тот же, что
// у рощи, стада и племени. Здесь остаётся только своё: чем годен центр купы
// (богатая земля — иначе ягоды не завяжутся, см. core/Berries.hpp) и как
// сажается один куст.
void seedBushes(World& world, const PlantParams& params, unsigned seed);

} // namespace goblins
