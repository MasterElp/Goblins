#pragma once

#include "core/World.hpp"
#include "core/generation/HerbivoreParams.hpp"

namespace goblins {

// Этап генерации мира "Появление животных" (02_CorePrinciples.md, п.5),
// выполняется один раз, последним — после почвы/воды, булыжников и
// заселения растительностью: травоядному нужен уже готовый мир, в котором
// есть что есть и где пить. Как и остальные этапы, это не System — прямое
// создание Entity здесь не нарушает правило очереди команд (05_Entity.md,
// п.5): систем на этапе генерации ещё никто не выполняет.
//
// Делает три вещи:
//   1. Выбирает виды травоядных (makeHerbivoreSpecies) и кладёт их
//      архетипы на World Entity (HerbivoreSpeciesComponent).
//   2. Записывает туда же свойства мира, которые нужны HerbivoreSystem
//      каждый тик: скорость мутаций и seed для случайности животных
//      (WorldPropertiesComponent).
//   3. Выпускает params.count особей на пригодные клетки: у каждой свой
//      геном, свой пол, свой возраст и свой запас — стадо ровесников
//      вымирало бы одной волной.
//
// Первое поголовье не берёт вещество из ниоткуда: белок, с которым
// животное появляется на свет, вычитается из минералов той клетки, на
// которой оно стоит — ровно как у первых растений (GrassSeeding). Дальше
// эти крупицы идут по кругу почва -> трава -> травоядное -> перегной ->
// почва.
void seedHerbivores(World& world, const HerbivoreParams& params, unsigned seed);

} // namespace goblins
