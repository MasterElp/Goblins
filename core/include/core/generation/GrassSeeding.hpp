namespace goblins {

// Этап генерации мира "заселение растительностью" (02_CorePrinciples.md,
// п.5), выполняется один раз после почвы/воды (generateTerrain) и
// булыжников (scatterBoulders): к этому моменту уже известно, где вода и
// где занятые непроходимыми объектами тайлы. Как и они, это не System —
// прямое создание Entity здесь не нарушает правило очереди команд
// (05_Entity.md, п.5): систем на этапе генерации ещё никто не выполняет.
//
// Делает три вещи:
//   1. Выбирает виды травы (makeGrassSpecies) и кладёт их архетипы на
//      World Entity (PlantSpeciesComponent).
//   2. Записывает туда же свойства мира, которые нужны PlantSystem каждый
//      тик: скорость мутаций, скорость разложения перегноя и seed для
//      случайности растений (WorldPropertiesComponent).
//   3. Засевает params.grassCoverage долю площади: каждое семя получает
//      СВОЙ геном — архетип вида с небольшой мутацией, поэтому уже на
//      старте внутри вида есть генетическая вариативность.
//
// Первые растения не берут минералы из ниоткуда: сколько нужно на их
// стартовый размер, столько и вычитается из SoilComponent своей клетки —
// дальше эти крупицы идут по кругу почва -> растение -> перегной ->
// почва и не создаются заново (PlantSystem).
void seedGrass(World& world, const PlantParams& params, unsigned seed);

} // namespace goblins
