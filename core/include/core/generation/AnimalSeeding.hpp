namespace goblins {

// Этап генерации мира "Появление животных" (02_CorePrinciples.md, п.5),
// выполняется один раз, последним — после почвы/воды, булыжников и
// заселения растительностью: животному нужен уже готовый мир, в котором
// есть что есть и где пить. Как и остальные этапы, это не System — прямое
// создание Entity здесь не нарушает правило очереди команд (05_Entity.md,
// п.5): систем на этапе генерации ещё никто не выполняет.
//
// Делает три вещи:
//   1. Выбирает виды травоядных и хищников (makeHerbivoreSpecies /
//      makePredatorSpecies) и кладёт их архетипы на World Entity
//      (AnimalSpeciesComponent).
//   2. Записывает туда же свойства мира, которые нужны AnimalSystem каждый
//      тик: скорость мутаций и seed для случайности животных
//      (WorldPropertiesComponent).
//   3. Выпускает поголовье: травоядных — туда, где в пределах их видимости
//      растёт трава, хищников — туда, где в пределах их видимости есть
//      травоядные. У каждой особи свой геном, свой пол, свой возраст и свой
//      запас: стадо ровесников вымирало бы одной волной.
//
// Первое поголовье не берёт вещество из ниоткуда: белок, с которым
// животное появляется на свет, вычитается из минералов той клетки, на
// которой оно стоит — ровно как у первых растений (GrassSeeding). Дальше
// эти крупицы идут по кругу почва -> трава -> травоядное -> хищник ->
// падаль -> перегной -> почва.
void seedAnimals(World& world, const AnimalParams& params, unsigned seed);

} // namespace goblins
