#pragma once

namespace goblins {

// Параметры этапа "Появление животных" (02_CorePrinciples.md, п.5) —
// следующего за заселением растительностью. Как и PlantParams, это
// plain-структура с разумными значениями по умолчанию: core не знает о JSON
// и конфигурации (07_TechStack.md, п.6), заполняет её server (см.
// shared/config::HerbivoreConfig и маппинг в server/main.cpp).
struct HerbivoreParams {
    // Сколько видов травоядных существует в этом мире. Обрезается
    // генерацией до [kMinHerbivoreSpecies, kMaxHerbivoreSpecies]
    // (HerbivoreGenetics.hpp) — 1..8.
    int species = 2;

    // Сколько особей выпускается в мир при генерации. Не доля площади, как
    // у травы, а штуки: травоядных десятки, а не тысячи, и "процент карты"
    // для них ничего не означал бы. Дальше поголовье живёт само —
    // размножается, голодает и вымирает по законам HerbivoreSystem,
    // поэтому это стартовое поголовье, а не итоговое.
    //
    // Ноль — мир без животных: трава в нём живёт ровно так же, как жила до
    // их появления.
    int count = 40;

    // Свойство мира (06_GameLoop.md, п.1a): насколько геном телёнка может
    // отличаться от родительского — доля вложения черты (см.
    // Genetics.hpp), а не доля самого значения гена. Выбирается при
    // генерации, дальше HerbivoreSystem его только читает.
    float mutationRate = 0.06f;
};

} // namespace goblins
