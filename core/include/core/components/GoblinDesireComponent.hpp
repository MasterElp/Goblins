#pragma once

#include <cstdint>
#include <string>

namespace goblins {

// Чего гоблин хочет. Одно желание за раз — то, которым он сейчас занят.
//
// Перечисление своё, а не общее с Desire (животные), и это не дублирование.
// У животного желаний пять и больше не станет: оно не может хотеть ничего
// такого, о чём не знает, а знает оно только то, что видит сейчас. У
// гоблина их станет вдвое больше — отдых, ноша, работа, постройка, — и
// каждое новое значение в общем перечислении было бы для животного враньём:
// оно носило бы то, чего не может выбрать никогда, и desireName отвечал бы
// за оба смысла сразу.
//
// У этого разделения есть и второе, более важное следствие: гоблин не носит
// DesireComponent, а AnimalSystem выбирает существ именно по нему — значит,
// гоблин из-под неё выходит сам, без единого entt::exclude. Забыть такое
// исключение было бы нетрудно, а мир от этого ожил бы вдвойне: гоблина
// считали бы две системы за тик.
//
// Сам закон выбора при этом общий (core/Desires.hpp): порог, ниже которого
// желание никуда не гонит, и инерция, с которой уже выбранное держится за
// себя. Общее — правило, разное — то, из чего выбирают.
enum class GoblinDesire : std::uint8_t {
    // Ничего не гонит: сытый, напоенный, не ищущий пары гоблин просто
    // бродит. Это полноценное состояние, а не "нет данных".
    Idle = 0,
    Food = 1,
    Water = 2,
    Mate = 3,
};

// Имя желания — не логика, а имя значения (см. desireName в
// DesireComponent.hpp): им пользуются файл мира, сетевой протокол и вывод
// сервера, и лежит оно рядом с перечислением, чтобы не разъехаться.
inline const char* goblinDesireName(GoblinDesire desire) {
    switch (desire) {
        case GoblinDesire::Food: return "food";
        case GoblinDesire::Water: return "water";
        case GoblinDesire::Mate: return "mate";
        case GoblinDesire::Idle: break;
    }
    return "idle";
}

// Обратная сторона той же пары. Неизвестное имя (файл от другой версии) —
// Idle, а не ошибка: желание пересчитывается на первом же тике из тела, и
// невозможность его прочитать — не повод не открыть мир.
inline GoblinDesire goblinDesireFromName(const std::string& name) {
    if (name == "food") return GoblinDesire::Food;
    if (name == "water") return GoblinDesire::Water;
    if (name == "mate") return GoblinDesire::Mate;
    return GoblinDesire::Idle;
}

// Желания гоблина и то, которое сейчас им движет.
//
// Хранится ровно то, что нельзя прочитать заново: голод и жажда выводятся
// из тела каждый тик (core/Needs.hpp), а вот желание пары в теле не
// прочитать — оно копится со временем у сытого взрослого и обнуляется
// встречей. И current: у желания есть инерция, и без неё гоблин с почти
// равными голодом и жаждой каждый тик разворачивался бы, не дойдя никуда.
struct GoblinDesireComponent {
    // Желание пары, 0..kFull (core/Scale.hpp).
    int mating = 0;
    GoblinDesire current = GoblinDesire::Idle;
};

} // namespace goblins
