#pragma once

namespace goblins {

// Наличие этого компонента на терраформирующем Entity тайла означает, что
// на тайле есть вода (река или пруд) — согласно принципу "Отсутствие
// компонента означает отсутствие возможности" (02_CorePrinciples.md, п.3),
// компонент есть только там, где вода действительно есть, а не как поле
// с нулевым значением у всех подряд.
// Отдельного признака "река/пруд" здесь нет: для симуляции его никогда и
// не существовало — вода течёт по одному закону (уклон поверхности,
// HydrologySystem), а не по тому, каким её нарисовала генерация. Раньше
// такое поле (flowSpeed) было, но не влияло ни на течение, ни на
// отрисовку — только хранилось в файле мира.
struct WaterComponent {
    // Глубина в тысячных (kDepthUnit, core/Scale.hpp), > 0. Для реки — по
    // ширине русла (см. TerrainGenerator), для пруда — разница между
    // уровнем заполнения впадины и высотой дна.
    int depth = 0;

    // Остаток от деления при разливе, 0..kPoolCells-1 (HydrologySystem).
    //
    // Вода разливается по перекрывающимся группам из девяти клеток, и
    // правка каждой клетки — сумма её правок по всем группам, делённая на
    // девять. В целых числах это деление теряло бы до восьми тысячных
    // глубины на клетке КАЖДЫЙ тик — вчетверо больше, чем испаряется, то
    // есть карта высыхала бы сама собой без всякой причины. Неделящийся
    // остаток остаётся здесь и достаётся клетке следующим тиком.
    //
    // Это не "накопитель дроби" вроде убранных pending: те копили дробную
    // скорость, а этот держит целый остаток целого деления. Без него закон
    // сохранения воды не выполняется, а с ним выполняется точно.
    int flowRemainder = 0;
};

} // namespace goblins
