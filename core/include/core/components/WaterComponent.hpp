#pragma once

namespace goblins {

// Наличие этого компонента на терраформирующем Entity тайла означает, что
// на тайле есть вода (река или пруд) — согласно принципу "Отсутствие
// компонента означает отсутствие возможности" (02_CorePrinciples.md, п.3),
// компонент есть только там, где вода действительно есть, а не как поле
// с нулевым значением у всех подряд.
struct WaterComponent {
    // Условные единицы глубины, > 0. Для реки — по ширине русла (см.
    // TerrainGenerator), для пруда — разница между уровнем заполнения
    // впадины и высотой дна.
    float depth = 0.0f;

    // Скорость потока: 0 — стоячая вода (пруд), > 0 — течёт (река). Тот
    // же паттерн, что и depth — скаляр со значением по умолчанию "не
    // применимо", а не отдельный компонент (сама вода уже отмечена
    // наличием WaterComponent).
    float flowSpeed = 0.0f;
};

} // namespace goblins
