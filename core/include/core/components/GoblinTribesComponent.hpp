#pragma once

#include <vector>

#include "core/components/AnimalGenomeComponent.hpp"

namespace goblins {

// Племена гоблинов, существующие в этом мире, — свойство мира
// (06_GameLoop.md, п.1a) из числа "зафиксированных при генерации", ровно как
// виды травы и виды животных: набор выбирается один раз, при создании мира,
// и System-ами не меняется. Поэтому компонент живёт на World Entity.
//
// Список один, а не два, как у животных: там их два потому, что у
// травоядных и хищников разные таблицы черт и разные бюджеты, и сравнивать
// их между собой незачем. Гоблины все одной таблицы — они и есть один вид,
// разошедшийся на племена. AnimalGenomeComponent::species у гоблина — номер
// племени в этом списке.
//
// Тип генома тот же самый, что у животных, и это не небрежность: у гоблина
// нет ни одного телесного признака, которого не было бы у зверя. Разными их
// делают не поля, а таблица черт — какие из полей вообще покупаются и в
// каких пределах (core/generation/GoblinGenetics.hpp). Зубов (attack) и
// рогов (defense) гоблин не покупает, и они остаются нулями: то, чем он
// возьмёт своё, будет куплено не бюджетом, а трудом.
//
// Архетип племени нужен как центр, вокруг которого мутациям разрешено
// гулять (kSpeciesBand, core/generation/Genetics.hpp), иначе за сотни
// поколений племена слились бы в одно.
struct GoblinTribesComponent {
    std::vector<AnimalGenomeComponent> tribes;
};

} // namespace goblins
