// Метка "это растение — куст", а не трава и не дерево. Пустая: сам факт
// наличия и есть данные (02_CorePrinciples.md, п.3), как у TreeComponent.
//
// Куст — то же растение: тот же PlantComponent (возраст, развитость,
// крупицы), тот же PlantGenomeComponent, та же PlantSystem, та же смерть и
// тот же перегной. Отличий у него ровно три, и все читаются там, где
// применяются:
//   1. Живёт дольше травы и короче дерева (kBushTraits, PlantGenetics.hpp).
//   2. Кормится со СВОЕЙ клетки, как трава, а не корнями с площади, как
//      дерево (core/Trees.hpp), и соседу вплотную не мешает. Дай кусту
//      корни — и он разредится в такие же одиночки, а ягодник обязан быть
//      купой: к одинокому кусту незачем возвращаться.
//   3. Даёт ягоды (BerryComponent, core/Berries.hpp).
//
// Третье и есть причина, по которой куст вообще заведён. Трава размазана по
// карте, её едят где стоят, и помнить её место бессмысленно; ягодник —
// точка, которую обирают и которая наполняется снова. Разница между едой
// размазанной и едой, у которой есть адрес, и делает возможным возвращение,
// а из возвращения растёт тропа (docs/plan/10_Goblins_roadmap.md, шаг 3a).
