namespace goblins {

// Падаль на тайле — то, что осталось от умершего животного. Живёт на том
// же терраформирующем Entity тайла, что SoilComponent, WaterComponent и
// HumusComponent: это не самостоятельный объект на земле, а состояние самой
// земли — лежащее на ней мясо. Наличие компонента и есть факт "здесь лежит
// падаль" (02_CorePrinciples.md, п.3).
//
// Падаль — единственный путь смерти животного обратно в мир, и путь этот
// один для всех: и загрызенное хищником, и издохшее от старости ложится
// одинаково. Отсюда сама собой берётся и возможность падальщичества: хищнику
// незачем знать, кто убил ту тушу, которую он ест.
//
// Судьба падали двойная: её либо съедают, либо она гниёт. И то, и другое —
// одно и то же убывание meat, разница только в том, куда уходят крупицы
// белка: в едока или в перегной. Поэтому и хранится она одной величиной, а
// не "мясом для еды" и "мясом для гниения" по отдельности.
struct CarcassComponent {
    // Сколько биомассы осталось. В тех же единицах, что развитость
    // растения (PlantComponent::growth), — иначе энергию от съеденного
    // пришлось бы считать по двум разным шкалам (см. kEnergyPerBiomass в
    // AnimalSystem).
    float meat = 0.0f;

    // Крупицы минералов, которые животное накопило при жизни и которые
    // ещё не ушли ни в едока, ни в перегной. Освобождаются пропорционально
    // убывающему мясу: съеденная половина туши уносит половину крупиц.
    // Накопителя доли (proteinPending) рядом нет: сколько крупиц
    // приходится на унесённую долю мяса, столько и освобождается тем же
    // тиком, целым числом. Округление вниз ничего не теряет —
    // неосвобождённое остаётся в туше и уйдёт со следующим куском или с
    // гниением.
    int protein = 0;
};

} // namespace goblins
