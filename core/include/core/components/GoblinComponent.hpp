#pragma once

namespace goblins {

// Тег-компонент без данных: существо с ним — гоблин. Как и
// HerbivoreComponent, само наличие компонента и есть факт
// (02_CorePrinciples.md, п.3).
//
// Гоблин — НЕ третья диета. Тело у него то же самое, что у животного
// (AnimalComponent), и стареет оно по тому же закону (core/Body.hpp);
// геном — тот же тип, только с другой таблицей черт
// (core/generation/GoblinGenetics.hpp). Отличается он тем, КАК принимает
// решения: у животного они выводятся из тела и из того, что видно вокруг, и
// больше ниоткуда, а у гоблина к этому добавится память мест, повторяющиеся
// маршруты, ноша, работа и связи с другими (02_CorePrinciples.md, п.6 —
// знания принадлежат Entity). Ничего этого ещё нет, и потому тег пока пуст.
//
// Отсюда и отдельная система: не потому, что гоблин иначе устроен, а
// потому, что всё перечисленное некуда класть внутрь AnimalSystem, не
// превратив её в свалку двух разных существ. Из-под самой AnimalSystem
// гоблин выходит не этим тегом, а тем, что у него нет DesireComponent — она
// выбирает по нему (см. GoblinDesireComponent).
//
// Ест гоблин и траву, и падаль: он всеяден. Живую добычу он не бьёт —
// подбирает мёртвое.
struct GoblinComponent {
    // Усталость, 0..kFull (core/Scale.hpp). Копится от того, что гоблин
    // жив и ходит, и убывает, пока он отдыхает.
    //
    // Хранится, в отличие от голода и жажды: тем есть что читать в теле
    // (пустеющие запасы, core/Needs.hpp), а усталости читать нечего — она
    // и есть то, что накопилось. Ровно та же причина, по которой хранится
    // желание пары.
    //
    // Это первая потребность гоблина, которую удовлетворяет МЕСТО, а не
    // вещество, и в этом весь её смысл. Траву съедают, и она кончается;
    // вода течёт; а место, на котором хорошо лежать, никуда не девается —
    // к нему можно вернуться. Из этого различия и вырастет всё остальное:
    // повторяющийся путь, тропа, лагерь (см. docs/10_Goblins.md, п.5).
    int fatigue = 0;
};

} // namespace goblins
