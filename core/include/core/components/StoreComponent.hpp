#pragma once

namespace goblins {

// Куча принесённой еды на тайле.
//
// Состояние ЗЕМЛИ, а не предмет на ней: компонент ложится на тот же
// терраформирующий Entity тайла, где живут почва, вода, перегной и падаль
// (04_WorldModel.md, п.3). Наличие компонента и есть факт "здесь лежит
// запас" (02_CorePrinciples.md, п.3) — у чистой клетки его просто нет, а не
// нулевое поле.
//
// Принесённое на одну клетку складывается в одну кучу, как складываются две
// туши и два перегноя: иначе у лагеря копились бы десятки отдельных горсток
// на одном тайле.
//
// Куча — первая вещь в этом мире, существующая не потому, что выросла, а
// потому, что её сюда принесли. Всё остальное на земле — трава, дерево,
// падаль, перегной — оказалось там само.
struct StoreComponent {
    // Еда в куче, в той же шкале биомассы, что ягода и мясо.
    int food = 0;
    // Крупицы, приехавшие внутрь этой еды. Уйдут либо в того, кто её съест,
    // либо в перегной, если куча сгниёт (core/Store.hpp): вещество не
    // пропадает ни в том, ни в другом случае.
    int minerals = 0;
};

} // namespace goblins
