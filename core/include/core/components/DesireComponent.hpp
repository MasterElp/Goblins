#pragma once

#include <cstdint>

namespace goblins {

// Чего существо хочет. Одно желание за раз — то, которым оно сейчас занято.
enum class Desire : std::uint8_t {
    // Ничего не гонит: сытое, напоенное, не ищущее пары животное просто
    // бродит. Это полноценное состояние, а не "нет данных".
    Idle = 0,
    Food = 1,
    Water = 2,
    Mate = 3,
};

// Имя желания — не логика, а имя значения (см. sexName в
// HerbivoreComponent.hpp): им пользуются файл мира, сетевой протокол и
// вывод сервера, и лежит оно рядом с перечислением, чтобы не разъехаться.
inline const char* desireName(Desire desire) {
    switch (desire) {
        case Desire::Food: return "food";
        case Desire::Water: return "water";
        case Desire::Mate: return "mate";
        case Desire::Idle: break;
    }
    return "idle";
}

// Обратная сторона той же пары: имя из файла мира снова становится
// желанием. Неизвестное имя (файл от другой версии) — Idle, а не ошибка:
// желание пересчитывается на первом же тике из тела животного, и
// невозможность прочитать его — не повод не открыть мир.
inline Desire desireFromName(const std::string& name) {
    if (name == "food") return Desire::Food;
    if (name == "water") return Desire::Water;
    if (name == "mate") return Desire::Mate;
    return Desire::Idle;
}

// Желания существа и то, которое сейчас им движет.
//
// Желание — не отдельная сила и не команда сверху, а выражение состояния
// тела (02_CorePrinciples.md, п.12: у всего есть причина). Голод — это
// пустеющий запас энергии и нехватка белка, жажда — пустеющий запас воды;
// оба пересчитываются из тела каждый тик и падают сами, как только
// животное поело или напилось. Так и выглядит "удовлетворение желания":
// не списание счётчика, а изменившееся тело.
//
// Особняком стоит mating: его в теле не прочитать, оно копится со временем
// у сытого взрослого (breedingUrge генома) и обнуляется встречей. Поэтому
// именно его значение хранится между тиками, а hunger/thirst хранятся лишь
// затем, чтобы их было видно снаружи (сеть, сохранение, отладка).
//
// current — не производная величина: у желания есть инерция. Без неё
// животное, у которого голод и жажда почти равны, каждый тик бросалось бы
// то к траве, то к воде и не дошло бы никуда — поэтому выбранное желание
// удерживается, пока другое не перевесит его с заметным запасом
// (kDesireSwitch в HerbivoreSystem).
struct DesireComponent {
    float hunger = 0.0f;
    float thirst = 0.0f;
    float mating = 0.0f;

    Desire current = Desire::Idle;
};

} // namespace goblins
