#pragma once

namespace goblins {

// Сколько последних шагов животное помнит. Шесть — это примерно два-три
// разворота: достаточно, чтобы узнать клетку, с которой только что ушёл, и
// не хватает, чтобы помнить весь свой путь. Помнить больше и незачем, и
// вредно: зверь, для которого вся округа "уже хожена", перестал бы ходить.
inline constexpr int kTrailSteps = 6;

// Память ног: куда животное только что шло, где оно только что было и куда
// ему не удалось пройти.
//
// Компонент, а не переменные внутри системы, потому что система не имеет
// права хранить состояние между тиками (05_Entity.md, п.3), а помнить это
// нужно именно между тиками — в одном тике животное делает всего один шаг.
// Помнит это само животное, и хранится оно там же, где всё остальное, что
// у животного есть.
//
// Хранятся НАПРАВЛЕНИЯ, а не клетки: клетки восстанавливаются шагами назад
// от нынешней (core/Walk.hpp), и одно и то же число служит сразу двум
// разным вещам — "куда я шёл" (инерция) и "где я только что был" (след).
// Две записи одного и того же разъехались бы при первом же переносе
// животного.
//
// В файл мира не пишется: шесть последних шагов — не мир, а походка, и
// загруженное животное просто начинает помнить заново, с первого своего
// шага. Всё, что от этого меняется, — первые несколько шагов после
// открытия сохранения будут чуть менее уверенными.
struct MovementComponent {
    // Последние шаги, свежий первым: направление 0..7 в круговой нумерации
    // (core/Walk.hpp) или -1, если шага ещё не было.
    int recent[kTrailSteps] = {-1, -1, -1, -1, -1, -1};

    // Насколько крепко животное помнит, что туда не пройти, по каждому из
    // восьми направлений: 0..kFull. Ставится при столкновении с преградой и
    // тает со временем — вода уходит, животное и само сдвигается, и
    // вчерашняя стена сегодня может оказаться лугом.
    int blocked[8] = {};

    // Насколько давно нет продвижения, 0..kFull. Копится, когда шаг упёрся в
    // преграду или лёг на собственный след, и убывает с каждым удачным
    // шагом. Из него растут случайность шага и цена возврата: зверь, который
    // топчется, начинает пробовать то, чего не пробовал, — и тем выбирается
    // из угла, из тупика и из хождения туда-сюда между двумя клетками.
    int stuck = 0;
};

} // namespace goblins
