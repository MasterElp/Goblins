#pragma once

namespace goblins {

// Усталость: сколько сил истрачено на то, чтобы быть живым и ходить.
//
// Свой компонент, а не поле внутри тега вида, и это правило, а не вкус
// (docs/10_Goblins.md, п.1a): усталость — свойство ТЕЛА, а телом гоблин от
// зверя не отличается ничем (core/Body.hpp). Образец здесь звериный —
// InjuryComponent: хромота тоже лежит отдельно, а не полем в
// HerbivoreComponent, и оттого дать её гоблину — это emplace и вызов
// закона, и больше ничего.
//
// Полежав полем в GoblinComponent, она показала ровно ту цену, о которой
// предупреждает правило: перенести её оттуда стоило полного
// круга — система, расселение, рождение, протокол, дельта, файл мира,
// панель наблюдателя. Каждое гоблинское поле, положенное рядом с ней, этот
// круг удлиняло бы.
//
// Носит компонент пока один гоблин, и это не противоречие, а разделение
// формы и наличия: правильный дом заведён заранее, а вешается он тому, кому
// нужен. Зверю усталость понадобится тогда, когда ему будет чем её унять, —
// желания Rest у него нет, и копить её впустую значило бы завести поле,
// которое ни на что не влияет.
struct FatigueComponent {
    // 0..kFull (core/Scale.hpp). Копится от того, что существо живо, и
    // втрое быстрее — от того, что оно идёт; убывает, пока оно отдыхает.
    //
    // Хранится, в отличие от голода и жажды: тем есть что читать в теле
    // (пустеющие запасы, core/Needs.hpp), а усталости читать нечего — она
    // и есть то, что накопилось. Ровно та же причина, по которой хранится
    // желание пары.
    //
    // Это первая потребность, которую удовлетворяет МЕСТО, а не вещество,
    // и в этом весь её смысл. Траву съедают, и она кончается; вода течёт;
    // а место, на котором хорошо лежать, никуда не девается — к нему можно
    // вернуться. Из этого различия и вырастает всё остальное:
    // повторяющийся путь, тропа, лагерь (docs/10_Goblins.md, п.5).
    int fatigue = 0;
};

} // namespace goblins
