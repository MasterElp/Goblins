#pragma once

namespace goblins {

// Почва — это Entity, а не свойство тайла (04_WorldModel.md, п.3: тайл —
// пустой контейнер; всё, что "на земле", существует как Entity). На
// каждом тайле стоит ровно один такой Entity — терраформирующий слой,
// сгенерированный один раз при инициализации мира.
//
// moisture/rockiness/trampled — доли в тысячных, 0..kFull (core/Scale.hpp):
// - moisture   — влажность (выше рядом с водой);
// - rockiness  — каменистость: сколько в клетке камня, а не земли;
// - trampled   — утоптанность: насколько землю умяли ногами.
//
// Утоптанность вернулась, и вернулась с причиной. Прежняя жила ради одной
// функции — пригодности почвы для растения (habitatFit), — и была вторым
// способом сказать то, что уже говорит влажность: на плохой земле сухо, а
// на сухой земле трава не растёт. Её убрали и записали здесь обещание
// вернуть, когда по миру пойдут гоблины и начнут набивать тропы. Гоблины
// пошли.
//
// Теперь у неё есть и причина, и следствия, и все они в одном законе
// (core/Trample.hpp): её оставляет всякий сделанный шаг, она зарастает
// сама, по ней легче идти (core/Walk.hpp) и на ней хуже растёт трава. Поле
// в почве, а не свой компонент, потому что это свойство ЗЕМЛИ, и земля уже
// есть на каждой клетке; правило "состояние — свой компонент"
// (docs/10_Goblins.md, п.1a) — про свойства существ.
//
// Каменистость осталась и переживёт эту чистку: она не только
// красит тайл серым, сушит почву и держит склон от размыва, но и будет
// той залежью, из которой гоблины станут добывать камень. Её значение —
// доля камня в клетке, то самое число, из которого добытое вычитается.
//
// minerals — количество минералов, целое неотрицательное число (не
// нормализовано: это счётное количество "крупиц", а не доля — см.
// HydrologySystem, где минералы двигаются между соседними тайлами по
// правилу игры в песочную кучу).
struct SoilComponent {
    int moisture = 0;
    int rockiness = 0;
    int trampled = 0;
    int minerals = 0;
};

} // namespace goblins
