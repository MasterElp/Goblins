#pragma once

namespace goblins {

// Почва — это Entity, а не свойство тайла (04_WorldModel.md, п.3: тайл —
// пустой контейнер; всё, что "на земле", существует как Entity). На
// каждом тайле стоит ровно один такой Entity — терраформирующий слой,
// сгенерированный один раз при инициализации мира.
//
// moisture/rockiness нормализованы в [0, 1]:
// - moisture   — влажность (выше рядом с водой);
// - rockiness  — каменистость: сколько в клетке камня, а не земли.
//
// Утрамбованности здесь больше нет. Она существовала ради одной
// функции — пригодности почвы для растения (habitatFit), — а сама
// пригодность оказалась вторым способом сказать то, что уже говорит
// влажность: на плохой земле сухо, а на сухой земле трава не растёт. Один
// закон вместо двух (02_CorePrinciples.md, п.14: сложность возникает из
// простоты, а не из числа величин). Когда по миру пойдут гоблины и начнут
// набивать тропы, утрамбованность вернётся — но с причиной, а не про
// запас.
//
// Каменистость, наоборот, осталась и переживёт эту чистку: она не только
// красит тайл серым, сушит почву и держит склон от размыва, но и будет
// той залежью, из которой гоблины станут добывать камень. Её значение —
// доля камня в клетке, то самое число, из которого добытое вычитается.
//
// minerals — количество минералов, целое неотрицательное число (не
// нормализовано: это счётное количество "крупиц", а не доля — см.
// HydrologySystem, где минералы двигаются между соседними тайлами по
// правилу игры в песочную кучу).
struct SoilComponent {
    float moisture = 0.0f;
    float rockiness = 0.0f;
    int minerals = 0;
};

} // namespace goblins
