#pragma once

namespace goblins {

// Ягоды, висящие на кусте прямо сейчас.
//
// Отдельным компонентом, а не полем в PlantComponent, и это не мелочь:
// PlantComponent носят ВСЕ растения мира, и поле ягод было бы нулём на
// каждой травинке в каждом снимке, каждом слое и каждом файле мира. Та же
// причина, по которой хромота живёт в своём InjuryComponent, а не полем в
// теле (docs/10_Goblins.md, п.1a): состояние, которое есть не у всех,
// живёт своим домом.
//
// Ягоду СРЫВАЮТ, а не объедают: сбор не трогает развитость куста
// (core/Berries.hpp). В этом вся разница между лугом и ягодником — луг
// объедают, и он кончается; ягодник обирают, и он остаётся стоять, чтобы
// наполниться снова. Место при этом не исчезает, а лишь пустеет на время, и
// потому к нему есть смысл вернуться.
struct BerryComponent {
    // Сколько ягод висит. Целые штуки, а не доля: ягода — счётная вещь, как
    // крупица минерала (core/Scale.hpp).
    int berries = 0;

    // Крупицы минералов, ушедшие в эти ягоды из клетки под кустом. Уходят
    // вместе со съеденным — ровно так же, как крупицы травы уходят в
    // травоядное, — и возвращаются в мир навозом и падалью того, кто ягоды
    // съел. Вещество не берётся из ниоткуда и не пропадает.
    int minerals = 0;
};

} // namespace goblins
