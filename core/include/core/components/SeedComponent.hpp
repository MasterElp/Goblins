#pragma once

namespace goblins {

// Семя, лежащее в клетке и ждущее своего часа. Не растение: у него нет
// PlantComponent, оно не растёт, не пьёт, не ест минералы и не подлежит
// объеданию — оно только считает тики. Живое растение появится из него
// при прорастании, и вот тогда Entity получит PlantComponent
// (02_CorePrinciples.md, п.3: нет компонента — нет и возможности).
//
// Геном семени лежит рядом, в PlantGenomeComponent того же Entity: он уже
// помутирован при рождении семени и не меняется до прорастания. Оттуда же
// берётся и срок покоя (PlantGenomeComponent::seedDormancy) — как долго
// семя лежит, прежде чем сможет прорасти.
//
// Семя делит клетку с растением-родителем: тайл занимает не оно, а
// растение (04_WorldModel.md, п.4), поэтому "одна клетка — одно растение"
// не нарушается. Зато семя на клетке может быть только одно: место в
// земле, где семечко пережидает, — тоже место.
struct SeedComponent {
    // Прожитые тики с момента, как семя легло в клетку. Сравнивается со
    // сроком покоя генома, а потом — с окном ожидания (kSeedWaitTicks в
    // PlantSystem.cpp), после которого семя сгнивает.
    int age = 0;

    // Запаса влаги семя больше не несёт: его некуда положить и незачем —
    // у проростка нет запаса влаги, как и у взрослого растения
    // (PlantComponent). Пить он начнёт из своей клетки в первый же тик.
    //
    // Минералов семя тоже не несёт: минералы решают только предел роста
    // (PlantSystem.cpp, mineralCeiling), а не право прорасти. Проросток
    // наберёт свои сам из почвы клетки, как и любое растущее растение.
};

} // namespace goblins
