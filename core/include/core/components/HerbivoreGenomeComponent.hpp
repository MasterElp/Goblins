#pragma once

namespace goblins {

// Наследуемые параметры одного травоядного — его геном. Только данные, без
// логики (05_Entity.md, п.2): что означает каждое поле, в каких пределах оно
// живёт и сколько стоит, знает не компонент, а таблица черт kHerbivoreTraits
// (core/generation/HerbivoreGenetics.hpp) — там же лежат правила порождения,
// скрещивания и мутации генома.
//
// Устроено ровно так же, как PlantGenomeComponent: геном принадлежит
// конкретному животному, а не виду; species — только индекс архетипа в
// HerbivoreSpeciesComponent на World Entity, и архетип задаёт центр, вокруг
// которого мутациям разрешено гулять. "Новое существо — это другая таблица
// черт при той же механике" (docs/08_Plants.md, п.2) — здесь это и
// происходит буквально: механика общая (core/generation/Genetics.hpp),
// таблица своя.
//
// Значения по умолчанию — примерно "средний вид" (все черты вполовину
// вложенного бюджета). Реально используемые геномы всегда приходят из
// makeHerbivoreSpecies/crossHerbivoreGenomes.
struct HerbivoreGenomeComponent {
    // Индекс вида в HerbivoreSpeciesComponent::archetypes. Не мутирует:
    // потомок всегда того же вида, что и родители.
    int species = 0;

    // Возраст (в тиках), с которого животное может размножаться. Он же —
    // срок взросления: телёнок дорастает до взрослого размера примерно к
    // этому возрасту (см. HerbivoreSystem), отдельной "скорости роста" в
    // геноме нет.
    float maturityAge = 1400.0f;
    // Возраст, в котором животное умирает от старости. Заметно больше, чем
    // у травы (300..2500 тиков): травоядное должно переживать не одно
    // поколение той травы, которой питается, иначе луг и стадо жили бы в
    // одном темпе и стадо было бы просто "медленной травой".
    float maxAge = 9000.0f;

    // Скорость — клеток за тик. Дробная: животное копит шаг
    // (HerbivoreComponent::stepProgress) и переставляет ноги, когда
    // накопит целую клетку. Быстрое животное первым добирается до корма и
    // до партнёра, но и энергии на шаги тратит больше — цена скорости
    // берётся не только бюджетом, но и самой жизнью.
    float speed = 0.4f;

    // Дальность восприятия — в клетках. Животное знает только то, что
    // видит отсюда (02_CorePrinciples.md, п.6: ИИ не обладает информацией,
    // которой не может обладать сам персонаж): дальше этого радиуса для
    // него нет ни травы, ни воды, ни сородичей, и оно бродит наугад.
    float perception = 6.0f;

    // Сколько энергии животное способно держать в себе и сколько тратит за
    // тик просто на то, чтобы жить (в пересчёте на взрослый размер).
    // Запас — это способность пережить бескормицу, расход — цена
    // существования; и то, и другое покупается бюджетом.
    float energyCapacity = 60.0f;
    float energyUpkeep = 0.12f;

    // Сколько развитости растения животное скусывает за тик кормёжки (при
    // взрослом размере). Растение от этого не исчезает: оно теряет
    // биомассу и получает стресс, а отрастёт или погибнет — решит
    // PlantSystem по своим законам.
    float biteSize = 0.2f;
    // Какая доля скушенной биомассы превращается в энергию. Остальное
    // проходит насквозь и возвращается в мир перегноем.
    float digestion = 0.65f;

    // Вода в теле: запас и расход за тик. Пьёт животное из воды на своей
    // или соседней клетке (HerbivoreSystem), немного получает из самой
    // травы — но собственного источника воды у него нет, как и у растения.
    float waterCapacity = 30.0f;
    float waterUpkeep = 0.1f;

    // Сколько целых крупиц минералов (белка) нужно накопить, чтобы вырасти
    // полностью. Ровно те же крупицы, что ходят по кругу почва -> растение
    // -> перегной -> почва: травоядное встраивается в этот круг третьим
    // звеном, а не заводит собственное вещество (02_CorePrinciples.md,
    // п.12b — круг описывает путь вещества, а не закон сохранения).
    float proteinNeed = 5.0f;

    // Насколько быстро копится желание размножаться (за тик, у сытого
    // взрослого). Самое сильное преимущество в мире, где еда конечна, —
    // поэтому и стоит дороже всех остальных черт, как seed_chance у травы.
    float breedingUrge = 0.01f;
};

} // namespace goblins
