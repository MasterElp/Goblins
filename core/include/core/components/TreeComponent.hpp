// Метка "это растение — дерево", а не трава. Пустая: сам факт наличия и
// есть данные (02_CorePrinciples.md, п.3), как у ImpassableComponent и
// WaterSourceComponent.
//
// Дерево — то же растение, что и трава: тот же PlantComponent (возраст,
// развитость, крупицы), тот же PlantGenomeComponent, та же PlantSystem, тот
// же способ умереть и лечь перегноем. Так же, как хищник — то же животное,
// что и травоядное, и отличается меткой да таблицей черт
// (AnimalSpeciesComponent). Заводить второй компонент состояния и вторую
// систему значило бы завести вторую копию роста, смерти и семян — и она
// разъехалась бы с первой, как разъезжается всякий второй экземпляр закона.
//
// Отличий у дерева ровно четыре, и все они читаются там, где применяются:
//   1. Живёт на порядок дольше травы (kTreeTraits, PlantGenetics.hpp).
//   2. Кормится корнями с площади вокруг себя, а не с одной клетки, и
//      растёт ровно настолько, насколько эта площадь его прокормила
//      (core/Trees.hpp) — отсюда и островки.
//   3. Не встаёт вплотную к другому дереву: корни не поделить.
//   4. Роняет семена за несколько клеток, а не в соседнюю.
//
// Метки "это трава" нет, и она не нужна: трава — растение по умолчанию, а
// дерево — растение с меткой. Второй пустой компонент на каждый куст
// добавил бы полю сохранения и снапшоту вес, ничего не сообщив.
