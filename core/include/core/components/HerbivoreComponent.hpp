#pragma once

#include <cstdint>

namespace goblins {

// Пол. Два значения и ничего больше: размножение требует встречи двух
// животных разного пола (см. HerbivoreSystem). Пол не наследуется и не
// мутирует — он разыгрывается при рождении, поэтому живёт в состоянии, а
// не в геноме.
enum class Sex : std::uint8_t {
    Female = 0,
    Male = 1,
};

// Имя пола — не логика, а имя значения (05_Entity.md, п.2: компонент не
// содержит логики). Лежит рядом с самим перечислением, чтобы файл мира,
// сетевой протокол и вывод сервера называли пол одинаково и в трёх местах
// не разъезжались.
inline const char* sexName(Sex sex) {
    return sex == Sex::Female ? "female" : "male";
}

// Обратная сторона той же пары — для чтения файла мира. Всё, что не
// "male", — самка: пол хранится двумя значениями, и третьего исхода у
// разбора быть не должно.
inline Sex sexFromName(const std::string& name) {
    return name == "male" ? Sex::Male : Sex::Female;
}

// Глубина воды, которую травоядное переходит вброд. Выше неё для него не
// вода, а препятствие: пить оно приходит на берег, а в реку не лезет.
//
// Число общее для генерации (HerbivoreSeeding.cpp: куда можно выпустить
// первое поголовье) и симуляции (HerbivoreSystem.cpp: куда можно шагнуть),
// поэтому живёт рядом с самим понятием "травоядное", а не продублировано в
// обеих — ровно как kVoidHeight при высоте (HeightComponent.hpp). Разойдись
// эти два числа, и стадо оказалось бы расставленным там, куда потом само
// не смогло бы вернуться.
inline constexpr float kWadeDepth = 0.15f;

// Текущее состояние живого травоядного — то, что меняется каждый тик, в
// отличие от HerbivoreGenomeComponent (наследуемые параметры, за жизнь не
// меняются). Наличие этого компонента и означает "Entity — живое
// травоядное": умершее теряет его вместе с геномом и желаниями
// (02_CorePrinciples.md, п.3).
//
// Координаты, как и у растения, хранит PositionComponent. Непроходимости у
// травоядного нет: на одной клетке их может стоять сколько угодно, и трава
// под ними продолжает расти (04_WorldModel.md, п.4 — непроходимость это
// свойство Entity, и здесь его просто нет).
struct HerbivoreComponent {
    // Прожитые тики. Сравнивается с maturityAge/maxAge генома.
    float age = 0.0f;

    // Развитость, 0..1: 0 — новорождённый, 1 — взрослое животное. Как и у
    // растения, ограничена сверху накопленным белком (protein /
    // proteinNeed): без вещества животное физически не может стать больше.
    // От размера зависит и сколько оно ест, и сколько тратит.
    float growth = 0.0f;

    Sex sex = Sex::Female;

    // Энергия — то, на что животное живёт и двигается. Приходит только из
    // съеденной травы, тратится каждый тик на существование и на шаги. При
    // нуле начинается голодная смерть (копится stress).
    float energy = 0.0f;

    // Вода в теле. Приходит из питья и немного из самой травы, тратится
    // каждый тик. При нуле — то же, что с энергией, только быстрее.
    float water = 0.0f;

    // Целые крупицы минералов, вынутые из съеденных растений, — тот самый
    // "белок". Ими животное растёт, ими же наделяет потомка, и ровно они
    // возвращаются в мир перегноем: с испражнениями при жизни и целиком
    // после смерти.
    int protein = 0;
    // Накопленная доля до следующей целой крупицы (0..1): скусывается
    // биомасса дробно, а минералы и в почве, и в растении — счётные.
    float proteinPending = 0.0f;

    // Крупицы, уже прошедшие через животное и ждущие испражнения, и доля
    // до следующей такой крупицы. Перегной ложится не каждый тик по чуть-
    // чуть, а порциями (см. kDungDrop в HerbivoreSystem): это навоз, а не
    // равномерная плёнка.
    int dung = 0;
    float dungPending = 0.0f;

    // Накопленный шаг, 0..1: за тик прибавляется скорость из генома, при
    // единице животное переставляет ноги на соседнюю клетку. Так дробная
    // скорость превращается в целые клетки, не превращая мир в сетку из
    // "быстрых" и "медленных" в один и тот же тик.
    float stepProgress = 0.0f;

    // Накопленное неблагополучие, 0..1 — ровно как у растения. Растёт,
    // когда кончилась энергия или вода, и медленно спадает, когда всё в
    // порядке. При 1 животное погибает — это смерть от условий, в отличие
    // от смерти от старости (age >= maxAge).
    float stress = 0.0f;
};

} // namespace goblins
