#pragma once

namespace goblins {

// Перегной на тайле — то, что осталось от умершего растения. Живёт на том
// же терраформирующем Entity тайла, что SoilComponent, ровно как и
// WaterComponent: это не самостоятельный объект на земле, а состояние
// самой земли — слой органики, который постепенно уходит в почву. Наличие
// компонента и есть факт "здесь лежит перегной" (02_CorePrinciples.md,
// п.3), поэтому у чистой почвы компонента просто нет, а не нулевое поле.
//
// Умершие на одной клетке растения складываются в один и тот же перегной
// (minerals суммируются) — иначе на старом лугу копились бы десятки
// отдельных остатков на одном тайле.
struct HumusComponent {
    // Сколько целых крупиц минералов ещё не вернулось в почву. Ровно то
    // количество, которое растение при жизни вынуло из SoilComponent
    // своей клетки: минералы не создаются и не исчезают, они лишь ходят
    // по кругу почва -> растение -> перегной -> почва.
    int minerals = 0;

    // Накопленная доля до возврата следующей крупицы (0..1) — скорость
    // разложения (WorldPropertiesComponent.humusDecayRate) дробная, а
    // минералы в почве целые, поэтому доля копится здесь.
    float pending = 0.0f;
};

} // namespace goblins
