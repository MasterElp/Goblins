#pragma once

namespace goblins {

// Встревоженность клетки — след того, что здесь недавно охотились. Живёт на
// том же терраформирующем Entity тайла, что SoilComponent, WaterComponent,
// HumusComponent и CarcassComponent: это не отдельный объект на земле, а
// состояние самой земли, как перегной. Наличие компонента и есть факт
// "здесь было страшно" (02_CorePrinciples.md, п.3).
//
// Зачем он нужен. У хищников нет территорий: они не расходятся по карте, а
// сходятся к одному стаду и выбивают его под ноль — и вымирают следом. Дать
// им прямое правило "видишь другого хищника — уходи" значило бы выдумать
// поведение; встревоженная земля даёт то же расползание СЛЕДСТВИЕМ. Добыча
// уходит с настрелянного участка (уровень тревоги входит в её страх,
// AnimalSystem), участок пустеет, и хищнику ничего не остаётся, кроме как
// искать нетронутое место. Территория получается сама, из голода и страха.
//
// Знать это животному можно: тревога — свойство клетки, на которой оно
// стоит (кровь, запах, вытоптанная трава), а не сведения о том, что
// происходит где-то вдали (02_CorePrinciples.md, п.6). Поэтому она и
// читается только под ногами, а не в радиусе восприятия.
//
// Тает сама собой, как гниёт падаль: страшное место со временем снова
// становится обычным.
struct DangerComponent {
    // 0..kFull (core/Scale.hpp), та же шкала долей, что у влажности и
    // развитости растения.
    int level = 0;
};

} // namespace goblins
