#pragma once

#include "core/Scale.hpp"

namespace goblins {

// Увечье: животное хромает и оттого ходит медленнее.
//
// Появляется у хищника, укусившего рогатую добычу (AnimalSystem, п.8
// "Зубы"): удар по рогам не отнимает у него здоровья, но на время лишает
// хода. Это и есть защита травоядного — не пережить укус, а сделать
// второй укус недостижимым: хромой хищник отстаёт от всякого, кто быстрее
// его нынешней скорости, и погоня срывается сама.
//
// Отдельный компонент, а не поле в теле (AnimalComponent), по той же
// причине, что и память ног (MovementComponent): тело — это то, из чего
// животное состоит и чем живёт, а хромота — временное состояние, которое
// проходит. И по той же причине его нет в файле мира: срок хромоты
// переживать сохранение незачем, загруженный зверь просто здоров.
//
// Хромота не складывается: два укуса подряд не удваивают срок, а
// продлевают его до большего из двух. Это состояние ("нога не работает"), а
// не счётчик полученных ударов.
struct InjuryComponent {
    // Сколько ещё тиков животное хромает. Убывает по единице за тик
    // (AnimalSystem, п.1 "Тело") — срок, а не скорость: дробям в состоянии
    // мира места нет (core/Scale.hpp).
    int lameTicks = 0;

    // Доля обычной скорости, пока животное хромает: kFull — нетронутая
    // скорость (сюда не попадает, пока lameTicks == 0), меньше — тем
    // тяжелее укус. Считается из рогов жертвы в момент удара, тем же
    // геномом (defense), что и lameTicks: слабо вооружённый вид калечит
    // слабее, а не только короче.
    int lameShare = kFull;
};

} // namespace goblins
