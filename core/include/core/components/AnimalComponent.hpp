#pragma once

#include <cstdint>
#include <string>

#include "core/Scale.hpp"

namespace goblins {

// Пол. Два значения и ничего больше: размножение требует встречи двух
// животных разного пола (см. AnimalSystem). Пол не наследуется и не
// мутирует — он разыгрывается при рождении, поэтому живёт в состоянии, а
// не в геноме.
enum class Sex : std::uint8_t {
    Female = 0,
    Male = 1,
};

// Имя пола — не логика, а имя значения (05_Entity.md, п.2: компонент не
// содержит логики). Лежит рядом с самим перечислением, чтобы файл мира,
// сетевой протокол и вывод сервера называли пол одинаково и в трёх местах
// не разъезжались.
inline const char* sexName(Sex sex) {
    return sex == Sex::Female ? "female" : "male";
}

// Обратная сторона той же пары — для чтения файла мира. Всё, что не
// "male", — самка: пол хранится двумя значениями, и третьего исхода у
// разбора быть не должно.
inline Sex sexFromName(const std::string& name) {
    return name == "male" ? Sex::Male : Sex::Female;
}

// Порога глубины, до которого животное переходит воду вброд, здесь нет и
// быть не должно: вода для животного — препятствие целиком, любой глубины
// (AnimalSystem.cpp, standable; AnimalSeeding.cpp — та же проверка при
// расселении). Пить оно приходит на берег, а в воду не заходит вовсе.

// Тело живого животного — то, что меняется каждый тик, в отличие от
// AnimalGenomeComponent (наследуемые параметры, за жизнь не меняются).
// Наличие этого компонента и означает "Entity — живое животное": умершее
// теряет его вместе с геномом и желаниями (02_CorePrinciples.md, п.3).
//
// Тело у травоядного и у хищника одно и то же: и тот, и другой стареют,
// тратят энергию и воду, растут на накопленном белке, устают и гибнут по
// одним законам. Разница между ними — не в теле, а в диете, и выражена
// она отдельными компонентами-тегами (HerbivoreComponent /
// PredatorComponent): "поведение определяется компонентами"
// (02_CorePrinciples.md, п.3), а не типом объекта.
//
// Координаты, как и у растения, хранит PositionComponent. Непроходимости у
// животного нет: на одной клетке их может стоять сколько угодно, и трава
// под ними продолжает расти (04_WorldModel.md, п.4 — непроходимость это
// свойство Entity, и здесь его просто нет).
struct AnimalComponent {
    // Прожитые тики. Сравнивается с maturityAge/maxAge генома.
    int age = 0;

    // Развитость, 0..kFull: 0 — новорождённый, kFull — взрослое. Как и у
    // растения, ограничена сверху накопленным белком (protein /
    // proteinNeed): без вещества животное физически не может стать больше.
    // От размера зависит и сколько оно ест, и сколько тратит, и сколько
    // мяса от него останется. Накопителя рядом нет: развитость выводится
    // из возраста (age / maturityAge), а прирост за тик — это разность
    // двух целых делений, которая ничего помнить не требует.
    int growth = 0;

    Sex sex = Sex::Female;

    // Энергия — то, на что животное живёт и двигается. Приходит только из
    // съеденного (трава для травоядного, падаль для хищника), тратится
    // каждый тик на существование и на шаги. При нуле начинается голодная
    // смерть: здоровье убывает, пока не кончится. В тысячных прежних
    // единиц (core/Scale.hpp) — той же шкале, в которой меряется биомасса
    // съеденного, иначе "сколько энергии в куске" не было бы целым.
    int energy = 0;

    // Вода в теле, в тех же тысячных. Приходит из питья и немного из самой
    // еды, тратится каждый тик. При нуле — то же, что с энергией, только
    // быстрее.
    int water = 0;

    // Целые крупицы минералов, вынутые из съеденного, — тот самый "белок".
    // Ими животное растёт, ими же наделяет потомка, и ровно они
    // возвращаются в мир: с испражнениями при жизни и с падалью после
    // смерти. Накопителей доли (proteinPending) рядом больше нет: крупицы
    // делятся между едоками целочисленно, прямо в тот тик, когда куст или
    // туша их отдаёт.
    int protein = 0;

    // Крупицы, уже прошедшие через животное и ждущие испражнения. Перегной
    // ложится не каждый тик по чуть-чуть, а порциями (см. kDungDrop в
    // AnimalSystem): это навоз, а не равномерная плёнка. Как часто крупица
    // трогается с места, задаёт срок (kDungPeriod), а не дробная скорость,
    // — поэтому и здесь накопитель не нужен.
    int dung = 0;

    // Целость тела, 0..kFull, — одна на все беды. Отнимают её и зубы хищника, и
    // пустой желудок, и пустая фляга; сама она медленно восстанавливается у
    // сытого и напоенного. При нуле животное погибает.
    //
    // Раньше их было две: health держал раны, а stress копил истощение, и
    // обе убивали при своём краю. Различать рану и голод по двум счётчикам
    // не было нужды: причина смерти видна в тот самый тик, когда животное
    // умирает, — по тому, что у него кончилось. Один закон вместо двух
    // одинаковых.
    int health = kFull;

    // Сколько тиков матери ещё отдыхать после родов. Пока не ноль, желание
    // пары не копится вовсе (см. AnimalSystem, GoblinSystem).
    //
    // Срок, а не скорость: дробям в состоянии мира места нет
    // (core/Scale.hpp). Ставится при родах долей предельного возраста
    // (birthRestOf, core/Body.hpp), убывает по единице в advanceBody.
    //
    // Живёт в теле, а не среди желаний, и это не мелочь: мать не РЕШАЕТ
    // отдыхать и не хочет отдыха — она просто ещё не готова, и прочесть это
    // в теле неоткуда, как и усталость гоблина. Поле общее для зверя и
    // гоблина, потому что общее у них тело.
    int recovery = 0;

    // Накопленный шаг, 0..kFull-1: за тик прибавляется скорость из генома
    // (тысячные клетки за тик), при полной единице животное переставляет
    // ноги на соседнюю клетку. Так мелкая разница в скорости превращается
    // в целые клетки, не превращая мир в сетку из "быстрых" и "медленных"
    // в один и тот же тик, — а исход погони по-прежнему решает разница в
    // сотые доли клетки, которую целая шкала сохраняет полностью.
    int stepProgress = 0;
};

} // namespace goblins
