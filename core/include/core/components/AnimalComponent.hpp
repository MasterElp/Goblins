#pragma once

#include <cstdint>
#include <string>

namespace goblins {

// Пол. Два значения и ничего больше: размножение требует встречи двух
// животных разного пола (см. AnimalSystem). Пол не наследуется и не
// мутирует — он разыгрывается при рождении, поэтому живёт в состоянии, а
// не в геноме.
enum class Sex : std::uint8_t {
    Female = 0,
    Male = 1,
};

// Имя пола — не логика, а имя значения (05_Entity.md, п.2: компонент не
// содержит логики). Лежит рядом с самим перечислением, чтобы файл мира,
// сетевой протокол и вывод сервера называли пол одинаково и в трёх местах
// не разъезжались.
inline const char* sexName(Sex sex) {
    return sex == Sex::Female ? "female" : "male";
}

// Обратная сторона той же пары — для чтения файла мира. Всё, что не
// "male", — самка: пол хранится двумя значениями, и третьего исхода у
// разбора быть не должно.
inline Sex sexFromName(const std::string& name) {
    return name == "male" ? Sex::Male : Sex::Female;
}

// Порога глубины, до которого животное переходит воду вброд, здесь нет и
// быть не должно: вода для животного — препятствие целиком, любой глубины
// (AnimalSystem.cpp, standable; AnimalSeeding.cpp — та же проверка при
// расселении). Пить оно приходит на берег, а в воду не заходит вовсе.

// Тело живого животного — то, что меняется каждый тик, в отличие от
// AnimalGenomeComponent (наследуемые параметры, за жизнь не меняются).
// Наличие этого компонента и означает "Entity — живое животное": умершее
// теряет его вместе с геномом и желаниями (02_CorePrinciples.md, п.3).
//
// Тело у травоядного и у хищника одно и то же: и тот, и другой стареют,
// тратят энергию и воду, растут на накопленном белке, устают и гибнут по
// одним законам. Разница между ними — не в теле, а в диете, и выражена
// она отдельными компонентами-тегами (HerbivoreComponent /
// PredatorComponent): "поведение определяется компонентами"
// (02_CorePrinciples.md, п.3), а не типом объекта.
//
// Координаты, как и у растения, хранит PositionComponent. Непроходимости у
// животного нет: на одной клетке их может стоять сколько угодно, и трава
// под ними продолжает расти (04_WorldModel.md, п.4 — непроходимость это
// свойство Entity, и здесь его просто нет).
struct AnimalComponent {
    // Прожитые тики. Сравнивается с maturityAge/maxAge генома.
    float age = 0.0f;

    // Развитость, 0..1: 0 — новорождённый, 1 — взрослое животное. Как и у
    // растения, ограничена сверху накопленным белком (protein /
    // proteinNeed): без вещества животное физически не может стать больше.
    // От размера зависит и сколько оно ест, и сколько тратит, и сколько
    // мяса от него останется.
    float growth = 0.0f;

    Sex sex = Sex::Female;

    // Энергия — то, на что животное живёт и двигается. Приходит только из
    // съеденного (трава для травоядного, падаль для хищника), тратится
    // каждый тик на существование и на шаги. При нуле начинается голодная
    // смерть (копится stress).
    float energy = 0.0f;

    // Вода в теле. Приходит из питья и немного из самой еды, тратится
    // каждый тик. При нуле — то же, что с энергией, только быстрее.
    float water = 0.0f;

    // Целые крупицы минералов, вынутые из съеденного, — тот самый "белок".
    // Ими животное растёт, ими же наделяет потомка, и ровно они
    // возвращаются в мир: с испражнениями при жизни и с падалью после
    // смерти.
    int protein = 0;
    // Накопленная доля до следующей целой крупицы (0..1): еда откусывается
    // дробно, а минералы и в почве, и в растении — счётные.
    float proteinPending = 0.0f;

    // Крупицы, уже прошедшие через животное и ждущие испражнения, и доля
    // до следующей такой крупицы. Перегной ложится не каждый тик по чуть-
    // чуть, а порциями (см. kDungDrop в AnimalSystem): это навоз, а не
    // равномерная плёнка.
    int dung = 0;
    float dungPending = 0.0f;

    // Целость тела, 0..1. Отнимают её только зубы хищника; сама она
    // медленно восстанавливается у сытого животного. При нуле животное
    // погибает — это смерть от чужих зубов, в отличие от смерти от голода
    // (stress) и от старости (age >= maxAge).
    //
    // Отдельно от stress, а не одним "здоровьем" на всё: рана и истощение
    // — разные причины смерти, и различать их важно не для красоты. Мир
    // без хищников убивает животных голодом и старостью, мир с хищниками —
    // ещё и зубами; если бы это была одна величина, отличить одно от
    // другого стало бы невозможно ни в отладке, ни в самой модели.
    float health = 1.0f;

    // Накопленный шаг, 0..1: за тик прибавляется скорость из генома, при
    // единице животное переставляет ноги на соседнюю клетку. Так дробная
    // скорость превращается в целые клетки, не превращая мир в сетку из
    // "быстрых" и "медленных" в один и тот же тик.
    float stepProgress = 0.0f;

    // Накопленное неблагополучие, 0..1 — ровно как у растения. Растёт,
    // когда кончилась энергия или вода, и медленно спадает, когда всё в
    // порядке. При 1 животное погибает — это смерть от условий.
    float stress = 0.0f;
};

} // namespace goblins
