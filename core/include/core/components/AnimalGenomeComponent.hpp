#pragma once

#include "core/Scale.hpp"

namespace goblins {

// Наследуемые параметры одного животного — его геном. Только данные, без
// логики (05_Entity.md, п.2): что означает каждое поле, в каких пределах оно
// живёт и сколько стоит, знает не компонент, а таблица черт своей диеты
// (kHerbivoreTraits / kPredatorTraits, core/generation/AnimalGenetics.hpp) —
// там же лежат правила порождения, скрещивания и мутации генома.
//
// Поля общие для травоядного, хищника и гоблина, а таблицы черт разные: у
// каждой диеты свои диапазоны и свои цены. Это прямое продолжение того же
// приёма, которым устроены растения: "новое существо — это другая таблица
// черт при той же механике" (docs/08_Plants.md, п.2).
//
// Поля, которыми пользуется не всякий, отсюда ушли, и это стоило того.
// Прежде их было три — attack только у хищника, defense и goreChance только
// у травоядного, — и каждое означало, что таблицы разной ФОРМЫ, а не только
// разных чисел. Теперь форма у всех трёх одна: девять черт, и удар один на
// всех (core/Strike.hpp).
//
// Значения по умолчанию — примерно "средний вид" (все черты вполовину
// вложенного бюджета). Реально используемые геномы всегда приходят из
// makeHerbivoreSpecies/makePredatorSpecies и crossGenomes.
struct AnimalGenomeComponent {
    // Индекс вида в AnimalSpeciesComponent — в списке своей диеты
    // (herbivores или predators). Не мутирует: потомок всегда того же
    // вида, что и родители.
    int species = 0;

    // Размер взрослого, в тысячных нынешнего зверя (kFull — ровно он).
    // Черта-ниша: ничего не стоит в бюджете преимуществ, потому что крупным
    // быть не лучше и не хуже, а иначе.
    //
    // Из него выведено всё, что в теле от величины и зависит: запас энергии
    // и воды, потребность в белке, срок взросления, сила удара и вес туши
    // (core/Body.hpp, core/Strike.hpp). Прежде это были отдельные черты, и
    // вид мог купить себе большое вместилище, не становясь большим, — то
    // есть быть крупным даром.
    int adultSize = kFull;

    // Возраст, в котором животное умирает от старости. Заметно больше, чем
    // у травы (300..2500 тиков): животное должно переживать не одно
    // поколение той травы, которой держится вся пищевая цепь.
    //
    // Возраста взросления рядом больше нет: он выведен из размера
    // (maturityAgeOf, core/Body.hpp) — крупный растёт дольше, и это не
    // выбор вида, а следствие его величины.
    int maxAge = 9000;

    // Скорость — тысячных клетки за тик (kFull = одна клетка). Животное
    // копит шаг (AnimalComponent::stepProgress) и переставляет ноги, когда
    // накопит целую клетку. Быстрый первым добирается до корма, до воды и
    // до партнёра, быстрее догоняет и быстрее убегает — но и энергии на
    // шаги тратит больше.
    //
    // От размера НЕ выводится намеренно: крупный в этом мире не обязан быть
    // ни быстрее, ни медленнее мелкого. Иначе размер решал бы и исход
    // погони, а погоня — единственное, что вообще держит пару хищник-жертва.
    int speed = 400;

    // Дальность восприятия — в целых клетках, и шкалы у неё нет: видно до
    // клетки, а не до её тысячной доли. Животное знает только то, что
    // видит отсюда (02_CorePrinciples.md, п.6: ИИ не обладает информацией,
    // которой не может обладать сам персонаж): дальше этого радиуса для
    // него нет ни травы, ни воды, ни сородичей, ни добычи, ни опасности.
    int perception = 6;

    // Сколько энергии и воды тело тратит за тик просто на то, чтобы жить (в
    // пересчёте на взрослый размер), в тысячных прежних единиц. Запасы, в
    // которые это тратится, выведены из размера (energyCapacityOf,
    // waterCapacityOf) — а вот обмен веществ остаётся выбором вида: при
    // одной и той же величине можно быть прожорливым или экономным, и
    // именно этим хищник покупает себе долгую жизнь между двумя добычами.
    int energyUpkeep = 120;
    int waterUpkeep = 100;

    // Сколько еды животное откусывает за тик (при взрослом размере) — для
    // травоядного это развитость растения, для хищника мясо падали, и
    // измеряются они одной шкалой биомассы (тысячные, kFull = взрослый
    // куст).
    int biteSize = 200;

    // Насколько быстро копится желание размножаться (тысячных за тик, у
    // сытого взрослого). Самое сильное преимущество в мире, где еда
    // конечна, — поэтому и стоит дороже всех остальных черт, как
    // seed_chance у травы.
    int breedingUrge = 10;

    // Меткость, 0..kFull: как часто удар вообще попадает (core/Strike.hpp).
    //
    // Единственная черта боя, оставшаяся покупаемой, и она есть у всех трёх
    // диет. Прежде их было три и все они были однобокими: attack только у
    // хищника, defense и goreChance только у травоядного. Сила удара теперь
    // берётся из размера — кто крупнее, тот бьёт тяжелее, — а вид выбирает
    // лишь, насколько он ловок.
    int hitChance = 500;
};

} // namespace goblins
