#pragma once

namespace goblins {

// Наследуемые параметры одного животного — его геном. Только данные, без
// логики (05_Entity.md, п.2): что означает каждое поле, в каких пределах оно
// живёт и сколько стоит, знает не компонент, а таблица черт своей диеты
// (kHerbivoreTraits / kPredatorTraits, core/generation/AnimalGenetics.hpp) —
// там же лежат правила порождения, скрещивания и мутации генома.
//
// Поля общие для травоядного и хищника, а таблицы черт разные: у каждой
// диеты свои диапазоны и свои цены, а часть полей одна из них не
// использует вовсе (травоядное не кусает никого, поэтому attack ему не
// нужен). Это прямое продолжение того же приёма, которым устроены растения:
// "новое существо — это другая таблица черт при той же механике"
// (docs/08_Plants.md, п.2). Заводить второй тип генома ради одного поля
// значило бы развести по двум типам и всё остальное — тело, желания,
// размножение, — которое у них общее.
//
// Значения по умолчанию — примерно "средний вид" (все черты вполовину
// вложенного бюджета). Реально используемые геномы всегда приходят из
// makeHerbivoreSpecies/makePredatorSpecies и crossGenomes.
struct AnimalGenomeComponent {
    // Индекс вида в AnimalSpeciesComponent — в списке своей диеты
    // (herbivores или predators). Не мутирует: потомок всегда того же
    // вида, что и родители.
    int species = 0;

    // Возраст (в тиках), с которого животное может размножаться. Он же —
    // срок взросления: детёныш дорастает до взрослого размера примерно к
    // этому возрасту (см. AnimalSystem), отдельной "скорости роста" в
    // геноме нет.
    float maturityAge = 1400.0f;
    // Возраст, в котором животное умирает от старости. Заметно больше, чем
    // у травы (300..2500 тиков): животное должно переживать не одно
    // поколение той травы, которой держится вся пищевая цепь.
    float maxAge = 9000.0f;

    // Скорость — клеток за тик. Дробная: животное копит шаг
    // (AnimalComponent::stepProgress) и переставляет ноги, когда накопит
    // целую клетку. Быстрый первым добирается до корма, до воды и до
    // партнёра, быстрее догоняет и быстрее убегает — но и энергии на шаги
    // тратит больше.
    float speed = 0.4f;

    // Дальность восприятия — в клетках. Животное знает только то, что
    // видит отсюда (02_CorePrinciples.md, п.6: ИИ не обладает информацией,
    // которой не может обладать сам персонаж): дальше этого радиуса для
    // него нет ни травы, ни воды, ни сородичей, ни добычи, ни опасности.
    float perception = 6.0f;

    // Сколько энергии животное способно держать в себе и сколько тратит за
    // тик просто на то, чтобы жить (в пересчёте на взрослый размер).
    float energyCapacity = 60.0f;
    float energyUpkeep = 0.12f;

    // Сколько еды животное откусывает за тик (при взрослом размере) — для
    // травоядного это развитость растения, для хищника мясо падали, и
    // измеряются они одной шкалой биомассы.
    float biteSize = 0.2f;
    // Какая доля откушенного превращается в энергию. Остальное проходит
    // насквозь и возвращается в мир перегноем.
    float digestion = 0.65f;

    // Вода в теле: запас и расход за тик. Пьёт животное из воды на своей
    // или соседней клетке (AnimalSystem), немного получает из самой еды —
    // но собственного источника воды у него нет, как и у растения.
    float waterCapacity = 30.0f;
    float waterUpkeep = 0.1f;

    // Сколько целых крупиц минералов (белка) нужно накопить, чтобы вырасти
    // полностью. Ровно те же крупицы, что ходят по кругу почва -> растение
    // -> травоядное -> хищник -> перегной -> почва.
    float proteinNeed = 5.0f;

    // Насколько быстро копится желание размножаться (за тик, у сытого
    // взрослого). Самое сильное преимущество в мире, где еда конечна, —
    // поэтому и стоит дороже всех остальных черт, как seed_chance у травы.
    float breedingUrge = 0.01f;

    // Сколько целости тела (AnimalComponent::health) отнимает у жертвы один
    // удар. Черта только хищной таблицы: травоядное никого не кусает, и у
    // его генома это поле просто не используется (см. комментарий к
    // структуре выше).
    float attack = 0.15f;
};

} // namespace goblins
