#pragma once

#include "core/Scale.hpp"
#include "core/WorldToggles.hpp"

namespace goblins {

// Свойство мира (06_GameLoop.md, п.1a) — глобальные данные, не привязанные
// ни к одному тайлу, поэтому живущие на World Entity, как и TimeComponent.
// В отличие от TimeComponent (меняется каждый тик), поля этого компонента
// выставляются один раз при генерации и System-ами далее не меняются —
// это выбор, зафиксированный на момент создания мира, а не текущее
// состояние симуляции.
//
// Здесь только то, что действительно РАЗНОЕ у разных миров и настраивается
// при генерации. Числа, одинаковые для любого мира (удержание влаги
// почвой, порог "здесь есть вода", порог переноса минералов), — не
// свойства мира, а форма самих законов: они живут константами в
// HydrologySystem.cpp рядом с местом использования.
struct WorldPropertiesComponent {
    // Глубина СТОЛБА воды источника (WaterSourceComponent). Источник не
    // подливает сколько-то за тик, а просто всегда стоит на этой глубине:
    // сколько бы из него ни вытекло, к следующему тику столб снова полон.
    // Ледяная шапка на вершине (docs/01_Cosmology.md) — бесконечный запас,
    // а не насос известной мощности, и мерить её "притоком за тик" не за
    // что: приток сам получается ровно таким, сколько уносит течение.
    //
    // Раньше это был именно приток, и его приходилось подбирать вручную
    // против испарения и стока: слишком мало — исток пересыхал, слишком
    // много — карту заливало. Со столбом подбирать нечего.
    // В тысячных единицы глубины (kDepthUnit, core/Scale.hpp).
    int waterSourceDepth = 2000;

    // Отключаемые механики мира (WorldToggles.hpp) — выбираются один раз
    // при генерации (WorldToggles внутри TerrainParams), System-ы читают
    // их отсюда каждый тик, как и остальные поля этого компонента.
    WorldToggles toggles;

    // Сколько тысячных глубины вода теряет от испарения за сто тиков.
    // Вместе с источниками и провалом за край карты (docs/01_Cosmology.md)
    // это баланс воды в мире, и держать его в константах было нельзя:
    // приток настраивается, а отток нет — значит при любом заметном
    // притоке вода неизбежно заливала карту целиком.
    //
    // За сто тиков, а не за один: испарение — самая мелкая величина в мире
    // (две десятитысячные глубины за тик), и целой она не становится ни при
    // каком сдвиге запятой, который выдержали бы остальные. Снимается она
    // разностью двух делений (HydrologySystem), поэтому ни накопителя, ни
    // дроби для этого не нужно.
    //
    // Сроком ("одна тысячная раз в N тиков") это выразить нельзя: срок не
    // описывает ничего быстрее одной тысячной за тик, а настраивать
    // испарение приходится и впятеро быстрее.
    int waterEvaporationRate = 20;

    // Дожди: раз в rainIntervalTicks тиков начинается дождь, и каждая его
    // капля приносит rainAmount глубины в одну случайную клетку. Сколько
    // тиков идёт дождь и сколько капель падает за тик — не настройка, а
    // форма закона (kRainDurationTicks/kRainDropsPerTick в
    // HydrologySystem.cpp): дождь, заливавший разом всю карту, топил
    // подчистую весь луг, поэтому редкие капли, растянутые по времени, —
    // часть самого понятия "дождь", а не выбор конкретного мира.
    //
    // Дальше эта вода живёт по общему закону: стекает по уклону в русла и
    // низины, испаряется, уходит за край. Отдельного "погодного" состояния
    // нет — момент дождя и точки падения капель разыгрываются от номера
    // тика и seed мира, поэтому погоде не нужна собственная память помимо
    // самого мира. rainIntervalTicks <= 0 — дождей в этом мире нет вовсе.
    int rainIntervalTicks = 400;
    int rainAmount = 50;

    // Эрозия: какая доля перенесённой воды превращается в вымытую породу.
    // Вымытое оседает ниже по течению, в углублениях, куда вода этим тиком
    // пришла; чему осесть негде — уходит с карты, как и вода за край:
    // Область открыта (02_CorePrinciples.md, п.12b), и точного баланса
    // почвы от неё не требуется. Скорость размыва дополнительно
    // умножается на мягкость почвы (1-rockiness)*(1-compaction): камень и
    // утрамбованный грунт вымываются заметно медленнее рыхлой земли.
    // В тысячных долях: 50 — это те же 5%, что и раньше.
    int soilErosionRate = 50;

    // Насколько геном потомка может отличаться от родительского —
    // доля вложения черты (см. core/generation/PlantGenetics.hpp), а не
    // доля самого значения гена: у всех черт вложение живёт в одном и том
    // же диапазоне [0, 1], поэтому одна настройка одинаково означает
    // "чуть-чуть" и для возраста в тиках, и для доли влаги за тик.
    // В тысячных долях вложения: 60 — это прежние 6%.
    int plantMutationRate = 60;

    // Раз во сколько тиков перегной (HumusComponent) возвращает в почву
    // одну крупицу минералов. Большое значение по умолчанию намеренно:
    // перегной — это отложенный возврат, а не мгновенный (растение копило
    // минералы сотни тиков, и вернуться они должны не за один).
    //
    // Срок, а не скорость: дробная скорость требовала поля-накопителя в
    // каждом перегное на карте, а целый срок не требует ничего.
    int humusDecayPeriod = 50;

    // Seed случайности растений. Система не имеет права хранить
    // собственный генератор между тиками (05_Entity.md, п.3), поэтому
    // PlantSystem каждый раз собирает случайность заново из этого числа,
    // номера тика и координат клетки (core/Random.hpp) — исход не зависит
    // ни от порядка обхода Entity, ни от того, сколько раз мир сохраняли
    // и загружали. Повторяемости прогонов это не обещает и не должно:
    // мир недетерминирован (02_CorePrinciples.md, п.12a).
    unsigned plantRandomSeed = 0;

    // То же самое для животных: насколько геном телёнка может отличаться
    // от родительского и из какого числа AnimalSystem собирает свою
    // случайность. Отдельные поля, а не общие с растениями: это разные
    // стадии генерации со своими настройками, и поток случайности у
    // подвижных существ раскручивается не из клетки, а из постоянного
    // идентификатора (см. IdentityComponent).
    int animalMutationRate = 60;
    unsigned animalRandomSeed = 0;

    // И то же самое для гоблинов. Отдельные поля, а не общие с животными,
    // хотя тело у них одно: скорость наследственных изменений у разумных не
    // обязана совпадать со звериной, и связывать их одним ползунком значило
    // бы решить это за мир. Своё число нужно и потоку случайности — иначе
    // гоблин и зверь с одинаковым идентификатором бросали бы один жребий.
    int goblinMutationRate = 60;
    unsigned goblinRandomSeed = 0;

    // Долголетие: во сколько раз растянуты все сроки жизни вида против
    // записанных в его геноме. В тысячных (kFull — как в геноме, 10000 —
    // вдесятеро дольше).
    //
    // Свойство МИРА, а не геном, и это не вкусовщина. Умножь сам ген — и
    // вложение черты посчитается против неумноженных границ таблицы
    // (advantageOf, core/generation/Genetics.hpp), обрежется до единицы, и
    // весь бюджет преимуществ поедет молча: все виды станут выглядеть
    // купившими максимальное долголетие. Здесь же множитель ничего не
    // ломает — геном остаётся в своих границах, а мир решает, как быстро в
    // нём течёт время для этой породы.
    //
    // По одному на КАЖДУЮ таблицу черт, а не одно на всех: у травы, дерева,
    // куста, травоядного, хищника и гоблина свои таблицы, и темп жизни у
    // них разный по самой сути — трава живёт сотни тиков, гоблин десятки
    // тысяч. Одна ручка на всех означала бы, что растянуть жизнь зверю
    // нельзя, не растянув её траве, которой он кормится.
    //
    // Поголовье от этой настройки НЕ едет: и взросление (kMaturityShare), и
    // отдых после родов (kBirthRestShare) — доли той же самой жизни, значит
    // растягиваются ровно во столько же раз. Число потомков за жизнь
    // остаётся тем же, растягивается только время.
    //
    // У растений множитель тянет за собой все три их срока — предельный
    // возраст, возраст созревания и покой семени: это все времена жизни
    // вида, и растягивать их порознь значило бы поехать долей взрослой
    // жизни.
    int grassLifespan = 10000;
    int treeLifespan = 10000;
    int bushLifespan = 10000;
    int herbivoreLifespan = 10000;
    int predatorLifespan = 10000;
    int goblinLifespan = 10000;
};

} // namespace goblins
