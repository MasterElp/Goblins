#pragma once

namespace goblins {

// Свойство мира (06_GameLoop.md, п.1a) — глобальные данные, не привязанные
// ни к одному тайлу, поэтому живущие на World Entity, как и TimeComponent.
// В отличие от TimeComponent (меняется каждый тик), поля этого компонента
// выставляются один раз при генерации и System-ами далее не меняются —
// это выбор, зафиксированный на момент создания мира, а не текущее
// состояние симуляции.
//
// Здесь только то, что действительно РАЗНОЕ у разных миров и настраивается
// при генерации. Числа, одинаковые для любого мира (испарение, добавка за
// уклон, сток за край карты, порог переноса минералов), — не свойства
// мира, а форма самих законов: они живут константами в HydrologySystem.cpp
// рядом с местом использования.
struct WorldPropertiesComponent {
    // На сколько глубина воды источника (WaterSourceComponent) растёт за
    // тик — абсолютная величина, НЕ множитель испарения (так было
    // раньше: при маленьком испарении по умолчанию даже огромный
    // множитель давал ничтожный приток — источник не мог угнаться за
    // собственным же оттоком через течение, глубина проседала почти до
    // нуля). Независима от испарения намеренно: источник должен
    // гарантированно перекрывать и своё испарение, и то, что течение
    // уносит соседям.
    float waterSourceStrength = 0.05f;

    // На сколько глубина воды убывает за тик просто от испарения. Вместе с
    // waterSourceStrength и стоком за край карты (kEdgeDrainRate в
    // HydrologySystem.cpp) это баланс воды в мире, и держать его в
    // константах было нельзя: приток настраивается, а отток нет — значит
    // при любом заметном притоке вода неизбежно заливала карту целиком.
    //
    // Порядок величины виден из равновесия: испарение снимает
    // waterEvaporationRate за тик с КАЖДОЙ водной клетки, а источники дают
    // (число истоков + родников) * waterSourceStrength на весь мир. При
    // умолчаниях (6 источников по 0.05 = 0.3 за тик) равновесие наступает
    // примерно на 1500 водных клетках плюс то, что уходит за край.
    float waterEvaporationRate = 0.0002f;

    // Дожди: раз в rainIntervalTicks тиков начинается дождь, и каждая его
    // капля приносит rainAmount глубины в одну случайную клетку. Сколько
    // тиков идёт дождь и сколько капель падает за тик — не настройка, а
    // форма закона (kRainDurationTicks/kRainDropsPerTick в
    // HydrologySystem.cpp): дождь, заливавший разом всю карту, топил
    // подчистую весь луг, поэтому редкие капли, растянутые по времени, —
    // часть самого понятия "дождь", а не выбор конкретного мира.
    //
    // Дальше эта вода живёт по общему закону: стекает по уклону в русла и
    // низины, испаряется, уходит за край. Отдельного "погодного" состояния
    // нет — момент дождя и точки падения капель разыгрываются от номера
    // тика и seed мира, поэтому погоде не нужна собственная память помимо
    // самого мира. rainIntervalTicks <= 0 — дождей в этом мире нет вовсе.
    int rainIntervalTicks = 400;
    float rainAmount = 0.05f;

    // Доля разницы уровней поверхности (высота + глубина воды), которая
    // перетекает к самому низкому соседу за тик (HydrologySystem) — чем
    // больше, тем быстрее вода растекается/заполняет впадины и тем
    // быстрее приток от источника расходится по руслу, а не скапливается
    // рядом с истоком. Это скорость на РОВНОМ месте; на склоне к ней
    // добавляется уклон (kWaterSlopeBoost в HydrologySystem.cpp).
    float waterFlowRate = 0.3f;

    // Эрозия: какая доля перенесённой воды превращается в вымытую породу.
    // Вымытое оседает ниже по течению, в углублениях, куда вода этим тиком
    // пришла; чему осесть негде — уходит с карты, как и вода за край:
    // Область открыта (02_CorePrinciples.md, п.12b), и точного баланса
    // почвы от неё не требуется. Скорость размыва дополнительно
    // умножается на мягкость почвы (1-rockiness)*(1-compaction): камень и
    // утрамбованный грунт вымываются заметно медленнее рыхлой земли.
    float soilErosionRate = 0.05f;

    // Насколько глубже соседа, с которым клетка обменивается водой, её
    // разрешено размыть. Без этого потолка клетка под постоянным
    // источником размывается каждый тик без конца: высота уезжает в
    // минус, и на карте появляется бездонная яма, никак не связанная с
    // рельефом вокруг. С ним размыв упирается в дно и останавливается,
    // а высота остаётся в разумных пределах относительно соседей.
    float maxErosionDepth = 0.5f;

    // Насколько геном потомка может отличаться от родительского —
    // доля вложения черты (см. core/generation/PlantGenetics.hpp), а не
    // доля самого значения гена: у всех черт вложение живёт в одном и том
    // же диапазоне [0, 1], поэтому одна настройка одинаково означает
    // "чуть-чуть" и для возраста в тиках, и для доли влаги за тик.
    float plantMutationRate = 0.06f;

    // Сколько крупиц минералов перегной (HumusComponent) возвращает в
    // почву за тик. Малое значение по умолчанию намеренно: перегной —
    // это отложенный возврат, а не мгновенный (растение копило минералы
    // сотни тиков, и вернуться они должны не за один).
    float humusDecayRate = 0.02f;

    // Seed случайности растений. Система не имеет права хранить
    // собственный генератор между тиками (05_Entity.md, п.3), поэтому
    // PlantSystem каждый раз собирает случайность заново из этого числа,
    // номера тика и координат клетки (core/Random.hpp) — исход не зависит
    // ни от порядка обхода Entity, ни от того, сколько раз мир сохраняли
    // и загружали. Повторяемости прогонов это не обещает и не должно:
    // мир недетерминирован (02_CorePrinciples.md, п.12a).
    unsigned plantRandomSeed = 0;
};

} // namespace goblins
