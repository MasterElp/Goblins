#pragma once

namespace goblins {

// Свойство мира (06_GameLoop.md, п.1a) — глобальные данные, не привязанные
// ни к одному тайлу, поэтому живущие на World Entity, как и TimeComponent.
// В отличие от TimeComponent (меняется каждый тик), поля этого компонента
// выставляются один раз при генерации и System-ами далее не меняются —
// это выбор, зафиксированный на момент создания мира, а не текущее
// состояние симуляции.
struct WorldPropertiesComponent {
    // Порог влажности соседнего тайла, при котором минералы начинают
    // "вымываться" в его сторону (HydrologySystem, правило песочной
    // кучи) — SoilComponent.moisture нормализована в [0, 1], поэтому
    // 0.5 здесь и есть те "50" из исходного запроса на минералы.
    float mineralMoistureThreshold = 0.5f;

    // На сколько глубина воды тайла уменьшается за тик просто от
    // испарения (HydrologySystem) — у каждого сгенерированного мира своя
    // скорость, зафиксированная при генерации, а не общая для всех миров
    // константа. Маленькое значение по умолчанию: испарение действует на
    // КАЖДУЮ водную клетку карты (их могут быть тысячи на 100x100), а
    // источников — единицы, поэтому даже небольшая скорость в сумме даёт
    // заметный отток.
    float waterEvaporationRate = 0.00004f;

    // На сколько глубина воды источника (WaterSourceComponent) растёт за
    // тик — абсолютная величина, НЕ множитель waterEvaporationRate (так
    // было раньше: при маленьком waterEvaporationRate по умолчанию даже
    // огромный множитель давал ничтожный приток — источник не мог
    // угнаться за собственным же оттоком через течение, глубина
    // проседала почти до нуля). Независима от испарения намеренно:
    // источник должен гарантированно перекрывать и своё испарение, и то,
    // что WaterFlowRate уносит соседям, при любых настройках обоих.
    float waterSourceStrength = 0.05f;

    // Доля разницы уровней поверхности (высота + глубина воды), которая
    // перетекает к самому низкому соседу за тик (HydrologySystem) — чем
    // больше, тем быстрее вода растекается/заполняет впадины и тем
    // быстрее приток от источника расходится по руслу, а не скапливается
    // рядом с истоком. Это скорость на РОВНОМ месте; на склоне к ней
    // добавляется waterSlopeBoost (ниже).
    float waterFlowRate = 0.3f;

    // Насколько круче склон — тем быстрее по нему течёт:
    // фактическая скорость = waterFlowRate + уклон * waterSlopeBoost
    // (не больше 1). Уклон здесь — падение уровня поверхности на единицу
    // расстояния до соседа. Без этого слагаемого скорость всюду
    // одинаковая, и чтобы протолкнуть постоянный приток дальше по руслу,
    // воде приходится накапливать большой стоячий перепад у истока —
    // отсюда и "конус" вокруг источника вместо реки.
    float waterSlopeBoost = 5.0f;

    // Эрозия: какая доля перенесённой воды превращается в вымытую породу.
    // Порода не исчезает — ровно столько же оседает в клетке, куда вода
    // пришла (баланс точный, почвы в мире не становится меньше, она лишь
    // переносится вниз по течению и там отстаивается). Скорость размыва
    // дополнительно умножается на мягкость почвы
    // (1-rockiness)*(1-compaction): камень и утрамбованный грунт
    // вымываются заметно медленнее рыхлой земли.
    float soilErosionRate = 0.05f;

    // Насколько глубже соседа, с которым клетка обменивается водой, её
    // разрешено размыть. Без этого потолка клетка под постоянным
    // источником размывается каждый тик без конца: высота уезжает в
    // минус, и на карте появляется бездонная яма, никак не связанная с
    // рельефом вокруг. С ним размыв упирается в дно и останавливается,
    // а высота остаётся в разумных пределах относительно соседей.
    float maxErosionDepth = 0.5f;
};

} // namespace goblins
