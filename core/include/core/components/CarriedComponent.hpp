#pragma once

#include "core/Resources.hpp"

namespace goblins {

// Что существо несёт в руках.
//
// Компонент СВОЙ, а не поле внутри GoblinComponent, и это правило, а не вкус
// (docs/10_Goblins.md, п.1a): ноша как вещь в руках — свойство всего живого,
// унести кусок может и зверь. Гоблинским её делает не сам факт переноски, а
// замысел — принести туда, где пригодится. Замысел живёт в GoblinSystem, вещь
// в руках живёт здесь, и подключить к ней зверя — это emplace и вызов закона
// (core/Carry.hpp), а не круг протокола заново.
//
// Держит он ОБЩИЙ список ресурсов (core/Resources.hpp), а не еду отдельным
// полем: всё, что носят, можно и складывать, и списку всё равно, еда это,
// солома или то, чего в мире ещё нет. Ёмкость при этом одна на все виды —
// руки одни, и набравший полные руки веток не унесёт ничего съестного. Из
// этого следует, что за материалом ходят отдельным походом, а стройка стоит
// ещё и того времени, которое не потрачено на еду.
struct CarriedComponent {
    Resources carried{};
};

} // namespace goblins
