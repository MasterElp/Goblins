#pragma once

namespace goblins {

// Что существо несёт в руках.
//
// Компонент СВОЙ, а не поле внутри GoblinComponent, и это правило, а не вкус
// (docs/10_Goblins.md, п.1a): ноша как вещь в руках — свойство всего живого,
// унести кусок может и зверь. Гоблинским её делает не сам факт переноски, а
// замысел — принести туда, где пригодится. Замысел живёт в GoblinSystem,
// вещь в руках живёт здесь, и подключить к ней зверя — это emplace и вызов
// закона (core/Carry.hpp), а не круг протокола заново.
//
// Сегодня носит только гоблин. Это отложено по замеру, а не по закону: у
// зверя нет ни памяти места, ни причины нести добычу куда-то, кроме своего
// желудка.
struct CarriedComponent {
    // Еда в руках, в шкале биомассы — той же, в которой меряются развитость
    // растения, ягода и мясо туши. Одна шкала на всё съедобное затем и
    // выбрана, чтобы куча получалась одна, а не три отдельные.
    int food = 0;

    // Крупицы минералов, уехавшие внутрь этой еды. Едут вместе с ней и
    // вместе с ней же ложатся в кучу или уходят в тело съевшего: иначе
    // вещество, вынутое из земли, пропадало бы на полпути между кустом и
    // лагерем (core/Portion.hpp).
    int minerals = 0;
};

} // namespace goblins
