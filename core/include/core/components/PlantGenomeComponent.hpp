#pragma once

namespace goblins {

// Наследуемые параметры одного растения — его геном. Только данные, без
// логики (05_Entity.md, п.2): что означает каждое поле и в каких пределах
// оно живёт, знает не компонент, а таблица черт kGrassTraits
// (core/generation/PlantGenetics.hpp) — там же лежат правила порождения
// и мутации генома.
//
// Геном принадлежит конкретному растению, а не виду: у каждого экземпляра
// свои значения, полученные от родителя с небольшой мутацией. Вид
// (species) — только индекс архетипа в PlantSpeciesComponent на World
// Entity; сам архетип задаёт центр, вокруг которого мутациям разрешено
// гулять, поэтому виды не расплываются друг в друга за сотни поколений.
//
// Значения по умолчанию — примерно "средний вид" (все черты вполовину
// вложенного бюджета). Реально используемые геномы всегда приходят из
// makeGrassSpecies/mutateGenome, здесь же значения нужны только чтобы
// компонент по умолчанию был осмысленным (как и у остальных компонентов).
struct PlantGenomeComponent {
    // Индекс вида в PlantSpeciesComponent::archetypes. Не мутирует:
    // потомок всегда того же вида, что и родитель.
    int species = 0;

    // Возраст (в тиках), с которого растение может дать потомка.
    float maturityAge = 320.0f;
    // Возраст (в тиках), в котором растение умирает от старости.
    float maxAge = 1400.0f;

    // Прирост growth за тик в идеальных условиях (growth от 0 до 1).
    float growthRate = 0.012f;

    // Влажность почвы, при которой растение растёт в полную силу. Ниже
    // неё рост падает пропорционально, при полной сухости — прекращается
    // и копится стресс. Это выбор места, а не расход: вид с малой
    // потребностью растёт и в сухом углу карты, вид с большой — только у
    // воды, зато там он быстрее.
    //
    // Ни забора влаги, ни запаса влаги в теле у растения больше нет —
    // были три черты и поле состояния там, где хватает одного порога.
    // Запас позволял пережить засуху; теперь засуху переживает не запас, а
    // сама потребность: кто просит мало, тому сухо не бывает. Разница на
    // карте та же (одни виды у воды, другие в сухом), причин вдвое меньше.
    float moistureNeed = 0.5f;

    // Сколько крупиц минералов нужно накопить, чтобы вырасти полностью:
    // растение не может быть больше, чем позволяет накопленный запас.
    // Отдельной "скорости добычи" (mineralUptake) в геноме нет: крупица
    // берётся из почвы тогда, когда рост в неё упёрся, — сколько успел
    // вырасти, столько и взял. Скорость добычи и так задана скоростью
    // роста, и вторым числом она только спорила с первым.
    float mineralNeed = 3.5f;

    // Ни "своей" каменистости, ни допуска по ней, ни терпимости к
    // утоптанности здесь больше нет. Три черты и функция пригодности
    // (habitatFit) описывали то же самое, что уже описывает влажность:
    // каменистая земля суше (kRockMoistureReduction в core/Moisture.hpp),
    // а на сухой земле растение не растёт и копит стресс. Голые горы и
    // зелёная пойма получаются от одной причины, а не от двух — и виду
    // больше не приходится покупать бюджетом право жить там, где ему и так
    // хватает воды.

    // Глубина стоящей воды, которую растение переносит. Ниже неё вода
    // росту не мешает вовсе (мокрая земля, мелкая лужа после дождя), выше
    // — растение тонет: пригодность клетки падает в ноль и копится
    // быстрый стресс затопления. Без этой черты водой считалось само
    // НАЛИЧИЕ воды на тайле, любой глубины: прошедший дождь и тонкая
    // плёнка разлива выкашивали весь луг подчистую, независимо от вида.
    float waterTolerance = 0.15f;

    // Вероятность за тик выпустить семя (у полностью выросшего растения,
    // достигшего maturityAge).
    float seedChance = 0.01f;

    // Сколько тиков семя лежит в земле, прежде чем сможет прорасти
    // (SeedComponent). Семя появляется, когда ронять потомка некуда:
    // все соседние клетки заняты или не годятся, — и тогда растение
    // оставляет семя в своей же клетке, где оно ждёт, пока место
    // освободится. Короткий покой — быстрая смена поколения на клетке,
    // длинный — семя переживает то, от чего погибло бы проросшее
    // растение (разлив, засуху), но и место занимает позже.
    float seedDormancy = 200.0f;
};

} // namespace goblins
