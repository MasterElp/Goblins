namespace goblins {

// Наследуемые параметры одного растения — его геном. Только данные, без
// логики (05_Entity.md, п.2): что означает каждое поле и в каких пределах
// оно живёт, знает не компонент, а таблица черт kGrassTraits
// (core/generation/PlantGenetics.hpp) — там же лежат правила порождения
// и мутации генома.
//
// Геном принадлежит конкретному растению, а не виду: у каждого экземпляра
// свои значения, полученные от родителя с небольшой мутацией. Вид
// (species) — только индекс архетипа в PlantSpeciesComponent на World
// Entity; сам архетип задаёт центр, вокруг которого мутациям разрешено
// гулять, поэтому виды не расплываются друг в друга за сотни поколений.
//
// Значения по умолчанию — примерно "средний вид" (все черты вполовину
// вложенного бюджета). Реально используемые геномы всегда приходят из
// makeGrassSpecies/mutateGenome, здесь же значения нужны только чтобы
// компонент по умолчанию был осмысленным (как и у остальных компонентов).
struct PlantGenomeComponent {
    // Индекс вида в PlantSpeciesComponent::archetypes. Не мутирует:
    // потомок всегда того же вида, что и родитель.
    int species = 0;

    // Возраст (в тиках), с которого растение может дать потомка.
    float maturityAge = 320.0f;
    // Возраст (в тиках), в котором растение умирает от старости.
    float maxAge = 1400.0f;

    // Прирост growth за тик в идеальных условиях (growth от 0 до 1).
    float growthRate = 0.012f;

    // Сколько влаги растение забирает из почвы за тик. Не абсолютная
    // величина, а доля от влажности клетки: из сухой почвы взять нечего
    // (SoilComponent.moisture нормализована в [0, 1]).
    float moistureUptake = 0.05f;
    // Предельный запас влаги, который растение может держать в себе, —
    // именно он позволяет пережить засуху, а не "личный источник воды".
    float moistureCapacity = 0.5f;
    // Сколько влаги уходит за тик на нормальный рост.
    float moistureNeed = 0.004f;

    // Сколько минералов растение вытягивает из почвы за тик (в крупицах
    // SoilComponent.minerals, дробно — целая крупица уходит из почвы,
    // когда накопленная доля переваливает за единицу).
    float mineralUptake = 0.04f;
    // Сколько крупиц нужно накопить, чтобы вырасти полностью: растение
    // не может быть больше, чем позволяет накопленный минеральный запас.
    float mineralNeed = 3.5f;

    // Каменистость почвы, при которой растению лучше всего, и ширина
    // допуска вокруг неё: узкий допуск — специалист под свой тип почвы,
    // широкий — универсал (за это платит бюджетом, см. PlantGenetics).
    float preferredRockiness = 0.3f;
    float rockinessTolerance = 0.5f;

    // Утоптанность почвы, которую растение ещё переносит без потери
    // роста; выше — рост падает вплоть до нуля на полностью убитой почве.
    float compactionTolerance = 0.5f;

    // Глубина стоящей воды, которую растение переносит. Ниже неё вода
    // росту не мешает вовсе (мокрая земля, мелкая лужа после дождя), выше
    // — растение тонет: пригодность клетки падает в ноль и копится
    // быстрый стресс затопления. Без этой черты водой считалось само
    // НАЛИЧИЕ воды на тайле, любой глубины: прошедший дождь и тонкая
    // плёнка разлива выкашивали весь луг подчистую, независимо от вида.
    float waterTolerance = 0.15f;

    // Вероятность за тик выпустить семя (у полностью выросшего растения,
    // достигшего maturityAge).
    float seedChance = 0.01f;
};

} // namespace goblins
