#pragma once

#include <array>
#include <cstdint>
#include <string>

#include "core/Scale.hpp"

namespace goblins {

// Нрав и склонности: чем один гоблин отличается от другого помимо тела и
// помимо того, что успел запомнить.
//
// До него два гоблина одного племени вели себя одинаково при одинаковых
// обстоятельствах: трудолюбие у всех было одним числом на весь мир
// (kHaulUrge, kBuildUrge — плоские 400), тяга к своим — одной и той же
// (kHerdPull), а друг о друге они не знали ничего. Разными их делали только
// возраст, случайные гены в полосе племени и разная память мест — то есть
// обстоятельства, а не они сами.
//
// --- Почему нрав НЕ в геноме ---
//
// Геном покупает черты общим бюджетом преимуществ: черта в нём стоит другой
// черты (core/generation/Genetics.hpp). Положи туда общительность — и она
// будет куплена за скорость или за зоркость, то есть болтливый гоблин обязан
// оказаться медленным. Это не свойство мира, а следствие того, что бюджет
// один. GoblinGenetics.hpp оговаривает то же самое со своей стороны: в геном
// идёт только телесное преимущество, а всё, чем гоблин берёт своё, приходит
// не рождением.
//
// Поэтому нрав наследуется своим законом (core/generation/GoblinCharacters.hpp):
// племя задаёт средний нрав, особь отклоняется в полосе, ребёнок берёт
// среднее родителей плюс дрейф. Бюджета здесь нет вовсе — нрав не делает
// гоблина лучше, он делает его другим.
//
// --- Почему компонент, а не поле в теге ---
//
// docs/10_Goblins.md, п.1a: состояние — свой компонент, и никогда не поле
// внутри тега вида. Свойство это гоблинское (общество и труд), но форма у
// него общая: закон живёт в core/Character.hpp на простых числах и ничего не
// знает ни про гоблина, ни про зверя. Дать нрав животному — это emplace и
// больше ничего.
//
// --- За жизнь не меняется ---
//
// Нрав — не умение: он не растёт от применения. То, что растёт, будет
// умением и придёт своим шагом. Отсюда следствие для провода: неизменное
// незачем возить дельтой, а рисовать нрав у каждого гоблина на карте нечем,
// поэтому он не едет и в карточке — только наблюдаемому, тем же путём, что и
// память мест (watched["knows"], server/NetworkServer.cpp).

// О чём гоблин думает и о чём заговорит.
//
// Список ОДИН, хотя спрашивали о трёх разных интересах — к местам, к
// занятиям и к темам вообще. Три списка означали бы, что "интерес к работе"
// и трудолюбие — два числа про одно и то же, и подкручивать их пришлось бы
// парой, гадая, какое из двух сейчас мешает.
//
// Четыре первых имеют место на карте (placeOf, core/Character.hpp) и потому
// несут ЗНАНИЕ: разговор о них кладёт слушателю слух о месте. Два последних
// места не имеют и несут только то, что несёт всякий разговор, — тепло.
enum class Topic : std::uint8_t {
    // Где еда. Самая ходовая тема поселения и единственная, ради которой
    // стоит идти через полкарты.
    Food = 0,
    Water = 1,
    // Где спать. Дом — тоже место, и рассказ о нём собирает лагерь вернее
    // всего остального: услышавший придёт ночевать туда же.
    Home = 2,
    // Что строить. Тема того, чего ещё нет, — единственная, которая зовёт не
    // к готовому, а к начатому.
    Work = 3,
    // Кто есть кто. Места нет, зато есть третий: слушатель теплеет к тому, о
    // ком ему хорошо отозвались. Так тепло идёт дальше пары говорящих, и у
    // общительного заводится вес, которого он сам никому не показывал.
    Kin = 4,
    // Ни о чём. Не пустое значение и не "нет данных": это то, о чём говорят
    // двое, которым нечего сказать друг другу, — а таковы все первые
    // разговоры. Без этой темы чужие не могли бы заговорить вовсе, и
    // знакомство начиналось бы с середины.
    Idle = 5,
};

inline constexpr int kTopicCount = 6;

// Имя темы — не логика, а имя значения (см. placeKindName, resourceName): им
// пользуются файл мира и панель наблюдения, и лежит оно рядом с самим
// перечислением, чтобы не разъехаться. Склонности пишутся в файл мира по
// этим именам, а не по порядку в массиве, — новая тема доедет сама, а
// вставленная в середину не перепутает старые.
inline const char* topicName(Topic topic) {
    switch (topic) {
        case Topic::Food: return "food";
        case Topic::Water: return "water";
        case Topic::Home: return "home";
        case Topic::Work: return "work";
        case Topic::Kin: return "kin";
        case Topic::Idle: break;
    }
    return "idle";
}

inline Topic topicFromName(const std::string& name) {
    if (name == "food") return Topic::Food;
    if (name == "water") return Topic::Water;
    if (name == "home") return Topic::Home;
    if (name == "work") return Topic::Work;
    if (name == "kin") return Topic::Kin;
    return Topic::Idle;
}

// Нрав. Четыре числа, и каждое отвечает на свой вопрос — пятого нет, пока
// нельзя назвать, что сломается без него.
//
// Все четыре в 0..kFull (core/Scale.hpp), и середина шкалы — обычный
// гоблин, а не ноль: ноль здесь означает край нрава, а не его отсутствие.
struct CharacterComponent {
    // Общительность: как часто он заговаривает первым. Скорость, с которой
    // копится желание говорить (GoblinDesireComponent::talking).
    int sociable = kFull / 2;

    // Постоянство: с одними и теми же или со всеми подряд. Вес тепла против
    // веса новизны при выборе собеседника (core/Talk.hpp).
    //
    // Отдельное число, а не следствие общительности, и это принципиально:
    // "часто" и "с кем" — разные вопросы, и болтливый однолюб ничем не хуже
    // молчуна, здоровающегося со всеми. Выведи второе из первого — и одна
    // ручка крутила бы оба, а подобрать их порознь стало бы нельзя.
    int loyal = kFull / 2;

    // Трудолюбие: браться ли за дело вообще. Сдвигает позывы отнести и
    // построить, до сих пор одинаковые у всех.
    //
    // Это УРОВЕНЬ, а склонность (interest) — НАПРАВЛЕНИЕ: трудолюбие решает,
    // работать или бездельничать, склонность — собирать или строить при
    // равном трудолюбии. Размах у них разный и намеренно (kDiligenceSwing
    // вдвое больше kInterestSwing): иначе увлечённый лентяй работал бы
    // столько же, сколько равнодушный трудяга, и одно из двух чисел было бы
    // лишним.
    int diligent = kFull / 2;

    // Харизма: сколько тепла остаётся у ДРУГОГО после разговора с ним.
    //
    // Единственное число нрава, которое читается не у своего хозяина, а у
    // собеседника, и в этом весь его смысл: обаяние — не то, что человек
    // чувствует, а то, что он оставляет. Оно же — будущая цена просьбы:
    // послушаются того, к кому тепло, а тепло копится быстрее к обаятельному.
    int charming = kFull / 2;

    // Склонность к каждой теме, 0..kFull. Решает две вещи сразу: о чём он
    // заговорит (тема тем вероятнее, чем сильнее склонность) и что удержит из
    // услышанного (слух приживается по склонности слушателя).
    //
    // Массив, а не одна "любимая тема": одна тема означала бы, что гоблин,
    // которому интересна еда, к воде равнодушен ровно так же, как к стройке,
    // — а разница между "всё равно" и "не интересно вовсе" здесь и есть то,
    // из чего складывается несхожесть.
    //
    // Умолчание — середина по каждой теме, а не ноль, и это важно за
    // пределами вкуса: ноль означает "не интересно вовсе" (услышанного не
    // удержит, сам об этом не заговорит). Гоблин, которому нрава не досталось
    // — из файла мира, записанного до нрава, или по чьему-то недосмотру, —
    // обязан выйти обычным, а не глухим ко всему на свете.
    std::array<int, kTopicCount> interest{kFull / 2, kFull / 2, kFull / 2,
                                          kFull / 2, kFull / 2, kFull / 2};
};

} // namespace goblins
