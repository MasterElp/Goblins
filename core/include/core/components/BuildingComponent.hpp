#pragma once

namespace goblins {

// Что построено на этой клетке.
//
// Состояние ЗЕМЛИ, как куча и перегной: компонент ложится на терраформирующий
// Entity тайла. Постройка — свойство МЕСТА, а не имущество: кто дошёл, тот и
// пользуется. Понятия собственности в этом мире нет ни в одном законе, и
// заводить его ради навеса не стоит.
//
// Значение каждого поля — ПРОЧНОСТЬ, 0..kFull. Ноль означает, что постройки
// нет.
//
// Никакого "готово / не готово" в мире не заводится, и это главное решение
// всего шага: навес прочностью в половину — это половина навеса, он укрывает
// вполовину и бережёт вполовину. Отсюда сразу три следствия, которых иначе
// пришлось бы добиваться отдельно:
//
//   1. недостроенное не требует особого состояния — оно просто слабое;
//   2. брошенная на середине стройка не создаёт вопроса "что с ней делать";
//   3. ПОДНОВЛЕНИЕ — ТО ЖЕ ДЕЙСТВИЕ, ЧТО СТРОЙКА. Работа поднимает прочность,
//      время опускает, и разницы между "строю" и "чиню" в законе нет.
//
// Навес и подстилка стоят на одной клетке и не мешают друг другу: клетка, где
// есть оба да ещё и куча, — лучшее место мира и сердце лагеря.
struct BuildingComponent {
    // Навес: крыша над головой. Лучше кроны дерева (core/Rest.hpp), но крыша
    // ОДНА — с кроной он не складывается, берётся лучшее. Оттого под деревом
    // строить его почти незачем.
    //
    // Он же и склад: под навесом еда в куче портится вдвое медленнее
    // (core/Store.hpp). Отдельной постройки для склада не заводится — он
    // получается сам, стоит поставить навес над кучей.
    int canopy = 0;

    // Подстилка: то, на чём лежат. Умеет то, чего не умеет крона, — гасит
    // камень и сырость под боком, — и тоже бережёт запас.
    int bedding = 0;
};

} // namespace goblins
