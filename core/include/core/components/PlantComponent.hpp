#pragma once

namespace goblins {

// Текущее состояние живого растения — то, что меняется каждый тик, в
// отличие от PlantGenomeComponent (наследуемые параметры, за жизнь не
// меняются). Наличие этого компонента и означает "Entity — живое
// растение": умершее растение теряет его вместе с геномом
// (02_CorePrinciples.md, п.3).
//
// Растение занимает одну клетку и стоит на ней — координаты хранит
// PositionComponent, как у любого другого Entity на карте; собственных
// координат здесь нет.
struct PlantComponent {
    // Прожитые тики. Сравнивается с maturityAge/maxAge генома.
    int age = 0;

    // Развитость, 0..kFull: 0 — только проросшее семя, kFull — взрослое.
    // Сверху её больше ничто не ограничивает, кроме самого kFull: минералы
    // растение набирает по мере роста, а не растёт по мере минералов
    // (kPlantMinerals в PlantGenetics.hpp).
    int growth = 0;

    // Неделящийся остаток скорости роста, 0..kFull-1. Скорость роста —
    // это growthRate генома, умноженный на обеспеченность влагой
    // (0..kFull), то есть величина, которая меняется каждый тик и из
    // возраста не выводится; ни срок, ни разность делений её не выражают.
    // Остаток целый, а не дробный: это единственное место у растения, где
    // без него не обойтись.
    int growthProgress = 0;

    // Запаса влаги в теле у растения нет. Он был, и был он третьим числом
    // про одну и ту же воду (забор, ёмкость, расход) — при том, что
    // влажность клетки и так лежит рядом, в SoilComponent. Растение пьёт
    // из клетки прямо сейчас; засуху переживает не тот, кто накопил, а
    // тот, кому нужно меньше (PlantGenomeComponent::moistureNeed).

    // Целые крупицы минералов, вынутые из SoilComponent.minerals своей
    // клетки. Целое число, потому что и в почве минералы — счётное
    // количество: сколько ушло из клетки, столько и лежит в растении, и
    // ровно столько же вернётся перегноем после смерти (часть — раньше и
    // в травоядное, если растение съедят). Набираются по мере роста: у
    // проростка крупиц нет, у взрослого их kPlantMinerals. Пустая клетка
    // росту не мешает — растение просто останется без крупиц, и вернуть
    // ему будет нечего.
    int minerals = 0;

    // Сколько растение стоит под водой, 0..kFull: клетка залита глубже,
    // чем переносит геном (waterTolerance), — счёт идёт, вода ушла — счёт
    // обнуляется. При kFull растение погибает, и это единственная его
    // смерть, кроме старости (age >= maxAge) и чужих зубов.
    //
    // Считалось здесь и неблагополучие от сухости — и это было лишним:
    // семя не ложится в клетку суше половины своей потребности (ни при
    // расселении, ни при размножении), так что копиться сухому стрессу
    // было в общем-то негде, зато любая просадка влажности выкашивала луг
    // целиком. Сухая клетка теперь просто останавливает рост.
    //
    // Имя поля осталось прежним: под ним состояние растения лежит в
    // сохранении мира и уходит клиенту.
    int stress = 0;
};

} // namespace goblins
