#pragma once

namespace goblins {

// Текущее состояние живого растения — то, что меняется каждый тик, в
// отличие от PlantGenomeComponent (наследуемые параметры, за жизнь не
// меняются). Наличие этого компонента и означает "Entity — живое
// растение": умершее растение теряет его вместе с геномом
// (02_CorePrinciples.md, п.3).
//
// Растение занимает одну клетку и стоит на ней — координаты хранит
// PositionComponent, как у любого другого Entity на карте; собственных
// координат здесь нет.
struct PlantComponent {
    // Прожитые тики. Сравнивается с maturityAge/maxAge генома.
    float age = 0.0f;

    // Развитость, 0..1: 0 — только проросшее семя, 1 — взрослое растение.
    // Ограничена сверху накопленными минералами (minerals / mineralNeed):
    // без минералов растение физически не может стать больше.
    float growth = 0.0f;

    // Накопленная влага (в тех же единицах, что moistureNeed за тик).
    // Наполняется ТОЛЬКО из влажности своей клетки и тратится на рост —
    // это запас на чёрный день, а не независимый источник воды.
    float moisture = 0.0f;

    // Целые крупицы минералов, вынутые из SoilComponent.minerals своей
    // клетки. Целое число, потому что и в почве минералы — счётное
    // количество: сколько ушло из клетки, столько и лежит в растении, и
    // ровно столько же вернётся перегноем после смерти.
    int minerals = 0;
    // Накопленная доля до следующей целой крупицы (0..1). Нужна потому,
    // что mineralUptake за тик — дробная величина, а минералы в почве
    // целые: доля копится здесь и превращается в крупицу, когда
    // переваливает за единицу.
    float mineralPending = 0.0f;

    // Накопленное неблагополучие, 0..1. Растёт, когда условия не дают
    // расти (нет влаги, чужая почва, клетку залило), и медленно спадает,
    // когда всё в порядке. При 1 растение погибает — это смерть от
    // условий, в отличие от смерти от старости (age >= maxAge).
    float stress = 0.0f;
};

} // namespace goblins
