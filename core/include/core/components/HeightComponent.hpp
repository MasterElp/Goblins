namespace goblins {

// Высота рельефа тайла — базовое свойство, как SoilComponent: есть у каждого
// террейн-Entity безусловно, а не только там, где вода. Персистентный аналог
// временного массива elevation из TerrainGenerator.cpp — нужен, чтобы у воды
// (HydrologySystem) было объективное "куда течь под гору", а не случайное
// блуждание (02_CorePrinciples.md, п.15: система вычисляет следующее
// состояние, а не имитирует желаемый результат).
struct HeightComponent {
    // В тысячных прежней единицы (kDepthUnit, core/Scale.hpp): гора
    // высотой 16 — это 16000.
    int height = 0;
};

// Высота края мира. Область висит островом в пустоте
// (docs/01_Cosmology.md): тайлы самой границы — обрыв, у них нулевая
// высота и никогда не бывает воды. Отсюда же считается уровень устья рек
// при генерации: русло спускается от истока в горах ровно до этой отметки, чтобы
// у самого края не образовалось ступеньки, за которой вода копится вместо
// того, чтобы падать вниз.
//
// Значение общее для генерации (TerrainGenerator.cpp) и симуляции
// (HydrologySystem.cpp), поэтому живёт рядом с самим понятием высоты, а не
// продублировано в обеих.
inline constexpr int kVoidHeight = 0;

} // namespace goblins
