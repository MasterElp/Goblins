#pragma once

#include <cstdint>

namespace goblins {

// Постоянный идентификатор существа — то, чем оно остаётся собой между
// тиками и между запусками мира.
//
// Идентификаторы EnTT для этого не годятся: при загрузке мира они выдаются
// заново (server/WorldSave.cpp пишет анонимные записи), поэтому всё, что
// хочет ссылаться на конкретное существо дольше одного сеанса, обязано
// иметь собственный ключ.
//
// Растениям такой ключ не нужен: растение неподвижно, и его "именем" в
// мире служит клетка — отсюда и ключ случайности PlantSystem
// ("seed мира + номер тика + координаты клетки"). С подвижным существом
// это перестаёт работать сразу по двум причинам: клетка у него меняется
// каждый шаг, а на одной клетке может стоять несколько существ — розыгрыш
// "куда пойти" получился бы у них одинаковым. Поэтому у животного ключ
// случайности — "seed мира + номер тика + этот id".
//
// Число случайное, а не порядковое: счётчик "следующего id" пришлось бы
// хранить свойством мира и держать в согласии с содержимым мира при каждом
// сохранении, загрузке и рождении, а взамен он не даёт ничего, чего не
// даёт случайное 64-битное число (совпадение двух — событие, которого не
// случится за всё время жизни мира). Порядок появления существ на свет
// идентификатор не кодирует и кодировать не должен: возраст — это
// возраст, он лежит в компоненте существа.
struct IdentityComponent {
    std::uint64_t id = 0;
};

} // namespace goblins
