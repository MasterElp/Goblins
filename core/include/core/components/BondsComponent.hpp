#pragma once

#include <array>
#include <cstdint>

namespace goblins {

// Кого гоблин знает — и второе, чего у животного нет вовсе. Зверь различает
// своих и чужих породой (WalkHerd тянет к ближайшему сородичу, кто бы он ни
// был); гоблин различает их поимённо.
//
// Устроено это построчно так же, как память мест (KnowledgeComponent), и не
// по лени, а потому, что задача та же: держать в конечной голове то, что
// пригождается, и терять то, что перестало. Тепло копится от встреч, тает
// само и вытесняет слабейшее, когда голова полна, — все три правила уже
// написаны для мест (core/Knowledge.hpp), и второй закон о том же разъехался
// бы с первым молча (CLAUDE.md).
//
// Помнится ИДЕНТИФИКАТОР, а не Entity: entt::entity переиспользуется после
// смерти, и знакомый превратился бы в незнакомца, случайно занявшего его
// место в реестре. Идентификатор же уникален и переживает сохранение
// (IdentityComponent).
//
// Мёртвых из головы никто не вычёркивает, и это намеренно: специальный обход
// "убрать умерших" означал бы, что гоблин знает о смерти всякого, кого
// помнил, где бы тот ни умер. Забудется он сам, остыв, — как забывается и
// место, к которому перестали ходить.

// Один знакомый: кто и насколько свой.
struct Acquaintance {
    std::uint64_t id = 0;
    // 0..kFull. Растёт от разговоров (тем быстрее, чем обаятельнее
    // собеседник), убывает само со временем. На этой одной шкале стоят все
    // пороги знакомства: с какого тепла рассказывают, где еда, и с какого
    // делятся ношей (core/Bonds.hpp).
    int warmth = 0;
};

// Скольких гоблин помнит. Столько же, сколько мест, и по той же причине:
// голова не растёт.
//
// Число не случайное и не "с запасом". Восемь — это чуть больше, чем
// умещается в одном лагере, и заметно меньше племени: значит, гоблин
// вынужден выбирать, кого держать в голове, и круг у каждого получается
// СВОЙ. Помни он всех, племя было бы одной ровной компанией, где никто ни к
// кому не ближе прочих, — и никакие связи в мире не были бы видны.
inline constexpr int kKnownFaces = 8;

struct BondsComponent {
    std::array<Acquaintance, kKnownFaces> faces{};
};

} // namespace goblins
