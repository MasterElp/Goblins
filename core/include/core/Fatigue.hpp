#pragma once

#include <algorithm>

#include "core/Scale.hpp"

namespace goblins {

// Как силы убывают от жизни и ходьбы и как возвращаются от лежания — ОДИН
// закон на всех, кто ходит. Живёт здесь, а не внутри системы, по той же
// причине, что и core/Trample.hpp: вызывающих у него больше одного
// (AnimalSystem и GoblinSystem), а две копии одного закона расходятся молча
// (CLAUDE.md).
//
// Про существ он не знает ничего и принимает одно число — накопленную
// усталость (FatigueComponent). Само состояние живёт компонентом, и это
// разделение здесь важнее обычного: усталость успела побывать полем внутри
// тега гоблинов, и переезд её оттуда стоил полного круга.

// Сколько усталости прибывает за тик просто оттого, что существо живо, и
// сколько сверх того стоит сделанный шаг.
//
// Целыми числами за тик, без накопителя (core/Scale.hpp). Ходьба дороже
// стояния втрое — иначе усталость была бы просто вторым возрастом и не
// значила бы ничего: она должна отличать того, кто обошёл полкарты, от
// того, кто простоял у куста.
//
// Размером тела не делится, в отличие от расхода энергии: маленький устаёт
// не меньше взрослого, а скорее больше. Делать из этого черту генома было
// бы преждевременно — сперва надо увидеть, что усталость вообще делает с
// поведением.
constexpr int kFatigueTick = 1;
constexpr int kFatigueStep = 3;

// Сколько усталости уходит за тик отдыха. Заметно больше, чем прибывает:
// отдых должен занимать меньшую часть жизни, чем дорога, иначе мир будет
// состоять из лежащих.
//
// Прибывает при этом и во время отдыха (kFatigueTick вычитается из этого
// числа, а не отменяется): отдыхающий отдыхает, но не перестаёт жить.
constexpr int kRestRelief = 8;

// Устать: от того, что живёшь (kFatigueTick), и от того, что шагнул
// (kFatigueStep). Потолок kFull — усталость не растёт без конца, как и
// всякая величина состояния мира.
inline void tireBy(int& fatigue, int amount) {
    fatigue = std::min(kFull, fatigue + amount);
}

// Отдохнуть. Дно — ноль: отдых не уводит силы в запас, которого нет.
//
// Чем именно отдых заслужен, закон не спрашивает, и это не упущение, а
// разделение: ГДЕ можно лечь — вопрос места (core/Rest.hpp), и отвечают на
// него по-разному. Гоблин ищет годную клетку и ложится только на неё, звери
// ложатся там, где стоят: искать место незачем тому, у кого нет памяти
// мест, — он и вернуться-то к нему не сможет.
inline void restBy(int& fatigue, int amount) {
    fatigue = std::max(0, fatigue - amount);
}

} // namespace goblins
