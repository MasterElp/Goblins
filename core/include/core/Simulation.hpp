#pragma once

#include "core/GameLoop.hpp"
#include "core/World.hpp"
#include "core/generation/PlantParams.hpp"
#include "core/generation/TerrainGenerator.hpp"

namespace goblins {

// Состав мира: из каких этапов он рождается и какие законы действуют на
// нём каждый тик.
//
// И то, и другое — свойства самого мира, а не того, кто его запустил:
// последовательность этапов генерации задана 02_CorePrinciples.md, п.5, а
// фиксированный порядок систем — 06_GameLoop.md, п.3. Раньше и список
// систем, и конвейер генерации собирались в server/main.cpp, то есть в
// транспортном слое: второй хост (headless-утилита, будущий веб-сервер)
// мог собрать другой мир, ничего формально не нарушив. Здесь они одни на
// всех, а server лишь вызывает.
//
// core по-прежнему ничего не знает о JSON и конфигурации (07_TechStack.md,
// п.6): WorldGenParams — plain-структура, заполняет её вызывающая сторона.

struct WorldGenParams {
    // Один seed на весь мир. Стадии расходятся от него смещениями (см.
    // generateWorld) — иначе булыжники и трава получали бы буквально одно
    // и то же число, и миры с близкими seed'ами выглядели бы похоже
    // расставленными. Ни одно из смещений ничего не значит, кроме "не
    // совпадать".
    unsigned seed = 54321;

    TerrainParams terrain{};
    int boulderCount = 40;
    PlantParams plants{};
};

// Рождение мира: полный сброс (пустой registry, свежая Область заданного
// размера, нулевой тик), затем этапы по 02_CorePrinciples.md, п.5 —
// карта, природные ресурсы, заселение растительностью. Порядок этапов не
// произволен: трава должна увидеть уже готовые водоёмы и уже расставленные
// непроходимые объекты.
//
// Возвращает статистику стадии террейна — вызывающая сторона (server)
// печатает её в консоль; core сам не делает I/O.
GenerationStats generateWorld(World& world, int width, int height, const WorldGenParams& params);

// Законы, действующие каждый тик, в том порядке, в котором они
// выполняются: время, затем вода и почва, затем растения. Порядок
// содержательный, а не произвольный — растение должно видеть почву уже в
// том состоянии, в которое её привела вода на этом тике.
void addDefaultSystems(GameLoop& loop);

} // namespace goblins
