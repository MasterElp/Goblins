#pragma once

namespace goblins {

// Докуда добирается тот, кто ходит, — ОДИН закон на всех. Про существ не
// знает ничего и принимает числа: отметку рельефа и то, чем по нему лезут.
//
// Зачем это миру. До сих пор преград было две — вода и валун, — и обе
// одинаковы для всех: их не берёт никто. Высота — первая преграда, которая
// РАЗЛИЧАЕТ идущих, и из этого различия берётся то, чего у поселения не было
// ни одного: место, куда зубы не дойдут.
//
// --- Почему отметка, а не уступ ---
//
// Первым здесь стоял закон подъёма: перебраться с клетки на клетку можно,
// если перепад между ними не больше твоих сил. Он был отвергнут ЗАМЕРОМ, и
// стоит записать почему.
//
// На плавном рельефе уступов нет вовсе: карта 200x130, порог подъёма 300
// тысячных — зверю доступно 98.7–99.8% суши, и вчетверо больший порог не
// отрезает ничего. Высота меняется на протяжении многих клеток, и любой
// перепад берётся мелкими шагами; закон подъёма по такому рельефу — число,
// которого никто не читает.
//
// Уступы можно было бы НАРЕЗАТЬ, превратив горы в лестницу из полок, — и это
// работало: убежищем становилась треть суши. Но платой была цена, которой
// никто не просил: полки запирали зверьё каждое на своей, и мир рассыпался
// на изолированные загоны. Высота такой платы не берёт. Ниже потолка лежит
// одна связная низина, и зверь ходит по ней весь, как ходил.
//
// --- Что значит "выше" ---
//
// Высокогорье — голый камень и осыпь. Идти по нему можно, но не всякому:
// зверю четыре ноги там не опора. Это не отдельное свойство клетки, а та же
// самая высота, которой в этом мире уже сложена каменистость почвы
// (mountainHardness: чем выше рельеф, тем твёрже земля).

// Докуда добирается НОГА. Всякий, кто ходит на четырёх.
//
// Отметка абсолютная, в тех же тысячных, что и HeightComponent, и выбрана
// замером по готовым мирам. Решающее требование к ней ровно одно: НИЖЕ
// ПОТОЛКА ЗЕМЛЯ ОБЯЗАНА ОСТАВАТЬСЯ ОДНИМ КУСКОМ. Потолок, разрезающий низину
// надвое, запирает зверьё в долинах — а тогда убежище гоблину куплено ценой
// загонов для всех остальных, и это плохая цена.
//
// Замер по трём мирам (доля суши ниже потолка / какая её часть — один связный
// кусок):
//
//   4000: 52% / 65%   — рассыпается, зверьё заперто
//   6000: 75% / 100%
//   8000: 87% / 99.9%
//
// Ниже шести тысяч связность ломается, поэтому взято заметно выше.
//
// Доля суши, достающаяся гоблину одному, при этом СИЛЬНО РАЗНАЯ от мира к
// миру: при восьми тысячах те же три мира дают 6%, 13% и 56%. Это не изъян
// закона, а свойство самих миров — у одного медиана высоты 3840, у другого
// 8440, то есть один холмистый, а другой горный. Отметка снежной линии в
// природе тоже одна на все горы, а не доля от каждой.
constexpr int kLegCeiling = 8000;

// Докуда добирается РУКА. Выше — потому что это уже не ходьба, а лазание:
// подтянуться, встать на выступ, перевалиться.
//
// Не бесконечность, и намеренно: у горного мира остаются макушки, где не
// бывает никого. В холмистом мире их не оказывается вовсе, и это тоже верно —
// там просто нет таких высот. Замер по трём мирам дал вершины 11290, 16740 и
// 21430: под этот потолок первые два проходят целиком, третий — нет.
constexpr int kHandCeiling = 20000;

// Во что обходится влезть на то, что СТОИТ на клетке, а не на саму клетку:
// на валун, на дерево. Одно число на оба, и это не лень: с точки зрения
// лезущего валун и ствол — одно и то же, вещь в рост, через которую надо
// перевалиться. Разными их делает не высота, а то, что бывает наверху.
//
// Числом оно не сравнивается ни с каким потолком: валун стоит и в низине, и
// на склоне, и "влезть на него" не зависит от того, где он лежит. Отсюда и
// отдельный признак у лезущего (Climber::hands), а не общая отметка: свяжи
// их — и валун на равнине оказался бы зверю по силам, потому что равнина
// низкая.
constexpr int kScrambleRise = 3000;

// Чем существо берёт высоту. Два числа, а не одно, потому что вопросов два и
// они независимы: докуда добирается по земле и влезает ли на то, что на ней
// стоит.
//
// Про виды здесь не сказано ничего: закон принимает Climber, а кто на ногах,
// а кто на руках — решает вызывающая система, одной строкой на вид.
struct Climber {
    int ceiling = 0;
    bool hands = false;
};

inline constexpr Climber kOnLegs{kLegCeiling, false};
inline constexpr Climber kOnHands{kHandCeiling, true};

// Достанут ли зубы того, кто стоит на этой клетке.
//
// Дерево — единственное место в мире, где "на клетке" значит две разные
// высоты: под кроной и в кроне. Умеющий лазить оказывается в кроне, и зверь
// стоит под ним — на той же клетке и всё равно не дотягиваясь.
//
// Это НЕ отменяет прежнего смысла рощи для зверья (kCoverSight,
// core/Hunting.hpp): травоядное по-прежнему прячется ПОД кроной, и прячется
// хуже — его там можно найти, наткнувшись. Два разных укрытия на одном
// дереве, и различает их не место, а то, чем существо за это дерево берётся.
inline bool outOfReachUpATree(bool tree, const Climber& who) {
    return tree && who.hands;
}

// Достанут ли зубы того, кто стоит на этой клетке, — ВЕСЬ ответ, а не одна
// его половина.
//
// Половин две, и различает их то же самое, что и всё здесь, — чем существо
// берёт высоту:
//   - крона: преследователь стоит на той же клетке, внизу, и не дотягивается
//     (outOfReachUpATree выше);
//   - высота, валун, забор: преследователю не встать на саму клетку. Но
//     встать ему надо не на неё, а РЯДОМ — удар дотягивается на клетку
//     (kStrikeReach, core/Strike.hpp), — и вопрос, значит, не в том, куда
//     нельзя, а в том, есть ли поблизости хоть одна клетка, куда можно.
//
// Записано после прямой ошибки, и она стоит того, чтобы остаться в памяти.
// Гоблин считал себя спасённым везде, где зверю не встать: на валуне, выше
// потолка ноги, за плетнём. Сочтя себя спасённым, он ЗАМИРАЛ — и замирал на
// кромке полки, в одном шаге от зубов. Замер: пока хищник стоял вплотную,
// испуганный гоблин на высокогорье не делал шага НИ РАЗУ за 2373 тика, а на
// голой земле уходил в 47.8% случаев. Со стороны это и выглядело так, будто
// гоблины хищника не боятся вовсе: боялись, бросали еду, называли страх — и
// стояли.
//
// Ошибка была ровно того рода, о котором говорит core/Fear.hpp: на один
// вопрос в мире было два ответа. Хищник, выбирая добычу, спрашивал про
// крону; гоблин, выбирая, бежать ли, спрашивал про свою клетку. Второй
// ответ был короче и неверен, и увидеть это было нечем — гоблин не умирал,
// он просто стоял.
//
// footing — есть ли в досягаемости удара хоть одна клетка, на которую
// преследователь может встать (footingToStrike, core/Strike.hpp). Считает
// вызывающая сторона: про Область Climb.hpp не знает ничего, а радиус удара
// — дело закона удара, а не закона лазания.
inline bool outOfReach(bool tree, const Climber& who, bool footing) {
    return outOfReachUpATree(tree, who) || !footing;
}

// Насколько высоко окажется тот, кто заберётся на эту клетку. Нужно не для
// прохода, а для ВЫБОРА: испуганный лезет как можно выше, и валун с деревом
// для него выше голой земли под ними.
inline int climbedHeightOf(int height, bool blocked, bool tree) {
    return height + (blocked || tree ? kScrambleRise : 0);
}

} // namespace goblins
