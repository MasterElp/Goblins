#pragma once

namespace goblins {

// Единицы, в которых измеряется состояние мира.
//
// В мире нет дробных величин. Не из вкуса к целым числам, а потому, что
// дробь в состоянии мира всегда тянет за собой второе поле — накопитель, в
// котором дробь дожидается, пока накопится до целого. Так в мире завелись
// mineralPending, proteinPending, dungPending, humus.pending: пять полей,
// не означавших ничего, кроме "0.004 за тик не помещается в штуку".
// Целая шкала убирает и дробь, и накопитель разом.
//
// Шкал ровно три, и все три — про одно и то же: сдвинуть запятую так,
// чтобы самая мелкая величина, которая в мире что-то значит, стала
// единицей.
//
// 1. Доли (всё, что раньше жило в [0, 1]) — в тысячных, kFull = 1000.
//    Развитость растения, здоровье, стресс, влажность, каменистость,
//    желания. Тысячная доля — предел того, что вообще различимо: на карте
//    в 512 тайлов её не видно, а в панели наблюдения она печатается как
//    третий знак после запятой, которого там и раньше не было.
//
// 2. Счётчики тела (энергия, вода, биомасса, мясо) — тоже в тысячных от
//    прежних единиц. Шкала выбрана не сама по себе, а из первого правила:
//    "сколько энергии в единице биомассы" должно быть целым, а биомасса
//    меряется той же тысячной шкалой, что и развитость растения.
//
// 3. Высота рельефа и глубина воды — в тысячных прежних единиц
//    (kDepthUnit). Река глубиной 0.9 стала рекой глубиной 900, гора
//    высотой 16 — горой высотой 16000.
//
// Времена (тики), расстояния (тайлы) и счётные вещи (крупицы минералов,
// крупицы белка) шкалы не имеют и не имели — они и так целые.
//
// --- Скорости ---
//
// Скорость в этом мире — это "сколько единиц за тик", и на целой шкале она
// почти всегда получается целой сама (0.012 развитости за тик — это 12
// тысячных за тик). Там, где не получается, есть два приёма, и оба
// обходятся без дробей:
//
//   - СРОК вместо скорости: "одна крупица раз в N тиков" (kDungPeriod,
//     humusDecayPeriod). Ничего копить не нужно вовсе — событие происходит
//     по остатку от деления номера тика. Годится там, где скорость заведомо
//     ниже единицы за тик: срок не выражает ничего быстрее.
//   - РАЗНОСТЬ ДВУХ ДЕЛЕНИЙ: величина, зависящая только от номера тика или
//     от возраста (взросление животного, испарение воды), считается как
//     разница между значением на этом тике и на прошлом. Тоже без
//     состояния, и, в отличие от срока, выражает любую скорость.
//
// Накопитель остаётся ровно там, где скорость модулируется чем-то
// переменным и от возраста не выводится: рост растения (скорость * влага)
// и шаг животного (дробная скорость в целых клетках). Оба — целые остатки,
// а не дроби.

// Полная доля: 1000 тысячных. Всё, что раньше было "0..1", теперь
// "0..kFull".
inline constexpr int kFull = 1000;

// --- Темп жизни ---
//
// Насколько медленнее идёт жизнь породы против того, что записано в её
// геноме: kFull — как записано, 10000 — вдесятеро дольше. Величина живёт в
// свойствах мира (WorldPropertiesComponent), по одной на каждую таблицу
// черт, а сюда вынесены два приёма, которыми она применяется.
//
// Замедлить всё разом — это НЕ смена баланса. Раздели каждую скорость и
// умножь каждый срок на одно и то же число, и все отношения мира останутся
// прежними: те же исходы, растянутые во времени. Балансом становится только
// то, что забыли разделить.
//
// Приёмов ровно два, и выбор между ними — не вкус, а целочисленность:
//
//   1. ДЕЛЕНИЕ (paced) — там, где величина остаётся целой. Расход энергии
//      350 на десятикратном темпе становится 35, и это по-прежнему число.
//
//      ДЕЛИТЬ НАДО ПОСЛЕДНИМ, после всех прочих умножений. Правило дорогое:
//      скорость роста травы живёт в 2..25, и делённая ПЕРВОЙ она у половины
//      видов обращается в ноль — трава просто перестаёт расти, а диапазоны
//      при этом сходятся и никто не ругается. Помножь сначала на влагу
//      (до 25 000), подели потом — и величина цела. Так же с укусом и
//      расходом: сперва на размер тела, делить в самом конце.
//   2. СРОК (paceBeat) — там, где деление даёт ноль. Позыв к паре 1..10,
//      заживление 2, посев 1..50 на тысячу: десятая доля любого из них —
//      ноль, то есть "никогда". Вместо этого величина применяется целиком,
//      но раз в N тиков. Средняя скорость та же, целостность сохранена, а
//      состояния не нужно никакого — тот же приём, что у пищеварения
//      (kDungPeriod) и созревания ягод.
//
// Смещение по имени существа или номеру клетки обязательно: без него всё
// поголовье мира било бы в один и тот же тик — плодилось, заживало и
// сеялось строем.
inline constexpr int paced(int perTick, int pace) {
    return perTick * kFull / (pace > 0 ? pace : kFull);
}

// Тот ли это тик, в который медленная величина применяется целиком.
inline constexpr bool paceBeat(unsigned long long tick, unsigned long long offset, int pace) {
    const unsigned long long period = static_cast<unsigned long long>(pace > kFull ? pace : kFull) / kFull;
    return period <= 1 || (tick + offset) % period == 0;
}

// Тысячная прежней единицы высоты и глубины. Отдельное имя от kFull, хотя
// число то же: высота — не доля, у неё нет потолка, и совпадение чисел
// здесь случайно.
inline constexpr int kDepthUnit = 1000;

} // namespace goblins
