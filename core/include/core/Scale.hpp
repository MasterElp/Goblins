#pragma once

namespace goblins {

// Единицы, в которых измеряется состояние мира.
//
// В мире нет дробных величин. Не из вкуса к целым числам, а потому, что
// дробь в состоянии мира всегда тянет за собой второе поле — накопитель, в
// котором дробь дожидается, пока накопится до целого. Так в мире завелись
// mineralPending, proteinPending, dungPending, humus.pending: пять полей,
// не означавших ничего, кроме "0.004 за тик не помещается в штуку".
// Целая шкала убирает и дробь, и накопитель разом.
//
// Шкал ровно три, и все три — про одно и то же: сдвинуть запятую так,
// чтобы самая мелкая величина, которая в мире что-то значит, стала
// единицей.
//
// 1. Доли (всё, что раньше жило в [0, 1]) — в тысячных, kFull = 1000.
//    Развитость растения, здоровье, стресс, влажность, каменистость,
//    желания. Тысячная доля — предел того, что вообще различимо: на карте
//    в 512 тайлов её не видно, а в панели наблюдения она печатается как
//    третий знак после запятой, которого там и раньше не было.
//
// 2. Счётчики тела (энергия, вода, биомасса, мясо) — тоже в тысячных от
//    прежних единиц. Шкала выбрана не сама по себе, а из первого правила:
//    "сколько энергии в единице биомассы" должно быть целым, а биомасса
//    меряется той же тысячной шкалой, что и развитость растения.
//
// 3. Высота рельефа и глубина воды — в тысячных прежних единиц
//    (kDepthUnit). Река глубиной 0.9 стала рекой глубиной 900, гора
//    высотой 16 — горой высотой 16000.
//
// Времена (тики), расстояния (тайлы) и счётные вещи (крупицы минералов,
// крупицы белка) шкалы не имеют и не имели — они и так целые.
//
// --- Скорости ---
//
// Скорость в этом мире — это "сколько единиц за тик", и на целой шкале она
// почти всегда получается целой сама (0.012 развитости за тик — это 12
// тысячных за тик). Там, где не получается, есть два приёма, и оба
// обходятся без дробей:
//
//   - СРОК вместо скорости: "одна крупица раз в N тиков" (kDungPeriod,
//     humusDecayPeriod, waterEvaporationPeriod). Ничего копить не нужно
//     вовсе — событие происходит по остатку от деления номера тика.
//   - РАЗНОСТЬ ДВУХ ДЕЛЕНИЙ: величина, которая зависит только от возраста
//     (взросление животного), считается как разница между значением на
//     этом тике и на прошлом. Тоже без состояния.
//
// Накопитель остаётся ровно там, где скорость модулируется чем-то
// переменным и от возраста не выводится: рост растения (скорость * влага)
// и шаг животного (дробная скорость в целых клетках). Оба — целые остатки,
// а не дроби.

// Полная доля: 1000 тысячных. Всё, что раньше было "0..1", теперь
// "0..kFull".
inline constexpr int kFull = 1000;

// Тысячная прежней единицы высоты и глубины. Отдельное имя от kFull, хотя
// число то же: высота — не доля, у неё нет потолка, и совпадение чисел
// здесь случайно.
inline constexpr int kDepthUnit = 1000;

} // namespace goblins
