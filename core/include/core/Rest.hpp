#pragma once

#include <algorithm>

#include "core/Carcass.hpp"
#include "core/Scale.hpp"

namespace goblins {

// Насколько клетка годится, чтобы на ней лечь, — ОДИН закон мира на систему
// и на наблюдателя.
//
// Живёт здесь, а не внутри GoblinSystem, по той же причине, что и
// moistureTarget в core/Moisture.hpp: пользуются им уже двое — сама система
// (чтобы выбрать, куда идти отдыхать) и сервер (чтобы нарисовать эту
// пригодность на карте вокруг наблюдаемого гоблина). Карта, показывающая не
// ту пригодность, по которой гоблин принял решение, хуже карты, не
// показывающей ничего.
//
// Складывается закон из того, что в мире УЖЕ есть, и ни одна из его частей
// не заведена ради него: сухость почвы, тень дерева, камень под боком,
// лежащая рядом туша. Это осознанно — место должно становиться хорошим по
// причинам, которые в мире уже действуют, а не по признаку "здесь можно
// спать", выставленному кем-то заранее.
//
// Слагаемые перечислены списком, а не свёрнуты в одно выражение, и это тоже
// осознанно: на шаге "тропы" сюда добавится утоптанность, на шаге
// "постройки" — крыша над головой, и каждое должно добавляться одной
// строкой, не переписывая остального.

// Начальная годность любой клетки: лечь можно где угодно, вопрос лишь
// насколько хорошо. Ноль означал бы, что голая земля непригодна вовсе, —
// а она пригодна, просто плохо.
constexpr int kRestBase = 300;

// Сухость. Самое сильное слагаемое из природных: мокрая земля — худшее, что
// можно найти для лежания, и это то немногое, что различает клетки на
// ровном лугу. Вода на клетке сюда не входит отдельно — гоблин в воду и
// шагнуть не может (core/Path.hpp), такой клетки для него просто нет.
constexpr int kRestDryWeight = 400;

// Тень дерева. Крона уже служит укрытием охоте (kCoverSight,
// core/Hunting.hpp) — здесь она же служит и отдыху, и это не совпадение, а
// одно свойство: под деревом спокойнее.
//
// Одного этого слагаемого хватает, чтобы дурное место стало годным, и в
// этом смысл: роща должна притягивать. Первое место, к которому гоблины
// начнут возвращаться, скорее всего окажется опушкой.
constexpr int kRestShelter = 250;

// Камень под боком. Меньше сухости: на камнях неудобно, но не мокро.
constexpr int kRestRockPenalty = 300;

// Туша рядом. Вычитается сильно и до нуля: спать у падали не станет никто, а
// заодно это разводит места отдыха и места, где кого-то съели.
constexpr int kRestCarcassPenalty = 600;

// С какой годности гоблин считает клетку годной и ложится.
//
// Порог, а не поиск лучшего во всей округе, — по тому же правилу, по
// которому животное идёт к ближайшей еде, а не к лучшей: существо идёт к
// тому, что видит рядом и что ему подходит (02_CorePrinciples.md, п.6).
// Искать оптимум по всему кругу видимости значило бы знать округу целиком.
//
// Значение подобрано ЗАМЕРОМ по готовому миру, а не на глаз, и его смысл в
// том, сколько слагаемых закона вообще что-то решают.
//
// При 450 годными выходили 1.7% суши — и все до одной под деревьями: сухость
// и каменистость до порога не дотягивали никогда, через него переносила одна
// тень. Закон из пяти слагаемых означал на деле "отдыхать под деревом", а
// четыре из пяти были украшением.
//
// При 420 годны 4% суши, и половина из них — без дерева: решать начинают все
// слагаемые сразу. Сухая нескалистая поляна проходит сама, сырая или
// каменистая — только под кроной, и тень становится преимуществом, а не
// единственной причиной. Мест при этом по-прежнему мало: они редки и собраны
// в рощи и сухие проплешины, то есть к ним есть смысл возвращаться.
//
// Обе крайности рядом и обе плохи: годно всё — гоблин ложится где стоял и
// никуда не возвращается; не годно ничто — он бродит, не отдыхая никогда.
// Замер по карте 200x130: порог 380 даёт 12.5% суши, 400 — 7.5%, 420 — 4%,
// 450 — 1.7%, 500 — 0.9%.
constexpr int kRestGood = 420;

// Что известно о клетке для этого закона. Простые числа, а не ссылка на
// снимок мира: спрашивают их двое и берут по-разному — система из снимка
// тика, наблюдатель прямо из мира.
struct RestPlace {
    int moisture = 0;     // 0..kFull
    int rockiness = 0;    // 0..kFull
    bool tree = false;    // стоит ли на клетке дерево
    int carcassMeat = 0;  // мясо лежащей туши, шкала биомассы
};

// Годность клетки для отдыха, 0..kFull.
inline int restQualityOf(const RestPlace& place) {
    int quality = kRestBase;
    quality += (kFull - std::clamp(place.moisture, 0, kFull)) * kRestDryWeight / kFull;
    if (place.tree) {
        quality += kRestShelter;
    }
    quality -= std::clamp(place.rockiness, 0, kFull) * kRestRockPenalty / kFull;
    if (place.carcassMeat > 0) {
        // От доли целой туши: одна кость под боком мешает меньше, чем
        // свежий труп, но мешает.
        quality -= std::min(kRestCarcassPenalty, place.carcassMeat * kRestCarcassPenalty / kMeatPerSize);
    }
    return std::clamp(quality, 0, kFull);
}

} // namespace goblins
