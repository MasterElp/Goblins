#pragma once

#include <cstddef>
#include <cstdint>

namespace goblins {

// Спор за одну клетку — ОДИН закон мира на всех, кто может на неё
// претендовать.
//
// На один куст, одну тушу и один водопой могут прийти сразу несколько
// существ, и решать спор порядком обхода Entity нельзя (04_WorldModel.md,
// п.8): порядок в памяти не может быть причиной события в мире. Поэтому
// намерения собираются, а потом делятся долями — если желаемого меньше, чем
// просят, каждый получает свою часть, и исход не зависит ни от обхода, ни от
// того, кого EnTT хранит раньше.
//
// Живёт здесь, а не внутри системы, потому что вызывающих стало двое: за
// один и тот же куст могут прийти и стадо, и гоблины. Две копии этого закона
// разъехались бы молча, и трава начала бы кормить одних не так, как других.

// Намерение получить что-то с клетки: кто, сколько просит и под каким
// именем. Имя (постоянный идентификатор) нужно для сортировки: целые крупицы
// белка достаются по нему, а не по порядку в хранилище.
struct ShareIntent {
    std::size_t cell = 0;  // клетка с кустом, тушей или водой
    int claimant = 0;      // индекс в снимке существ этого тика
    std::uint64_t id = 0;  // постоянный идентификатор — им сортируем
    int want = 0;
};

inline bool sortByCellThenId(const ShareIntent& a, const ShareIntent& b) {
    if (a.cell != b.cell) {
        return a.cell < b.cell;
    }
    return a.id < b.id;
}

// Доля просящего от того, что на клетке ОСТАЛОСЬ.
//
// Зовётся по кругу, в порядке имён, и вызывающая сторона вычитает выданное:
// left — сколько ещё лежит на клетке, stillAsked — сколько ещё просят те, до
// кого очередь не дошла. Оттого раздача и выходит ровно на то, что было, —
// без остатка и без перебора.
//
// --- Почему по кругу, а не всем сразу, и почему ВВЕРХ ---
//
// Прежде доля считалась от полного наличия и округлялась вниз:
// want * available / demand. На тысячных это работало, а на штучном
// выродилось начисто. На кусте две ягоды, просящих трое, каждый просит две:
// 2 * 2 / 6 = НОЛЬ. Ноль всем, куст остаётся нетронутым — и трое голодных
// стоят на нём вечно, потому что еда под ногами, а взять её нельзя. Замер
// поймал такие стоянки по две-три тысячи тиков: гоблин "собирает ягоды", а
// счёт ягод не меняется ни на штуку.
//
// Округление вверх с вычитанием разрешает это без всяких порогов и особых
// случаев: первый по имени берёт единицу, второй — то, что осталось, третий
// не берёт ничего и на следующем тике уходит, потому что куст пуст. Целое
// достаётся кому-то одному, а не растворяется в нулях.
//
// Смещение в пользу меньшего имени здесь то же самое, что и у крупиц белка
// (см. выше), и по той же причине: делить неделимое всё равно приходится, а
// порядок имён — единственный порядок в этом мире, не зависящий от того, как
// вещи легли в памяти (02_CorePrinciples.md, п.12a).
//
// Промежуточное произведение — long long, потому что запрос на тысячи
// биомассы, умноженный на тысячи наличных, из int выходит.
inline int shareOf(int want, int left, int stillAsked) {
    if (want <= 0 || left <= 0 || stillAsked <= 0) {
        return 0;
    }
    const long long share = (static_cast<long long>(want) * left + stillAsked - 1) / stillAsked;
    const long long capped = share < want ? share : want;
    return static_cast<int>(capped < left ? capped : left);
}

} // namespace goblins
