#pragma once

#include <span>

namespace goblins {

// Как из нескольких желаний выбирается одно — ОДИН закон мира, общий для
// всех, у кого желания есть.
//
// Общий здесь именно закон, а НЕ перечень: у животного желаний пять
// (DesireComponent), у гоблина их станет вдвое больше, и единый на двоих
// список был бы враньём для обоих — животное носило бы значения, которых не
// может выбрать никогда. Поэтому наружу вынесено только правило выбора, а
// чем именно занято существо, каждый называет своими именами.
//
// Правило состоит из двух вещей, и обе несущие:
//
//   Порог (floor). Ниже него желание никуда не гонит: существо считается
//   довольным и просто бродит. Без порога любое, сколь угодно слабое
//   желание всё равно куда-нибудь вело бы, и покоя в мире не было бы вовсе.
//
//   Инерция (switchGap). Насколько сильнее должно быть другое желание, чтобы
//   перебить уже выбранное. Это часть закона, а не сглаживание картинки:
//   животное с почти равными голодом и жаждой каждый тик разворачивалось бы
//   и не дошло бы ни до травы, ни до воды.
//
// Порядок кандидатов в списке — и есть приоритет при равенстве: сравнение
// нестрогое, поэтому побеждает ПОСЛЕДНИЙ из равных. У животного страх стоит
// в списке последним, и это не мелочь оформления, а закон: сытость
// подождёт, зубы — нет.
struct Urgency {
    // Чем занято существо, числом. Свой enum каждый приводит к int сам:
    // общий закон не должен знать ни одного имени желания.
    int tag = 0;
    // Насколько гонит, 0..kFull.
    int value = 0;
};

// Какое желание сейчас гонит существо. currentTag/currentUrgency — то, чем
// оно занято сейчас и насколько это его гонит; idleTag — чем оно занято,
// когда не гонит ничто.
inline int chooseUrgent(std::span<const Urgency> candidates, int currentTag, int currentUrgency, int floor,
                        int switchGap, int idleTag) {
    int best = idleTag;
    int bestUrgency = floor;
    for (const Urgency& candidate : candidates) {
        if (candidate.value >= bestUrgency) {
            best = candidate.tag;
            bestUrgency = candidate.value;
        }
    }

    // Уже выбранное держится, пока новое не перевесит его с запасом. Само
    // текущее желание при этом обязано ещё быть выше порога: иначе существо
    // держалось бы за то, что давно перестало его гнать.
    if (currentTag != idleTag && currentUrgency >= floor && bestUrgency < currentUrgency + switchGap) {
        return currentTag;
    }
    return best;
}

} // namespace goblins
