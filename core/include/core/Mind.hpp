namespace goblins {

// РАЗУМ — то единственное в этом коде, что не является законом мира.
//
// 02_CorePrinciples.md, п.6 говорит об этом прямо: "ИИ не является частью
// мира", "Мир не зависит от реализации ИИ", и перечисляет, что обязано
// заменяться программно — долгосрочное планирование, постановка целей,
// память. До этого файла ни одного такого шва в коде не было: решения были
// размазаны по системам, и заменить разум было негде.
//
// --- У разума одна операция, и в этом весь замысел ---
//
// Постановка цели и выбор цели — ОДИН И ТОТ ЖЕ ВОПРОС. Что сейчас важнее,
// куда идти за травой, кого выбрать в пару, с кем заговорить, какую добычу
// взять — всюду мир считает варианты и их вес (расстояние, тепло, размер,
// число соседей, срочность), а решение состоит в том, чтобы взять ОДИН ИЗ
// ВЗВЕШЕННЫХ.
//
// Поэтому здесь нет ни одного имени желания, ни одного вида существа и ни
// одной величины мира. Мир кладёт варианты — разум берёт один. Больше между
// ними не проходит ничего, и оттого п.6 держится сам собой: разум физически
// не может знать того, чего ему не положили.
//
// --- Что осталось миру, а что ушло разуму ---
//
// Миру: чего существо хочет и насколько сильно (это считают законы тела,
// страха, памяти), и какие варианты оно вообще видит.
//
// Разуму: порог, инерция, паника и сам выбор. Всё, что раньше называлось
// "арбитражем желаний", — устройство разума, а не закон мира. Изъятий нет
// намеренно, и плата названа прямо: другой разум вправе оставить гоблина
// есть под волком, и мир его не остановит. Это цена того, чтобы разум
// действительно можно было заменить, а не заменить наполовину.
//
// --- Что разуму НЕ отдано, и почему ---
//
// Шаг ногой (chooseStep, core/Walk.hpp). Так определяет себя он сам — "куда
// животное ставит ногу, когда уже решило, в какую сторону ему надо".
// Направление приходит снаружи; восемь слагаемых шага — исполнение, а не
// выбор.
//
// Очерёдность падали перед погоней (chooseHuntTarget, core/Hunting.hpp).
// Разум выбирает, КАКУЮ тушу и КАКУЮ добычу, но что доесть важнее, чем
// погнаться, решает мир: "сначала доешь" записано замером, а не вкусом.
//
// Чтение памяти (recall, core/Knowledge.hpp). Оно отвечает "что помнится
// отсюда", а не "куда идти"; идти решает вызывающий. Память же целиком
// относится к разуму (02_CorePrinciples.md, п.6) и переедет к нему вместе с
// самим хранением — отдельной работой.
//
// Годность и запреты: кто кому по зубам, куда можно поставить ногу, кто
// ровня. Это не предпочтения, а условия, и очками они не выражаются —
// когда вся округа не по зубам, лучшая из плохих всё равно оказалась бы
// выбрана, а такой выбор не "рискнул", а "пошёл умирать".
//
// --- Чем этот список НЕ является ---
//
// Он не про то, что "здесь жадный разум ведёт себя хуже". Тема разговора
// (chooseTopic, core/Talk.hpp) сперва была оставлена миру именно по такому
// доводу — там стоял свой жребий по склонностям с объяснением, что жадный
// выбор обесценил бы половину нрава. Довод был верен и не имел отношения к
// делу: он говорил не о мире, а о РАЗУМЕ. Зашитое правило выбора, оставленное
// в законе мира ради того, что при одном из разумов выйдет некрасиво, — это
// второй, потайной разум рядом с настоящим, и стоит он ровно там, где его
// труднее всего заметить.
//
// Мерка для этого списка одна: попадает сюда то, что перестаёт быть ПРАВДОЙ
// О МИРЕ, если решить иначе. Мёртвый не ест — правда. Через реку не пройти —
// правда. "О чём я скорее заговорю" правдой о мире не является ни в каком
// смысле.

// Один вариант, каким его кладёт мир.
struct Option {
    // Чем это назвать. Желание, номер добычи, что угодно: разум не смотрит
    // внутрь и приводит обратно тем же числом.
    int tag = 0;
    // Где это, если у варианта есть место. Для выбора занятия — не значит
    // ничего.
    int x = 0;
    int y = 0;
    // Насколько это хорошо. Считает МИР, и только он.
    //
    // Веса сравнимы ТОЛЬКО ВНУТРИ ОДНОГО ВЫБОРА. Расстояние до куста, тепло
    // знакомства и срочность голода приведены к общей шкале каждый в своём
    // законе и для своего вопроса; складывать их между собой нельзя, и
    // сказано это здесь потому, что однажды сложат.
    int weight = 0;
    // Старшинство: кто побеждает при РАВНОМ весе. Больше — старше.
    //
    // Заведено потому, что один разум обслуживает два разных вида выбора.
    // В списке желаний порядок значит приоритет ("сытость подождёт, зубы —
    // нет"), и его надо сохранить. В переборе клеток порядок не значит
    // ничего: он идёт с левого верхнего угла, и победа "последнего из
    // равных" увела бы всех дружно вниз и вправо. Порядок в памяти не может
    // быть причиной события в мире (02_CorePrinciples.md, п.12a).
    //
    // Поэтому приоритет назван числом, а не местом в списке: у желаний он
    // свой у каждого, у клеток — общий ноль, и там связку разрывает жребий.
    int rank = 0;
    // Это то, чем существо занято сейчас. Нужно инерции: начатое дело стоит
    // дороже нового при прочих равных.
    bool current = false;
    // Выше этой величины вариант не спорит ни с кем; 0 — спорит наравне.
    //
    // Заведено под страх и ни подо что другое. Причина не в силе, а в том,
    // что величины значат разное: голод 800 — это "не ел полдня", страх 800
    // — это "зубы в трёх шагах". Пока зубы далеко, сравнивать можно;
    // вплотную — уже нет, и уступает голод не потому, что слабее, а потому,
    // что мёртвому есть нечем.
    //
    // Полем варианта, а не настройкой разума: так разум не знает даже того,
    // какое желание бывает паническим. Мир помечает — разум читает.
    int panic = 0;
};

// Что разум выбрал. made == false — не выбрано ничего: ни один вариант не
// дотянул до порога. Что делать в этом случае, решает вызывающий (у существ
// это безделье), и разум об этом не знает.
struct Choice {
    bool made = false;
    int tag = 0;
    int x = 0;
    int y = 0;
};

// Чем разум настроен. Числа свои у каждого, кто думает: у зверя и у гоблина
// они намеренно разные, и общим остаётся закон, а не значения.
struct Temper {
    // Ниже этого вариант не рассматривается вовсе. Без порога любой, сколь
    // угодно слабый вариант всё равно куда-нибудь вёл бы, и покоя в мире не
    // было бы.
    int floor = 0;
    // Насколько новое должно перевесить начатое, чтобы его сменили. Без
    // этого существо с почти равными голодом и жаждой разворачивалось бы
    // каждый тик и не дошло бы ни до травы, ни до воды.
    int hold = 0;
};

// Какой разум думает. Значение мира (WorldPropertiesComponent), а не сборки,
// и это несущее: наблюдатель обязан рисовать решение ТОГО ЖЕ разума, каким
// его принял зверь, — иначе панель покажет дорогу, по которой никто не идёт.
// Заодно из этого само собой выходит сравнение A/B на одном бинарнике,
// которого проект требует от всякой правки.
enum class Mind : std::uint8_t {
    // Наибольший вес; при равном весе — старший (Option::rank), при равном
    // старшинстве — жребий. Ровно то, чем мир жил до появления этого файла:
    // прежде старшинство выражалось местом в списке, а жребий жил отдельно,
    // внутри перебора клеток.
    //
    // Держится он не ради совместимости, а ради сравнения: без него нечем
    // сказать, что другой разум что-то изменил.
    Greedy = 0,
    // Жребий по весам, и вес идёт В КВАДРАТЕ. Вдвое лучший вариант
    // выигрывает вчетверо чаще: сильное желание остаётся сильным, но
    // перестаёт быть единственным.
    //
    // Прямая пропорция была бы слишком ровной — существо с голодом 400 и
    // жаждой 380 ходило бы туда-сюда почти поровну. Квадрат оставляет разницу
    // заметной, а исход — не предрешённым. Ровно этого и не было: при
    // Greedy вариант с весом 999 проигрывает варианту с весом 1000 всегда и
    // навсегда, сколько бы тиков мир ни прожил.
    Lottery = 1,
};

inline const char* mindName(Mind mind) {
    switch (mind) {
        case Mind::Lottery: return "lottery";
        case Mind::Greedy: break;
    }
    return "greedy";
}

inline Mind mindFromName(const std::string& name) {
    return name == "lottery" ? Mind::Lottery : Mind::Greedy;
}

namespace detail {

// Зубы вплотную — не предмет обсуждения ни для одного разума здесь. Оба
// спрашивают об этом первыми и одинаково.
//
// Это РЕШЕНИЕ ОБОИХ РАЗУМОВ, а не закон мира: третий волен решить иначе, и
// мир его не остановит (см. шапку). Вынесено сюда, чтобы два разума не
// разошлись в этом молча.
inline Choice panicking(std::span<const Option> options) {
    for (const Option& option : options) {
        if (option.panic > 0 && option.weight >= option.panic) {
            return Choice{true, option.tag, option.x, option.y};
        }
    }
    return Choice{};
}

} // namespace detail

// Что выбрать. random меняется — розыгрыш тратит состояние; разум, которому
// жребий не нужен, его не трогает.
inline Choice decide(Mind mind, std::span<const Option> options, Temper temper, std::uint64_t& random) {
    if (const Choice panic = detail::panicking(options); panic.made) {
        return panic;
    }

    // Начатое дело — чтобы инерция знала, что именно держать. Ищется до
    // выбора: оба разума спрашивают о нём, просто по-разному.
    const Option* held = nullptr;
    for (const Option& option : options) {
        if (option.current) {
            held = &option;
            break;
        }
    }

    if (mind == Mind::Lottery) {
        // Вес в квадрате, и начатому прибавляется инерция ДО возведения:
        // прибавка к весу, а не к вероятности, — иначе она значила бы разное
        // при разных весах.
        //
        // Квадрат считается в 64 битах не из осторожности, а по нужде: вес
        // доходит до kFull, квадрат — до миллиона, и десяток вариантов
        // переполнил бы int на второй строке.
        std::uint64_t total = 0;
        for (const Option& option : options) {
            if (option.weight < temper.floor) {
                continue;
            }
            const std::uint64_t bid = static_cast<std::uint64_t>(option.weight) +
                                       (option.current ? static_cast<std::uint64_t>(temper.hold) : 0ull);
            total += bid * bid;
        }
        if (total == 0) {
            return Choice{};
        }
        std::uint64_t roll = randomBelow(random, total);
        for (const Option& option : options) {
            if (option.weight < temper.floor) {
                continue;
            }
            const std::uint64_t bid = static_cast<std::uint64_t>(option.weight) +
                                       (option.current ? static_cast<std::uint64_t>(temper.hold) : 0ull);
            const std::uint64_t share = bid * bid;
            if (roll < share) {
                return Choice{true, option.tag, option.x, option.y};
            }
            roll -= share;
        }
        // Сюда не приходят: доли складывались в total тем же обходом.
        return Choice{};
    }

    // Вес решает; при равном весе — старшинство; при равном старшинстве —
    // жребий. Третья ступень нужна ровно затем, чтобы порядок обхода не
    // решал ничего: клетки перебираются с угла, и без жребия все шли бы в
    // один и тот же угол.
    //
    // Жребий здесь честный: из n равных каждый берётся с вероятностью 1/n
    // (тот же приём, что был в findNearest, — заменить найденное с
    // вероятностью 1/ties).
    const Option* best = nullptr;
    int bestWeight = temper.floor;
    int bestRank = 0;
    std::uint64_t ties = 0;
    for (const Option& option : options) {
        if (option.weight < bestWeight) {
            continue;
        }
        if (best != nullptr && option.weight == bestWeight) {
            if (option.rank < bestRank) {
                continue;
            }
            if (option.rank == bestRank) {
                ++ties;
                if (randomBelow(random, ties) != 0) {
                    continue;
                }
                best = &option;
                continue;
            }
        }
        best = &option;
        bestWeight = option.weight;
        bestRank = option.rank;
        ties = 1;
    }
    if (best == nullptr) {
        return Choice{};
    }

    // Начатое держится, пока новое не перевесит с запасом. Само оно при этом
    // обязано ещё быть выше порога: иначе существо держалось бы за то, что
    // давно перестало его гнать.
    //
    // Запаса не ждёт помеченное паникой: инерция бережёт начатое дело от
    // метаний, а не от зубов.
    if (held != nullptr && held->weight >= temper.floor && bestWeight < held->weight + temper.hold &&
        best->panic == 0) {
        return Choice{true, held->tag, held->x, held->y};
    }
    return Choice{true, best->tag, best->x, best->y};
}

} // namespace goblins
