#pragma once

#include <cstdint>

namespace goblins {

// Случайность мира — общий приём, а не деталь какой-то одной системы.
//
// Система не имеет права хранить состояние между тиками (05_Entity.md,
// п.3), поэтому собственного генератора у неё быть не может. Вместо него
// случайность каждый раз собирается заново из чисел, которые и так есть в
// мире: seed мира, номер тика, координаты клетки, чем-нибудь ещё, что
// отличает один розыгрыш от другого. Отсюда её и раскручивают.
//
// Из этого НЕ следует, что мир воспроизводим: одинаковый seed не обязан
// давать одинаковый мир (02_CorePrinciples.md, п.12a) — мир открыт и
// недетерминирован, и seed здесь всего лишь удобная точка отсчёта, а не
// обещание повторить прошлый прогон. Приём выбран не ради повторяемости,
// а ради того, чтобы системе не приходилось ничего помнить.
//
// Живёт в core/, а не рядом с растениями или водой: этим пользуются и
// генерация (виды, первые семена, расстановка), и системы (посев, дождь).

// splitmix64: следующее состояние и очередное число из него. Дешёвый и не
// требует ничего, кроме самого state.
inline std::uint64_t nextState(std::uint64_t& state) {
    state += 0x9E3779B97F4A7C15ull;
    std::uint64_t z = state;
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
    return z ^ (z >> 31);
}

// Смешать два числа в одно — так из "seed мира" и "номера тика" (или
// координат клетки) получается отправная точка для розыгрыша.
inline std::uint64_t mixSeed(std::uint64_t a, std::uint64_t b) {
    std::uint64_t state = a ^ (b * 0x9E3779B97F4A7C15ull);
    return nextState(state);
}

// Следующее случайное число в [0, 1) от состояния state (state меняется).
// Остаётся для генерации, где счёт идёт в дробных числах по существу
// (геометрия русла, расклады бюджета черт). Состояние мира дробным больше
// не бывает — там нужен randomBelow ниже.
inline float randomUnit(std::uint64_t& state) {
    // 24 старших бита -> [0, 1): float всё равно не различает больше.
    return static_cast<float>(nextState(state) >> 40) * (1.0f / 16777216.0f);
}

// Следующее случайное целое в [0, bound) — розыгрыш для мира, где все
// величины целые (core/Scale.hpp). Через остаток от деления, а не через
// долю: доля потребовала бы округления обратно в целое, то есть тех самых
// дробей, от которых мир и избавлен.
//
// Перекос от остатка (последний неполный блок 2^64 чуть вероятнее) меньше
// 2^-40 при любом разумном bound — на порядки меньше всего, что в этом
// мире вообще различимо.
inline std::uint64_t randomBelow(std::uint64_t& state, std::uint64_t bound) {
    return bound == 0 ? 0 : nextState(state) % bound;
}

} // namespace goblins
