namespace goblins {

// Жизнь гоблинов: кормление, водопой, ходьба, продолжение рода и смерть.
// Идёт в GameLoop последней — после AnimalSystem (см. core/Simulation.cpp):
// гоблин ходит по миру, уже прожившему тик, и видит траву такой, какой её
// оставило стадо, а падаль — такой, какой её оставили хищники.
//
// Система отдельная, хотя тело у гоблина то же самое, что у зверя. Причина
// не в теле, а в том, откуда берутся решения. У животного они выводятся из
// тела и из того, что видно вокруг, и больше ниоткуда — оно не может хотеть
// того, о чём не знает (02_CorePrinciples.md, п.6). У гоблина к этому
// добавится память мест, повторяющиеся маршруты, ноша, работа, постройки и
// связи с другими; ни для чего из этого внутри AnimalSystem места нет, и
// появись оно там — вышли бы два разных существа, считаемые одной функцией.
//
// Всё, что у гоблина и зверя действительно общее, вынесено и вызывается
// обоими:
//   core/Body.hpp      — расход, взросление, пищеварение, здоровье;
//   core/Carcass.hpp   — смерть и падаль;
//   core/Needs.hpp     — голод и жажда из тела;
//   core/Desires.hpp   — порог и инерция выбора желания;
//   core/Share.hpp     — дележ одной клетки между несколькими едоками;
//   core/Walk.hpp      — шаг, инерция, память ног;
//   core/Path.hpp      — дорога волной в пределах видимости;
//   core/Mating.hpp    — встреча, зов, выбор пары;
//   core/TileSnapshot.hpp — что лежит на клетках.
// Здесь остаётся только гоблинское.
//
// Один тик для одного гоблина:
//   1. Тело — общим законом (advanceBody). Болезни от тесноты у него нет:
//      она про скученность сородичей, а поселение тесно по самой своей сути.
//   2. Желания: голод и жажда из тела, желание пары копится у сытого
//      взрослого. Из них выбирается одно, с порогом и инерцией.
//   3. Действие: гоблин всеяден — ест и траву, и падаль. Мясо под ногами
//      съедается раньше травы под ногами: туша это десяток кустов разом
//      (kMeatPerSize). Пьёт со своей или соседней клетки. С парой сходится
//      на своей.
//   4. Шаг, если желаемого рядом нет. За редкой находкой — падалью и парой —
//      идут дорогой (core/Path.hpp): увиденное через реку ещё не найдено. За
//      травой и за водой идут напрямик и обходят преграду вслепую — их в
//      мире много, и упереться в берег ради одного конкретного куста
//      незачем.
//   5. Смерть — от старости или от истощения. Чужих зубов в этом списке
//      пока нет: хищник гоблина не видит (см. AnimalSystem, список preys).
//      Это временно и снимается одной строкой; сейчас важнее посмотреть,
//      удержат ли гоблины численность своими решениями, а не чужими.
//
// Кто с кем поспорил за один куст, одну тушу или один водопой, решается не
// порядком обхода Entity (04_WorldModel.md, п.8), а долями (core/Share.hpp).
// Спорить при этом можно и со стадом — но не в один тик: стадо ело раньше,
// и гоблин видит то, что от куста осталось.
void GoblinSystem(World& world, CommandQueue& commands);

} // namespace goblins
