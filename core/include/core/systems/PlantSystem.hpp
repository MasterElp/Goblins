namespace goblins {

// Жизнь растений: питание из своей клетки, рост, размножение в соседнюю
// клетку, смерть и разложение перегноя. Идёт в GameLoop после
// HydrologySystem (см. server/main.cpp) — растение должно видеть почву
// уже в том состоянии, в которое её привела вода на этом тике, а не в
// прошлом.
//
// Один тик для одного растения:
//   1. Пригодность клетки (habitatFit по каменистости/утоптанности).
//   2. Влага: забирает долю влажности своей клетки в собственный запас,
//      клетка от этого сохнет; расход на рост идёт из запаса — поэтому
//      засуху растение какое-то время переживает, а потом начинает
//      страдать.
//   3. Минералы: целые крупицы уходят из SoilComponent клетки в растение,
//      не больше mineralNeed за всю жизнь; накопленное ограничивает
//      предельный размер.
//   4. Рост: скорость * пригодность клетки * обеспеченность влагой, но не
//      выше того, что позволяют накопленные минералы.
//   5. Стресс: копится, когда расти нечем (нет влаги, чужая почва) или
//      клетку залило водой; при 1 растение погибает. Смерть от старости —
//      отдельно, по maxAge.
//   6. Размножение: созревшее и достаточно выросшее растение с
//      вероятностью seedChance роняет одно семя в одну из соседних клеток
//      (свободную, без воды, подходящую потомку) и платит за это своим
//      ростом и крупицей минералов.
//   7. Смерть: Entity растения исчезает, а накопленные им минералы
//      остаются на тайле перегноем (HumusComponent) и возвращаются в
//      почву по humusDecayRate за тик.
//
// Минералы в этой цепочке не создаются и не пропадают: почва -> растение
// -> перегной -> почва. Влага — не запас, а состояние почвы, которое
// восстанавливает HydrologySystem, поэтому потраченная на рост влага
// просто исчезает (растение её испарило), а не должна куда-то вернуться.
void PlantSystem(World& world, CommandQueue& commands);

} // namespace goblins
