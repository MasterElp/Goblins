namespace goblins {

// Жизнь растений: питание из своей клетки, рост, размножение в соседнюю
// клетку, смерть и разложение перегноя. Идёт в GameLoop после
// HydrologySystem (см. server/main.cpp) — растение должно видеть почву
// уже в том состоянии, в которое её привела вода на этом тике, а не в
// прошлом.
//
// Один тик для одного растения:
//   1. Обеспеченность влагой: влажность своей клетки против того, сколько
//      её нужно этому геному (moistureNeed). Своего запаса влаги у
//      растения нет — засуху переживает не тот, кто накопил, а тот, кому
//      нужно меньше. Растущий куст сушит клетку под собой.
//   2. Минералы: целые крупицы уходят из SoilComponent клетки в растение
//      тогда, когда в них упёрся рост, не больше mineralNeed за всю
//      жизнь; накопленное ограничивает предельный размер.
//   3. Рост: скорость * обеспеченность влагой, но не выше того, что
//      позволяют накопленные минералы.
//   4. Стресс: копится, когда расти нечем (нет влаги) или
//      клетку залило водой; при 1 растение погибает. Смерть от старости —
//      отдельно, по maxAge.
//   5. Размножение: созревшее и достаточно выросшее растение с
//      вероятностью seedChance роняет одно семя в одну из соседних клеток
//      (свободную, без воды, достаточно влажную для потомка) и платит за
//      это своим ростом и крупицей минералов.
//   6. Смерть: Entity растения исчезает, а накопленные им минералы
//      остаются на тайле перегноем (HumusComponent) и возвращаются в
//      почву по одной крупице раз в humusDecayPeriod тиков.
//
// Минералы в этой цепочке не создаются и не пропадают: почва -> растение
// -> перегной -> почва. Влага — не запас, а состояние почвы, которое
// восстанавливает HydrologySystem, поэтому потраченная на рост влага
// просто исчезает (растение её испарило), а не должна куда-то вернуться.
void PlantSystem(World& world, CommandQueue& commands);

} // namespace goblins
