namespace goblins {

// Работа — универсальная единица труда (02_CorePrinciples.md, п.11).
//
// Тик работы одного существа есть ОДНА единица. Дело стоит своего числа
// единиц, и больше в этом законе ничего нет: он не знает ни кто работает, ни
// над чем, ни зачем. Оттого им и смогут пользоваться постройка сегодня,
// добыча и починка завтра.
//
// Из того, что единица привязана к тику одного существа, следует и
// совместный труд: двое кладут в одно и то же дело по единице за тик и
// делают его вдвое быстрее. Никакого "нескольких исполнителей" отдельно
// писать не нужно — оно уже здесь.
//
// Умения (шаг 8) придут сюда одной строкой: п.11 говорит, что умелый
// выполняет дело за меньшее число работ, то есть удешевляет ЦЕНУ, а не
// ускоряет тик. Место для этого — workCost ниже.

// Во сколько единиц труда обходится полная прочность постройки.
//
// Подстилка — дело сотни тиков: набрать травы рядом и разложить. Навес впятеро
// дороже: это уже стройка, ради которой ходят за ветками и возвращаются не
// один раз. При жизни в несколько тысяч тиков навес —
// заметное вложение, но не подвиг всей жизни, и его успевает поставить даже
// одиночка.
// Числа выбраны так, чтобы kFull делился на них НАЦЕЛО: подстилка растёт на
// десять прочности за работу, навес — на две. Дробной единицы труда в мире
// нет, и неделящийся остаток хранить негде и незачем (core/Scale.hpp: дробь
// всегда тянет за собой накопитель — проще избавиться от дроби).
constexpr int kWorkBedding = 100;
constexpr int kWorkCanopy = 500;

// Цена дела для конкретного исполнителя. Пока умений нет, она равна
// объявленной; когда появятся, здесь и появится их скидка — в одном месте на
// все дела мира, а не в каждом деле по-своему.
inline int workCost(int base, int skill = 0) {
    (void)skill;
    return base;
}

} // namespace goblins
