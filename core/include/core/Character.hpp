#include <algorithm>

#include "core/Scale.hpp"
#include "core/components/CharacterComponent.hpp"
#include "core/components/KnowledgeComponent.hpp"

namespace goblins {

// Что нрав делает — ОДИН закон на систему и на наблюдателя.
//
// Живёт здесь, а не внутри GoblinSystem, по той же причине, что core/Rest.hpp
// и core/Knowledge.hpp: пользуются им уже двое. Система — чтобы решить, за
// что гоблин возьмётся; сервер — чтобы показать в панели наблюдения ТО ЖЕ
// САМОЕ число, по которому он это решил. Показанный позыв, не совпадающий с
// тем, по которому принято решение, хуже непоказанного: по нему нельзя
// понять, почему гоблин стоит, когда рядом недостроенный навес.
//
// Закон принимает простые числа и ничего не знает ни про гоблина, ни про
// зверя (docs/10_Goblins.md, п.1a).

// Тема с местом на карте или без него.
//
// Мост между двумя перечислениями, а не третье перечисление: темы разговора о
// местах намеренно не завели своих имён, иначе "еда" в теме и "еда" в памяти
// разъехались бы, и однажды гоблин рассказывал бы о еде, а слушатель
// запоминал бы это водопоем.
inline PlaceKind placeOf(Topic topic) {
    switch (topic) {
        case Topic::Food: return PlaceKind::Food;
        case Topic::Water: return PlaceKind::Water;
        case Topic::Home: return PlaceKind::Rest;
        case Topic::Work: return PlaceKind::Work;
        // Родня и болтовня ни о чём места не имеют — и это не пробел, а вся
        // разница между разговором, который что-то сообщает, и разговором,
        // который только греет.
        case Topic::Kin:
        case Topic::Idle: break;
    }
    return PlaceKind::None;
}

// Насколько трудолюбие раздвигает позыв к работе в обе стороны от общего для
// всех основания.
//
// Триста — не осторожная величина, и намеренно. Позывы отнести и построить
// стоят 400 при пороге желания 350 (kDesireFloor, Temper::floor в
// core/Mind.hpp): при
// меньшем размахе ленивый всё равно оставался бы выше порога и работал, просто
// чуть реже, — то есть трудолюбие было бы оттенком, а не чертой. При трёхстах
// ленивый (нрав 0) проваливается к 100 и за работу не берётся вовсе, пока его
// не погонит что-то другое, а трудолюбивый (нрав kFull) держит 700 и бросает
// дело только ради еды и воды. Разницу видно на карте, а не в панели: одни
// таскают, другие слоняются.
inline constexpr int kDiligenceSwing = 300;

// Насколько склонность двигает отдельное занятие. Вдвое меньше трудолюбия, и
// это то самое, что не даёт двум числам означать одно.
//
// Трудолюбие — уровень (работать или бездельничать), склонность —
// направление (собирать или строить). Сравняй их — и увлечённый лентяй
// работал бы наравне с равнодушным трудягой, то есть по поведению их стало
// бы не отличить, и одно из двух чисел оказалось бы лишним. Оставь
// склонность совсем малой — и она не решала бы ничего при равном трудолюбии,
// то есть лишним оказалось бы другое.
inline constexpr int kInterestSwing = 150;

// Черта нрава как сдвиг: середина шкалы ничего не меняет, края двигают на
// swing в обе стороны. Знаковый результат — складывать его с основанием
// приходится и вверх, и вниз.
//
// Умножение раньше деления (core/Scale.hpp): при swing = 300 и шаге нрава в
// одну тысячную обратный порядок дал бы ноль на любом нраве.
inline constexpr int traitShift(int trait, int swing) {
    return (2 * std::clamp(trait, 0, kFull) - kFull) * swing / kFull;
}

// Позыв к работе с поправкой на трудолюбие. base — то, чего работа стоила бы
// гоблину без нрава (kHaulUrge, kBuildUrge в GoblinSystem).
inline int workUrge(int base, int diligent) {
    return std::clamp(base + traitShift(diligent, kDiligenceSwing), 0, kFull);
}

// То же самое, но склонностью к теме: чем занять руки при равном трудолюбии.
inline int interestUrge(int base, int interest) {
    return std::clamp(base + traitShift(interest, kInterestSwing), 0, kFull);
}

// Насколько за один удар пульса (paceBeat, core/Scale.hpp) подрастает желание
// поговорить. base — скорость у среднего гоблина, свойство мира
// (WorldPropertiesComponent::goblinTalkUrge).
//
// Не сдвиг, а доля, в отличие от трудолюбия: молчун обязан молчать
// по-настоящему, а сдвиг оставил бы ему медленное, но неотвратимое
// накопление — рано или поздно заговорил бы и он, просто раз в полжизни.
// Доля же даёт настоящий ноль: нрав 0 — гоблин не заговаривает первым
// никогда. Ею же выключаются разговоры во всём мире разом (base = 0), и
// это вторая половина машинной сверки A/B.
inline int talkStep(int base, int sociable) {
    return std::max(0, base) * std::clamp(sociable, 0, kFull) / kFull;
}

// Склонность к теме. Отдельной функцией, а не обращением к массиву на месте:
// перечисление и массив связаны только порядком значений, и связывать их
// заново в каждом вызывающем месте — верный способ однажды промахнуться на
// единицу.
inline int interestIn(const CharacterComponent& character, Topic topic) {
    const auto slot = static_cast<std::size_t>(topic);
    return slot < character.interest.size() ? std::clamp(character.interest[slot], 0, kFull) : 0;
}

} // namespace goblins
